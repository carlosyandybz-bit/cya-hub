create or replace function private.credit_grant_balance_minutes_unchecked(
  p_grant_id bigint
)
returns integer
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce(sum(cm.delta_minutes),0)::integer
  from public.credit_movements cm
  where cm.grant_id=p_grant_id;
$$;

create or replace function private.credit_grant_effective_expires_at_unchecked(
  p_grant_id bigint,
  p_at timestamptz default now()
)
returns timestamptz
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_expiry timestamptz;
  v_pause record;
  v_pause_end timestamptz;
begin
  select g.expires_at into v_expiry
  from public.credit_grants g
  where g.id=p_grant_id;

  if not found or v_expiry is null then
    return v_expiry;
  end if;

  for v_pause in
    select pp.paused_at,pp.resumed_at
    from public.credit_grant_pause_periods pp
    where pp.grant_id=p_grant_id
      and pp.paused_at<p_at
    order by pp.paused_at,pp.id
  loop
    if v_pause.paused_at>=v_expiry then
      continue;
    end if;

    v_pause_end:=least(coalesce(v_pause.resumed_at,p_at),p_at);
    if v_pause_end>v_pause.paused_at then
      v_expiry:=v_expiry+(v_pause_end-v_pause.paused_at);
    end if;
  end loop;

  return v_expiry;
end;
$$;

create or replace function private.credit_grant_is_paused_unchecked(
  p_grant_id bigint,
  p_at timestamptz default now()
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists(
    select 1
    from public.credit_grant_pause_periods pp
    where pp.grant_id=p_grant_id
      and pp.paused_at<=p_at
      and (pp.resumed_at is null or pp.resumed_at>p_at)
  );
$$;

