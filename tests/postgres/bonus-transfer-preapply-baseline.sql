create or replace function qa_transfer.seed_source(
  p_grant_id bigint,
  p_person_id bigint,
  p_minutes integer,
  p_payment_status text default 'paid',
  p_starts_at timestamptz default now(),
  p_expires_at timestamptz default null
)
returns void
language plpgsql
set search_path = ''
as $$
begin
  insert into public.credit_grants(
    id,modality,label,total_minutes,price_cents,payment_status,status,
    purchased_at,expires_at,created_by,starts_at,purchased_at_approximate,historical_provenance
  )
  values(
    p_grant_id,'individual','QA source '||p_grant_id::text,p_minutes,10000,
    p_payment_status,'active',now(),p_expires_at,(select auth.uid()),p_starts_at,false,'qa-disposable'
  );

  insert into public.credit_grant_members(grant_id,person_id)
  values(p_grant_id,p_person_id);

  insert into public.credit_movements(
    grant_id,person_id,movement_type,delta_minutes,note,created_by,provenance
  )
  values(
    p_grant_id,p_person_id,'grant',p_minutes,'QA disposable seed',
    (select auth.uid()),jsonb_build_object('qa','bonus-transfer-preapply')
  );
end;
$$;

create or replace function qa_transfer.assert_eq(
  p_actual bigint,
  p_expected bigint,
  p_label text
)
returns void
language plpgsql
set search_path = ''
as $fn$
begin
  if p_actual is distinct from p_expected then
    raise exception 'QA_ASSERT_EQ failed: %, actual %, expected %',
      p_label,p_actual,p_expected;
  end if;
end;
$fn$;


