create table public.credit_grants (
  id bigint generated by default as identity primary key,
  modality text not null check (modality in ('individual','pair')),
  label text,
  total_minutes integer not null check (total_minutes > 0 and total_minutes <= 100000),
  price_cents integer not null default 0 check (price_cents >= 0),
  payment_status text not null default 'paid'
    check (payment_status in ('paid','pending','refunded')),
  status text not null default 'active'
    check (status in ('active','exhausted','cancelled')),
  purchased_at timestamptz not null default now(),
  expires_at timestamptz,
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  starts_at timestamptz not null default now(),
  purchased_at_approximate boolean not null default false,
  historical_provenance text,
  constraint credit_grants_expires_after_starts_at_check
    check (expires_at is null or expires_at > starts_at)
