create or replace function private.has_app_role(p_role text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $fn$
  select exists(
    select 1
    from public.app_member_roles r
    where r.user_id=(select auth.uid())
      and r.active
      and r.role=p_role
  );
$fn$;

