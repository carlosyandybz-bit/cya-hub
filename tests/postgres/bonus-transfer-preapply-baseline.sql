create table public.people (
  id bigint primary key,
  active boolean not null default true
);

create table public.classes (
  id bigint primary key
);

create table public.credit_grants (
  id bigint generated by default as identity primary key,
  modality text not null check (modality in ('individual','pair')),
  label text,
  total_minutes integer not null check (total_minutes > 0 and total_minutes <= 100000),
  price_cents integer not null default 0 check (price_cents >= 0),
  payment_status text not null default 'paid'
    check (payment_status in ('paid','pending','refunded')),
  status text not null default 'active'
    check (status in ('active','exhausted','cancelled')),
  purchased_at timestamptz not null default now(),
  expires_at timestamptz,
  created_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  starts_at timestamptz not null default now(),
  purchased_at_approximate boolean not null default false,
  historical_provenance text,
  constraint credit_grants_expires_after_starts_at_check
    check (expires_at is null or expires_at > starts_at)
);

create table public.credit_grant_members (
  grant_id bigint not null references public.credit_grants(id) on delete cascade,
  person_id bigint not null references public.people(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (grant_id,person_id)
);

create table public.credit_grant_pause_periods (
  id bigint generated by default as identity primary key,
  grant_id bigint not null references public.credit_grants(id) on delete cascade,
  paused_at timestamptz not null,
  resumed_at timestamptz,
  pause_reason text not null,
  resume_reason text,
  paused_by uuid,
  resumed_by uuid,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint credit_grant_pause_periods_interval_check
    check (resumed_at is null or resumed_at > paused_at)
);

create unique index credit_grant_pause_periods_one_open_idx
  on public.credit_grant_pause_periods(grant_id)
  where resumed_at is null;

create table public.credit_movements (
  id bigint generated by default as identity primary key,
  grant_id bigint not null references public.credit_grants(id) on delete restrict,
  person_id bigint references public.people(id) on delete set null,
  class_id bigint references public.classes(id) on delete set null,
  movement_type text not null,
  delta_minutes integer not null check (delta_minutes <> 0),
  note text,
  created_by uuid,
  created_at timestamptz not null default now(),
  occurred_at timestamptz not null default now(),
  date_approximate boolean not null default false,
  reverses_movement_id bigint references public.credit_movements(id) on delete restrict,
  provenance jsonb not null default '{}'::jsonb,
  source_operation_key text,
  constraint credit_movements_movement_type_check
    check (movement_type in ('grant','class','adjustment','refund')),
  constraint credit_movements_no_self_reversal_check
    check (reverses_movement_id is null or reverses_movement_id <> id),
  constraint credit_movements_source_operation_key_nonblank
    check (source_operation_key is null or btrim(source_operation_key) <> '')
);

create unique index credit_movements_source_operation_key_uidx
  on public.credit_movements(source_operation_key)
  where source_operation_key is not null;

alter table public.credit_movements enable row level security;

