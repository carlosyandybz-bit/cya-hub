create or replace function public.set_crm_interest_state(p_person_id bigint, p_interest_type text, p_status text, p_note text default null)
returns public.crm_interest_states
language plpgsql security definer set search_path=public,private
as $$
declare v_old text; v_row public.crm_interest_states;
begin
  if not private.is_staff() then raise exception 'staff_required'; end if;
  if p_interest_type not in ('in_person_classes','online_content','teacher_training','wedding','online_feedback','other') then raise exception 'invalid_interest_type'; end if;
  if p_status not in ('unknown','interested','not_interested') then raise exception 'invalid_interest_status'; end if;
  select status into v_old from public.crm_interest_states where person_id=p_person_id and interest_type=p_interest_type;
  insert into public.crm_interest_states(person_id,interest_type,status,note,updated_by)
  values(p_person_id,p_interest_type,p_status,nullif(btrim(p_note),''),auth.uid())
  on conflict(person_id,interest_type) do update set status=excluded.status,note=excluded.note,updated_by=auth.uid(),updated_at=now()
  returning * into v_row;
  if v_old is distinct from p_status then
    insert into public.crm_activities(person_id,activity_type,summary,occurred_at,created_by,metadata,source_type)
    values(p_person_id,'interest_changed','Interés actualizado',now(),auth.uid(),jsonb_build_object('interest_type',p_interest_type,'from',v_old,'to',p_status),'crm_interest');
  end if;
  return v_row;
end $$;

create or replace function public.set_crm_no_booking_reason(p_person_id bigint, p_reason_key text, p_active boolean default true, p_is_primary boolean default false, p_note text default null, p_source_type text default 'manual', p_source_class_id bigint default null)
returns public.crm_no_booking_reasons
language plpgsql security definer set search_path=public,private
as $$
declare v_row public.crm_no_booking_reasons;
begin
  if not private.is_staff() then raise exception 'staff_required'; end if;
  if p_reason_key not in ('price','own_availability','cya_availability','incompatible_schedules','location_distance','temporary_stay','later','thinking','no_longer_interested','no_response','other') then raise exception 'invalid_no_booking_reason'; end if;
  if p_source_type not in ('manual','class_cancellation','system') then raise exception 'invalid_source_type'; end if;
  if p_is_primary and p_active then update public.crm_no_booking_reasons set is_primary=false,updated_at=now() where person_id=p_person_id and active and is_primary; end if;
  select * into v_row from public.crm_no_booking_reasons where person_id=p_person_id and reason_key=p_reason_key and active limit 1;
  if found then
    update public.crm_no_booking_reasons set active=p_active,is_primary=(p_is_primary and p_active),note=nullif(btrim(p_note),''),source_type=p_source_type,source_class_id=p_source_class_id,last_confirmed_at=now(),updated_at=now() where id=v_row.id returning * into v_row;
  elsif p_active then
    insert into public.crm_no_booking_reasons(person_id,reason_key,is_primary,note,source_type,source_class_id,created_by)
    values(p_person_id,p_reason_key,p_is_primary,nullif(btrim(p_note),''),p_source_type,p_source_class_id,auth.uid()) returning * into v_row;
  else
    raise exception 'reason_not_found';
  end if;
  insert into public.crm_activities(person_id,activity_type,summary,occurred_at,created_by,metadata,source_type,source_ref_id)
  values(p_person_id,case when p_active then 'no_booking_reason_set' else 'no_booking_reason_cleared' end,'Motivo de no reserva actualizado',now(),auth.uid(),jsonb_build_object('reason',p_reason_key,'active',p_active,'primary',p_is_primary,'note',nullif(btrim(p_note),'')),p_source_type,p_source_class_id);
  return v_row;
end $$;

