create table if not exists public.crm_interest_states (
  person_id bigint not null references public.people(id) on delete cascade,
  interest_type text not null check (interest_type in ('in_person_classes','online_content','teacher_training','wedding','online_feedback','other')),
  status text not null default 'unknown' check (status in ('unknown','interested','not_interested')),
  note text,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (person_id, interest_type)
);

create table if not exists public.crm_no_booking_reasons (
  id bigint generated by default as identity primary key,
  person_id bigint not null references public.people(id) on delete cascade,
  reason_key text not null check (reason_key in ('price','own_availability','cya_availability','incompatible_schedules','location_distance','temporary_stay','later','thinking','no_longer_interested','no_response','other')),
  is_primary boolean not null default false,
  note text,
  source_type text not null default 'manual' check (source_type in ('manual','class_cancellation','system')),
  source_class_id bigint references public.classes(id) on delete set null,
  active boolean not null default true,
  first_noted_at timestamptz not null default now(),
  last_confirmed_at timestamptz not null default now(),
  created_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now()
);
create unique index if not exists crm_no_booking_reason_active_unique on public.crm_no_booking_reasons(person_id, reason_key) where active;
create unique index if not exists crm_no_booking_primary_unique on public.crm_no_booking_reasons(person_id) where active and is_primary;

