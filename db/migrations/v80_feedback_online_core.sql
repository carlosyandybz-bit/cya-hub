-- PR-C · Feedback Online
-- Separate discrete-credit domain. Feedback never consumes class minutes and never creates fake classes.

create table if not exists public.feedback_products (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  price_cents integer,
  currency text not null default 'EUR',
  credits_per_purchase integer not null default 1,
  target_response_hours integer,
  active boolean not null default false,
  sort_order integer not null default 0,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint feedback_products_name_check check (length(btrim(name)) > 0),
  constraint feedback_products_price_check check (price_cents is null or price_cents >= 0),
  constraint feedback_products_currency_check check (currency ~ '^[A-Z]{3}$'),
  constraint feedback_products_single_credit_check check (credits_per_purchase = 1),
  constraint feedback_products_sla_check check (target_response_hours is null or target_response_hours between 1 and 720),
  constraint feedback_products_active_price_check check (not active or price_cents is not null)
);

create table if not exists public.feedback_credit_orders (
  id bigint generated by default as identity primary key,
  person_id bigint not null references public.people(id) on delete cascade,
  product_id bigint not null references public.feedback_products(id) on delete restrict,
  credits integer not null default 1,
  unit_price_cents integer not null,
  total_price_cents integer not null,
  currency text not null,
  payment_status text not null default 'pending',
  requested_by uuid references auth.users(id) on delete set null,
  confirmed_by uuid references auth.users(id) on delete set null,
  requested_at timestamptz not null default now(),
  paid_at timestamptz,
  cancelled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint feedback_credit_orders_credits_check check (credits = 1),
  constraint feedback_credit_orders_price_check check (unit_price_cents >= 0 and total_price_cents >= 0),
  constraint feedback_credit_orders_currency_check check (currency ~ '^[A-Z]{3}$'),
  constraint feedback_credit_orders_status_check check (payment_status in ('pending','paid','cancelled')),
  constraint feedback_credit_orders_paid_at_check check ((payment_status='paid' and paid_at is not null) or payment_status<>'paid'),
  constraint feedback_credit_orders_cancelled_at_check check ((payment_status='cancelled' and cancelled_at is not null) or payment_status<>'cancelled')
);

create unique index if not exists feedback_credit_orders_one_pending_idx
  on public.feedback_credit_orders(person_id, product_id)
  where payment_status='pending';
create index if not exists feedback_credit_orders_person_idx on public.feedback_credit_orders(person_id, requested_at desc);
create index if not exists feedback_credit_orders_status_idx on public.feedback_credit_orders(payment_status, requested_at);

create table if not exists public.feedback_credit_ledger (
  id bigint generated by default as identity primary key,
  person_id bigint not null references public.people(id) on delete cascade,
  order_id bigint references public.feedback_credit_orders(id) on delete set null,
  movement_type text not null,
  delta_credits integer not null,
  idempotency_key text not null unique,
  note text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint feedback_credit_ledger_type_check check (movement_type in ('purchase','consumption','refund','adjustment')),
  constraint feedback_credit_ledger_delta_check check (delta_credits <> 0),
  constraint feedback_credit_ledger_key_check check (length(btrim(idempotency_key)) > 0)
);
create index if not exists feedback_credit_ledger_person_idx on public.feedback_credit_ledger(person_id, created_at desc);
create index if not exists feedback_credit_ledger_order_idx on public.feedback_credit_ledger(order_id) where order_id is not null;

create table if not exists public.feedback_requests (
  id bigint generated by default as identity primary key,
  person_id bigint not null references public.people(id) on delete cascade,
  product_id bigint not null references public.feedback_products(id) on delete restrict,
  status text not null default 'draft',
  style_term_id bigint references public.catalog_terms(id) on delete set null,
  role_term_id bigint references public.catalog_terms(id) on delete set null,
  level_term_id bigint references public.catalog_terms(id) on delete set null,
  student_note text,
  external_file_id text,
  upload_proof text,
  video_title text,
  mime_type text,
  size_bytes bigint,
  assigned_teacher_user_id uuid references auth.users(id) on delete set null,
  teacher_summary text,
  evaluation_session_id bigint references public.evaluation_sessions(id) on delete set null,
  target_response_hours integer,
  due_at timestamptz,
  submitted_at timestamptz,
  started_at timestamptz,
  completed_at timestamptz,
  cancelled_at timestamptz,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint feedback_requests_status_check check (status in ('draft','submitted','in_review','completed','cancelled')),
  constraint feedback_requests_file_check check (external_file_id is null or length(btrim(external_file_id)) > 5),
  constraint feedback_requests_proof_check check (upload_proof is null or length(btrim(upload_proof)) >= 32),
  constraint feedback_requests_mime_check check (mime_type is null or mime_type like 'video/%'),
  constraint feedback_requests_size_check check (size_bytes is null or (size_bytes > 0 and size_bytes <= 1073741824)),
  constraint feedback_requests_sla_check check (target_response_hours is null or target_response_hours between 1 and 720),
  constraint feedback_requests_submitted_check check ((status in ('submitted','in_review','completed') and submitted_at is not null) or status in ('draft','cancelled')),
  constraint feedback_requests_started_check check ((status in ('in_review','completed') and started_at is not null) or status in ('draft','submitted','cancelled')),
  constraint feedback_requests_completed_check check ((status='completed' and completed_at is not null) or status<>'completed'),
  constraint feedback_requests_cancelled_check check ((status='cancelled' and cancelled_at is not null) or status<>'cancelled')
);
create index if not exists feedback_requests_person_idx on public.feedback_requests(person_id, created_at desc);
create index if not exists feedback_requests_queue_idx on public.feedback_requests(status, submitted_at) where status in ('submitted','in_review');
create index if not exists feedback_requests_due_idx on public.feedback_requests(due_at) where status in ('submitted','in_review') and due_at is not null;
create unique index if not exists feedback_requests_file_idx on public.feedback_requests(external_file_id) where external_file_id is not null;

