create or replace function public.feedback_complete_request(p_request_id bigint,p_teacher_summary text)
returns public.feedback_requests language plpgsql security definer set search_path=''
as $$
declare v_request public.feedback_requests; v_user uuid; v_from text;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para cerrar Feedback Online.' using errcode='42501'; end if;
  if nullif(btrim(coalesce(p_teacher_summary,'')),'') is null then raise exception 'Escribe el feedback para el alumno antes de terminar.' using errcode='22023'; end if;
  select * into v_request from public.feedback_requests where id=p_request_id for update;
  if not found then raise exception 'No se ha encontrado la solicitud.' using errcode='22023'; end if;
  if v_request.status='completed' then return v_request; end if;
  if v_request.status not in ('submitted','in_review') then raise exception 'Este Feedback no se puede cerrar.' using errcode='22023'; end if;
  if v_request.evaluation_session_id is not null and exists(select 1 from public.evaluation_sessions where id=v_request.evaluation_session_id and status<>'completed') then
    raise exception 'Termina o elimina la evaluación abierta antes de cerrar el Feedback.' using errcode='22023';
  end if;
  v_from:=v_request.status;
  if v_request.status='submitted' then
    update public.feedback_requests set started_at=coalesce(started_at,now()),assigned_teacher_user_id=coalesce(assigned_teacher_user_id,(select auth.uid())) where id=v_request.id;
  end if;
  update public.feedback_requests set status='completed',teacher_summary=btrim(p_teacher_summary),completed_at=now(),started_at=coalesce(started_at,now()),
    assigned_teacher_user_id=coalesce(assigned_teacher_user_id,(select auth.uid())),updated_by=(select auth.uid()) where id=v_request.id returning * into v_request;
  update public.student_content_assignments a set student_visible_at=coalesce(a.student_visible_at,now()),updated_at=now()
  from public.feedback_request_contents frc join public.teaching_contents tc on tc.id=frc.content_id
  where frc.request_id=v_request.id and frc.assignment_id=a.id and private.assignment_is_student_releasable(tc.content_type,a.assignment_status);
  insert into public.feedback_request_events(request_id,person_id,event_type,from_status,to_status,actor_user_id)
  values(v_request.id,v_request.person_id,'completed',v_from,'completed',(select auth.uid()));
  select auth_user_id into v_user from public.people where id=v_request.person_id;
  if v_user is not null then
    perform private.enqueue_notification('feedback.online.completed',v_user,'Tu Feedback Online está listo','Ya puedes abrirlo y revisar las indicaciones.','student:feedback','feedback_online',v_request.id::text,jsonb_build_object('request_id',v_request.id));
  end if;
  return v_request;
end;
$$;
revoke all on function public.feedback_complete_request(bigint,text) from public, anon;
grant execute on function public.feedback_complete_request(bigint,text) to authenticated;

