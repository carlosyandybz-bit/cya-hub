create or replace function public.feedback_submit_request(p_request_id bigint)
returns public.feedback_requests language plpgsql security definer set search_path=''
as $$
declare v_person bigint; v_request public.feedback_requests; v_product public.feedback_products; v_balance integer; v_user uuid;
begin
  select private.current_person_id() into v_person;
  if v_person is null then raise exception 'No hemos podido vincular esta cuenta.' using errcode='42501'; end if;
  select * into v_request from public.feedback_requests where id=p_request_id and person_id=v_person for update;
  if not found then raise exception 'No se ha encontrado la solicitud.' using errcode='22023'; end if;
  if v_request.status='submitted' or v_request.status='in_review' or v_request.status='completed' then return v_request; end if;
  if v_request.status<>'draft' then raise exception 'La solicitud ya no se puede enviar.' using errcode='22023'; end if;
  if v_request.external_file_id is null or v_request.upload_proof is null then raise exception 'Sube el vídeo antes de enviarlo.' using errcode='22023'; end if;
  perform 1 from public.people where id=v_person and active for update;
  select coalesce(sum(delta_credits),0)::integer into v_balance from public.feedback_credit_ledger where person_id=v_person;
  if v_balance<1 then raise exception 'No tienes créditos de Feedback Online disponibles.' using errcode='22023'; end if;
  select * into v_product from public.feedback_products where id=v_request.product_id;
  perform private.feedback_add_ledger(v_person,null,v_request.id,'consumption',-1,'feedback:request:'||v_request.id||':consume','Feedback Online enviado');
  update public.feedback_requests set status='submitted',submitted_at=now(),target_response_hours=v_product.target_response_hours,
    due_at=case when v_product.target_response_hours is null then null else now() + make_interval(hours=>v_product.target_response_hours) end,
    updated_by=(select auth.uid()) where id=v_request.id returning * into v_request;
  insert into public.feedback_request_events(request_id,person_id,event_type,from_status,to_status,actor_user_id)
  values(v_request.id,v_person,'submitted','draft','submitted',(select auth.uid()));
  for v_user in select distinct user_id from public.app_member_roles where active and role in ('admin','teacher_admin','teacher') loop
    perform private.enqueue_notification('feedback.online.pending',v_user,'Nuevo Feedback Online','Hay un vídeo pendiente de revisar.','live:feedback','feedback_online',v_request.id::text,jsonb_build_object('person_id',v_person,'request_id',v_request.id));
  end loop;
  return v_request;
end;
$$;
revoke all on function public.feedback_submit_request(bigint) from public, anon;
grant execute on function public.feedback_submit_request(bigint) to authenticated;

create or replace function public.feedback_cancel_request(p_request_id bigint)
returns public.feedback_requests language plpgsql security definer set search_path=''
as $$
declare v_person bigint; v_request public.feedback_requests;
begin
  select private.current_person_id() into v_person;
  select * into v_request from public.feedback_requests where id=p_request_id and person_id=v_person for update;
  if not found then raise exception 'No se ha encontrado la solicitud.' using errcode='22023'; end if;
  if v_request.status='cancelled' then return v_request; end if;
  if v_request.status not in ('draft','submitted') or v_request.started_at is not null then raise exception 'Este Feedback ya está siendo revisado y no se puede cancelar.' using errcode='22023'; end if;
  if v_request.status='submitted' then
    perform 1 from public.people where id=v_person for update;
    perform private.feedback_add_ledger(v_person,null,v_request.id,'refund',1,'feedback:request:'||v_request.id||':refund','Feedback cancelado antes de revisión');
    insert into public.feedback_request_events(request_id,person_id,event_type,from_status,to_status,actor_user_id)
    values(v_request.id,v_person,'credit_refunded','submitted','submitted',(select auth.uid()));
  end if;
  update public.feedback_requests set status='cancelled',cancelled_at=now(),updated_by=(select auth.uid()) where id=v_request.id returning * into v_request;
  insert into public.feedback_request_events(request_id,person_id,event_type,from_status,to_status,actor_user_id)
  values(v_request.id,v_person,'cancelled',case when v_request.submitted_at is null then 'draft' else 'submitted' end,'cancelled',(select auth.uid()));
  return v_request;
end;
$$;
revoke all on function public.feedback_cancel_request(bigint) from public, anon;
grant execute on function public.feedback_cancel_request(bigint) to authenticated;

