create or replace function private.feedback_activate_student(p_person_id bigint)
returns void language plpgsql security definer set search_path=''
as $$
declare v_auth uuid;
begin
  if not exists(select 1 from public.people where id=p_person_id and active) then
    raise exception 'La persona no está disponible.' using errcode='22023';
  end if;
  insert into public.student_profiles(person_id,student_since,active,created_by)
  values(p_person_id,current_date,true,(select auth.uid()))
  on conflict(person_id) do update set active=true, updated_at=now();
  select auth_user_id into v_auth from public.people where id=p_person_id;
  if v_auth is not null then
    insert into public.app_member_roles(user_id,role,active,granted_by)
    values(v_auth,'student',true,(select auth.uid()))
    on conflict(user_id,role) do update set active=true, updated_at=now();
  end if;
end;
$$;
revoke all on function private.feedback_activate_student(bigint) from public, anon, authenticated;

create or replace function private.feedback_add_ledger(
  p_person_id bigint,
  p_order_id bigint,
  p_request_id bigint,
  p_movement_type text,
  p_delta integer,
  p_idempotency_key text,
  p_note text default null
) returns public.feedback_credit_ledger
language plpgsql security definer set search_path=''
as $$
declare v_row public.feedback_credit_ledger;
begin
  insert into public.feedback_credit_ledger(person_id,order_id,request_id,movement_type,delta_credits,idempotency_key,note,created_by)
  values(p_person_id,p_order_id,p_request_id,p_movement_type,p_delta,p_idempotency_key,nullif(btrim(coalesce(p_note,'')),''),(select auth.uid()))
  on conflict(idempotency_key) do nothing returning * into v_row;
  if v_row.id is null then
    select * into v_row from public.feedback_credit_ledger where idempotency_key=p_idempotency_key;
  end if;
  return v_row;
end;
$$;
revoke all on function private.feedback_add_ledger(bigint,bigint,bigint,text,integer,text,text) from public, anon, authenticated;

create or replace function public.feedback_credit_balance(p_person_id bigint default null)
returns integer language plpgsql stable security definer set search_path=''
as $$
declare v_person bigint:=coalesce(p_person_id,(select private.current_person_id())); v_balance integer;
begin
  if v_person is null then raise exception 'No hemos podido vincular esta cuenta con una persona.' using errcode='22023'; end if;
  if not (select private.is_staff()) and v_person<>(select private.current_person_id()) then
    raise exception 'No tienes permiso para consultar este saldo.' using errcode='42501';
  end if;
  select coalesce(sum(delta_credits),0)::integer into v_balance from public.feedback_credit_ledger where person_id=v_person;
  return v_balance;
end;
$$;
revoke all on function public.feedback_credit_balance(bigint) from public, anon;
grant execute on function public.feedback_credit_balance(bigint) to authenticated;

create or replace function public.feedback_request_purchase(p_product_id bigint)
returns public.feedback_credit_orders language plpgsql security definer set search_path=''
as $$
declare v_person bigint; v_product public.feedback_products; v_order public.feedback_credit_orders;
begin
  select private.current_person_id() into v_person;
  if v_person is null then raise exception 'Necesitas una cuenta de alumno vinculada para solicitar Feedback Online.' using errcode='42501'; end if;
  select * into v_product from public.feedback_products where id=p_product_id and active and price_cents is not null;
  if not found then raise exception 'Este Feedback Online no está disponible para compra.' using errcode='22023'; end if;
  insert into public.feedback_credit_orders(person_id,product_id,credits,unit_price_cents,total_price_cents,currency,payment_status,requested_by)
  values(v_person,v_product.id,1,v_product.price_cents,v_product.price_cents,v_product.currency,'pending',(select auth.uid()))
  on conflict(person_id,product_id) where payment_status='pending'
  do update set updated_at=now()
  returning * into v_order;
  return v_order;
end;
$$;
revoke all on function public.feedback_request_purchase(bigint) from public, anon;
grant execute on function public.feedback_request_purchase(bigint) to authenticated;

create or replace function public.admin_feedback_save_product(
  p_product_id bigint,
  p_name text,
  p_description text,
  p_price_cents integer,
  p_currency text,
  p_target_response_hours integer,
  p_active boolean
) returns public.feedback_products language plpgsql security definer set search_path=''
as $$
declare v_row public.feedback_products;
begin
  if not (select private.is_admin()) then raise exception 'Solo Administración puede configurar Feedback Online.' using errcode='42501'; end if;
  if nullif(btrim(coalesce(p_name,'')),'') is null then raise exception 'Indica un nombre.' using errcode='22023'; end if;
  if p_price_cents is not null and p_price_cents<0 then raise exception 'El precio no es válido.' using errcode='22023'; end if;
  if p_active and p_price_cents is null then raise exception 'Configura el precio antes de activar el producto.' using errcode='22023'; end if;
  if p_product_id is null then
    insert into public.feedback_products(name,description,price_cents,currency,target_response_hours,active,created_by)
    values(btrim(p_name),nullif(btrim(coalesce(p_description,'')),''),p_price_cents,upper(coalesce(nullif(btrim(p_currency),''),'EUR')),p_target_response_hours,p_active,(select auth.uid()))
    returning * into v_row;
  else
    update public.feedback_products set name=btrim(p_name),description=nullif(btrim(coalesce(p_description,'')),''),price_cents=p_price_cents,
      currency=upper(coalesce(nullif(btrim(p_currency),''),'EUR')),target_response_hours=p_target_response_hours,active=p_active
    where id=p_product_id returning * into v_row;
    if v_row.id is null then raise exception 'No se ha encontrado el producto de Feedback Online.' using errcode='22023'; end if;
  end if;
  return v_row;
end;
$$;
revoke all on function public.admin_feedback_save_product(bigint,text,text,integer,text,integer,boolean) from public, anon;
grant execute on function public.admin_feedback_save_product(bigint,text,text,integer,text,integer,boolean) to authenticated;

create or replace function public.admin_feedback_confirm_purchase(p_order_id bigint)
returns public.feedback_credit_orders language plpgsql security definer set search_path=''
as $$
declare v_order public.feedback_credit_orders;
begin
  if not (select private.is_admin()) then raise exception 'Solo Administración puede confirmar un pago.' using errcode='42501'; end if;
  select * into v_order from public.feedback_credit_orders where id=p_order_id for update;
  if not found then raise exception 'No se ha encontrado la compra.' using errcode='22023'; end if;
  if v_order.payment_status='paid' then return v_order; end if;
  if v_order.payment_status<>'pending' then raise exception 'Esta compra ya no está pendiente.' using errcode='22023'; end if;
  perform private.feedback_activate_student(v_order.person_id);
  update public.feedback_credit_orders set payment_status='paid',paid_at=now(),confirmed_by=(select auth.uid()) where id=v_order.id returning * into v_order;
  perform private.feedback_add_ledger(v_order.person_id,v_order.id,null,'purchase',v_order.credits,'feedback:order:'||v_order.id||':purchase','Compra de Feedback Online');
  return v_order;
end;
$$;
revoke all on function public.admin_feedback_confirm_purchase(bigint) from public, anon;
grant execute on function public.admin_feedback_confirm_purchase(bigint) to authenticated;

create or replace function public.admin_feedback_create_paid_purchase(p_person_id bigint,p_product_id bigint,p_note text default null)
returns public.feedback_credit_orders language plpgsql security definer set search_path=''
as $$
declare v_product public.feedback_products; v_order public.feedback_credit_orders;
begin
  if not (select private.is_admin()) then raise exception 'Solo Administración puede registrar una compra.' using errcode='42501'; end if;
  if not exists(select 1 from public.people where id=p_person_id and active) then raise exception 'La persona no está disponible.' using errcode='22023'; end if;
  select * into v_product from public.feedback_products where id=p_product_id and price_cents is not null;
  if not found then raise exception 'Configura primero el producto de Feedback Online.' using errcode='22023'; end if;
  perform private.feedback_activate_student(p_person_id);
  insert into public.feedback_credit_orders(person_id,product_id,credits,unit_price_cents,total_price_cents,currency,payment_status,requested_by,confirmed_by,paid_at)
  values(p_person_id,v_product.id,1,v_product.price_cents,v_product.price_cents,v_product.currency,'paid',(select auth.uid()),(select auth.uid()),now())
  returning * into v_order;
  perform private.feedback_add_ledger(p_person_id,v_order.id,null,'purchase',1,'feedback:order:'||v_order.id||':purchase',coalesce(nullif(btrim(coalesce(p_note,'')),''),'Compra de Feedback Online'));
  return v_order;
end;
$$;
revoke all on function public.admin_feedback_create_paid_purchase(bigint,bigint,text) from public, anon;
grant execute on function public.admin_feedback_create_paid_purchase(bigint,bigint,text) to authenticated;

create or replace function public.admin_feedback_adjust_credits(p_person_id bigint,p_delta integer,p_note text)
returns public.feedback_credit_ledger language plpgsql security definer set search_path=''
as $$
declare v_balance integer; v_row public.feedback_credit_ledger; v_key text;
begin
  if not (select private.is_admin()) then raise exception 'Solo Administración puede ajustar créditos de Feedback.' using errcode='42501'; end if;
  if p_delta=0 then raise exception 'El ajuste debe sumar o restar al menos un crédito.' using errcode='22023'; end if;
  if nullif(btrim(coalesce(p_note,'')),'') is null then raise exception 'Indica el motivo del ajuste.' using errcode='22023'; end if;
  perform 1 from public.people where id=p_person_id and active for update;
  if not found then raise exception 'La persona no está disponible.' using errcode='22023'; end if;
  select coalesce(sum(delta_credits),0)::integer into v_balance from public.feedback_credit_ledger where person_id=p_person_id;
  if v_balance+p_delta<0 then raise exception 'El ajuste dejaría un saldo de Feedback negativo.' using errcode='22023'; end if;
  perform private.feedback_activate_student(p_person_id);
  v_key:='feedback:adjust:'||p_person_id||':'||gen_random_uuid()::text;
  select * into v_row from private.feedback_add_ledger(p_person_id,null,null,'adjustment',p_delta,v_key,p_note);
  return v_row;
end;
$$;
revoke all on function public.admin_feedback_adjust_credits(bigint,integer,text) from public, anon;
grant execute on function public.admin_feedback_adjust_credits(bigint,integer,text) to authenticated;

create or replace function public.feedback_create_draft(
  p_product_id bigint,
  p_style_term_id bigint default null,
  p_role_term_id bigint default null,
  p_level_term_id bigint default null,
  p_student_note text default null
) returns public.feedback_requests language plpgsql security definer set search_path=''
as $$
declare v_person bigint; v_product public.feedback_products; v_balance integer; v_request public.feedback_requests;
begin
  select private.current_person_id() into v_person;
  if v_person is null then raise exception 'Necesitas una cuenta de alumno vinculada.' using errcode='42501'; end if;
  select * into v_product from public.feedback_products where id=p_product_id and active;
  if not found then raise exception 'Este Feedback Online no está disponible.' using errcode='22023'; end if;
  perform 1 from public.people where id=v_person and active for update;
  select coalesce(sum(delta_credits),0)::integer into v_balance from public.feedback_credit_ledger where person_id=v_person;
  if v_balance<1 then raise exception 'Necesitas un crédito de Feedback Online disponible.' using errcode='22023'; end if;
  if p_style_term_id is not null and not exists(select 1 from public.catalog_terms where id=p_style_term_id and taxonomy='dance_style' and active) then raise exception 'El estilo no es válido.' using errcode='22023'; end if;
  if p_role_term_id is not null and not exists(select 1 from public.catalog_terms where id=p_role_term_id and taxonomy='dance_role' and active) then raise exception 'El rol no es válido.' using errcode='22023'; end if;
  if p_level_term_id is not null and not exists(select 1 from public.catalog_terms where id=p_level_term_id and taxonomy='dance_level' and active) then raise exception 'El nivel no es válido.' using errcode='22023'; end if;
  insert into public.feedback_requests(person_id,product_id,status,style_term_id,role_term_id,level_term_id,student_note,created_by,updated_by)
  values(v_person,v_product.id,'draft',p_style_term_id,p_role_term_id,p_level_term_id,nullif(btrim(coalesce(p_student_note,'')),''),(select auth.uid()),(select auth.uid()))
  returning * into v_request;
  insert into public.feedback_request_events(request_id,person_id,event_type,to_status,actor_user_id)
  values(v_request.id,v_person,'created','draft',(select auth.uid()));
  return v_request;
end;
$$;
revoke all on function public.feedback_create_draft(bigint,bigint,bigint,bigint,text) from public, anon;
grant execute on function public.feedback_create_draft(bigint,bigint,bigint,bigint,text) to authenticated;

