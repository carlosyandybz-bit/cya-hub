create or replace function private.academy_activate_student(p_person_id bigint)
returns void language plpgsql security definer set search_path=''
as $$
declare v_auth uuid;
begin
  select auth_user_id into v_auth from public.people where id=p_person_id and active;
  if not found then raise exception 'La persona no está disponible.' using errcode='22023'; end if;

  insert into public.student_profiles(person_id,student_since,active,created_by)
  values(p_person_id,current_date,true,(select auth.uid()))
  on conflict(person_id) do update set active=true,updated_at=now();

  if v_auth is not null then
    insert into public.app_member_roles(user_id,role,active,granted_by)
    values(v_auth,'student',true,(select auth.uid()))
    on conflict(user_id,role) do update set active=true,updated_at=now();
  end if;
end;
$$;
revoke all on function private.academy_activate_student(bigint) from public,anon,authenticated;

create or replace function private.academy_validate_context(p_style_term_id bigint,p_role_term_id bigint,p_level_term_id bigint)
returns void language plpgsql stable security definer set search_path=''
as $$
begin
  if not exists(select 1 from public.catalog_terms where id=p_style_term_id and taxonomy='dance_style' and active) then
    raise exception 'Selecciona un estilo válido.' using errcode='22023';
  end if;
  if not exists(select 1 from public.catalog_terms where id=p_role_term_id and taxonomy='dance_role' and active) then
    raise exception 'Selecciona un rol válido.' using errcode='22023';
  end if;
  if not exists(select 1 from public.catalog_terms where id=p_level_term_id and taxonomy='dance_level' and active) then
    raise exception 'Selecciona un nivel válido.' using errcode='22023';
  end if;
end;
$$;
revoke all on function private.academy_validate_context(bigint,bigint,bigint) from public,anon,authenticated;

create or replace function public.academy_save_program(
  p_program_id bigint,
  p_title text,
  p_description text,
  p_style_term_id bigint,
  p_role_term_id bigint,
  p_level_term_id bigint
) returns public.academy_programs
language plpgsql security definer set search_path=''
as $$
declare v_row public.academy_programs;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para editar Academia Online.' using errcode='42501'; end if;
  if nullif(btrim(coalesce(p_title,'')),'') is null then raise exception 'Indica un título para el programa.' using errcode='22023'; end if;
  perform private.academy_validate_context(p_style_term_id,p_role_term_id,p_level_term_id);

  if p_program_id is null then
    insert into public.academy_programs(title,description,style_term_id,role_term_id,level_term_id,created_by,updated_by)
    values(btrim(p_title),nullif(btrim(coalesce(p_description,'')),''),p_style_term_id,p_role_term_id,p_level_term_id,(select auth.uid()),(select auth.uid()))
    returning * into v_row;
  else
    update public.academy_programs
    set title=btrim(p_title),description=nullif(btrim(coalesce(p_description,'')),''),style_term_id=p_style_term_id,
        role_term_id=p_role_term_id,level_term_id=p_level_term_id,updated_by=(select auth.uid())
    where id=p_program_id and publication_status<>'archived'
    returning * into v_row;
    if v_row.id is null then raise exception 'No se ha encontrado un programa editable.' using errcode='22023'; end if;
  end if;
  return v_row;
end;
$$;
revoke all on function public.academy_save_program(bigint,text,text,bigint,bigint,bigint) from public,anon;
grant execute on function public.academy_save_program(bigint,text,text,bigint,bigint,bigint) to authenticated;

create or replace function public.academy_set_program_content(
  p_program_id bigint,
  p_content_id bigint,
  p_position integer,
  p_required boolean default true
) returns public.academy_program_contents
language plpgsql security definer set search_path=''
as $$
declare v_program public.academy_programs; v_row public.academy_program_contents;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para organizar Academia Online.' using errcode='42501'; end if;
  if p_position is null or p_position<1 or p_position>10000 then raise exception 'La posición no es válida.' using errcode='22023'; end if;

  select * into v_program from public.academy_programs where id=p_program_id and publication_status<>'archived' for update;
  if not found then raise exception 'No se ha encontrado el programa.' using errcode='22023'; end if;

  if not exists(
    select 1 from public.teaching_contents t
    where t.id=p_content_id and t.active and t.completion_status='complete' and t.publication_status='published' and t.visibility='student'
      and exists(select 1 from public.teaching_content_styles s where s.content_id=t.id and s.style_term_id=v_program.style_term_id)
      and exists(select 1 from public.teaching_content_roles r where r.content_id=t.id and r.role_term_id=v_program.role_term_id)
      and exists(select 1 from public.teaching_content_levels l where l.content_id=t.id and l.level_term_id=v_program.level_term_id)
  ) then
    raise exception 'El contenido debe estar completo, publicado para alumnos y ser compatible con el contexto del programa.' using errcode='22023';
  end if;

  if exists(select 1 from public.academy_program_contents where program_id=p_program_id and position=p_position and content_id<>p_content_id) then
    raise exception 'Ya existe otro contenido en esa posición.' using errcode='23505';
  end if;

  insert into public.academy_program_contents(program_id,content_id,position,required,created_by)
  values(p_program_id,p_content_id,p_position,coalesce(p_required,true),(select auth.uid()))
  on conflict(program_id,content_id) do update set position=excluded.position,required=excluded.required
  returning * into v_row;

  insert into public.academy_progress(enrollment_id,program_content_id)
  select e.id,v_row.id from public.academy_enrollments e
  where e.program_id=p_program_id and e.status in ('active','completed')
  on conflict(enrollment_id,program_content_id) do nothing;

  return v_row;
end;
$$;
revoke all on function public.academy_set_program_content(bigint,bigint,integer,boolean) from public,anon;
grant execute on function public.academy_set_program_content(bigint,bigint,integer,boolean) to authenticated;

