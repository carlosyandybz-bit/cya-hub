create or replace function public.admin_academy_publish_program(
  p_program_id bigint,
  p_price_cents integer,
  p_currency text,
  p_active boolean,
  p_publication_status text
) returns public.academy_programs
language plpgsql security definer set search_path=''
as $$
declare v_row public.academy_programs;
begin
  if not (select private.is_admin()) then raise exception 'Solo Administración puede publicar y fijar el precio de Academia Online.' using errcode='42501'; end if;
  if p_publication_status not in ('draft','published','archived') then raise exception 'El estado de publicación no es válido.' using errcode='22023'; end if;
  if p_price_cents is not null and p_price_cents<0 then raise exception 'El precio no es válido.' using errcode='22023'; end if;
  if p_publication_status='published' then
    if p_price_cents is null then raise exception 'Configura el precio antes de publicar.' using errcode='22023'; end if;
    if not exists(select 1 from public.academy_program_contents where program_id=p_program_id) then raise exception 'Añade contenido antes de publicar el programa.' using errcode='22023'; end if;
  end if;
  if p_active and p_publication_status<>'published' then raise exception 'Solo un programa publicado puede estar activo.' using errcode='22023'; end if;

  update public.academy_programs
  set price_cents=p_price_cents,
      currency=upper(coalesce(nullif(btrim(coalesce(p_currency,'')),''),'EUR')),
      active=coalesce(p_active,false),
      publication_status=p_publication_status,
      published_at=case when p_publication_status='published' then coalesce(published_at,now()) else null end,
      updated_by=(select auth.uid())
  where id=p_program_id
  returning * into v_row;
  if v_row.id is null then raise exception 'No se ha encontrado el programa.' using errcode='22023'; end if;
  return v_row;
end;
$$;
revoke all on function public.admin_academy_publish_program(bigint,integer,text,boolean,text) from public,anon;
grant execute on function public.admin_academy_publish_program(bigint,integer,text,boolean,text) to authenticated;

create or replace function public.admin_academy_enroll(
  p_person_id bigint,
  p_program_id bigint,
  p_starts_at timestamptz default null,
  p_expires_at timestamptz default null,
  p_note text default null
) returns public.academy_enrollments
language plpgsql security definer set search_path=''
as $$
declare v_program public.academy_programs; v_row public.academy_enrollments; v_start timestamptz:=coalesce(p_starts_at,now());
begin
  if not (select private.is_admin()) then raise exception 'Solo Administración puede conceder acceso a Academia Online.' using errcode='42501'; end if;
  select * into v_program from public.academy_programs where id=p_program_id and active and publication_status='published';
  if not found then raise exception 'El programa debe estar publicado y activo antes de matricular.' using errcode='22023'; end if;
  if p_expires_at is not null and p_expires_at<=v_start then raise exception 'La fecha de fin debe ser posterior al inicio.' using errcode='22023'; end if;

  perform private.academy_activate_student(p_person_id);

  insert into public.academy_enrollments(program_id,person_id,status,access_source,starts_at,expires_at,granted_by,note)
  values(p_program_id,p_person_id,'active','admin',v_start,p_expires_at,(select auth.uid()),nullif(btrim(coalesce(p_note,'')),''))
  on conflict(program_id,person_id) do update
    set status='active',access_source='admin',starts_at=excluded.starts_at,expires_at=excluded.expires_at,
        completed_at=null,granted_by=(select auth.uid()),note=excluded.note,updated_at=now()
  returning * into v_row;

  insert into public.academy_progress(enrollment_id,program_content_id)
  select v_row.id,c.id from public.academy_program_contents c where c.program_id=p_program_id
  on conflict(enrollment_id,program_content_id) do nothing;

  return v_row;
end;
$$;
revoke all on function public.admin_academy_enroll(bigint,bigint,timestamptz,timestamptz,text) from public,anon;
grant execute on function public.admin_academy_enroll(bigint,bigint,timestamptz,timestamptz,text) to authenticated;

