-- PR-D · Academia Online
-- Academia reuses canonical teaching content and canonical people.
-- Course consumption progress is intentionally separate from pedagogical assignment/mastery state.

create table if not exists public.app_module_settings (
  module_key text primary key,
  label text not null,
  sort_order integer not null,
  updated_by uuid references auth.users(id) on delete set null,
  updated_at timestamptz not null default now(),
  constraint app_module_settings_key_check check (module_key in ('home','students','teaching','marketing','statistics','academy')),
  constraint app_module_settings_label_check check (length(btrim(label)) > 0),
  constraint app_module_settings_order_check check (sort_order between 0 and 1000)
);

create table if not exists public.academy_programs (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  style_term_id bigint not null references public.catalog_terms(id) on delete restrict,
  role_term_id bigint not null references public.catalog_terms(id) on delete restrict,
  level_term_id bigint not null references public.catalog_terms(id) on delete restrict,
  price_cents integer,
  currency text not null default 'EUR',
  publication_status text not null default 'draft',
  active boolean not null default false,
  sort_order integer not null default 0,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  published_at timestamptz,
  constraint academy_programs_title_check check (length(btrim(title)) > 0),
  constraint academy_programs_price_check check (price_cents is null or price_cents >= 0),
  constraint academy_programs_currency_check check (currency ~ '^[A-Z]{3}$'),
  constraint academy_programs_publication_check check (publication_status in ('draft','published','archived')),
  constraint academy_programs_active_check check (not active or publication_status='published'),
  constraint academy_programs_published_price_check check (publication_status<>'published' or price_cents is not null),
  constraint academy_programs_published_at_check check ((publication_status='published' and published_at is not null) or publication_status<>'published')
);
create index if not exists academy_programs_context_idx on public.academy_programs(style_term_id,role_term_id,level_term_id,publication_status,active);
create index if not exists academy_programs_order_idx on public.academy_programs(sort_order,id);

create table if not exists public.academy_program_contents (
  id bigint generated by default as identity primary key,
  program_id bigint not null references public.academy_programs(id) on delete cascade,
  content_id bigint not null references public.teaching_contents(id) on delete cascade,
  position integer not null,
  required boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  constraint academy_program_contents_position_check check (position between 1 and 10000),
  unique(program_id,content_id),
  unique(program_id,position)
);
create index if not exists academy_program_contents_content_idx on public.academy_program_contents(content_id);

create table if not exists public.academy_enrollments (
  id bigint generated by default as identity primary key,
  program_id bigint not null references public.academy_programs(id) on delete restrict,
  person_id bigint not null references public.people(id) on delete cascade,
  status text not null default 'active',
  access_source text not null default 'admin',
  starts_at timestamptz not null default now(),
  expires_at timestamptz,
  completed_at timestamptz,
  granted_by uuid references auth.users(id) on delete set null,
  note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint academy_enrollments_status_check check (status in ('active','completed','cancelled')),
  constraint academy_enrollments_source_check check (access_source in ('admin','purchase','promotion','migration')),
  constraint academy_enrollments_expiry_check check (expires_at is null or expires_at > starts_at),
  constraint academy_enrollments_completed_check check ((status='completed' and completed_at is not null) or status<>'completed'),
  unique(program_id,person_id)
);
create index if not exists academy_enrollments_person_idx on public.academy_enrollments(person_id,status);
create index if not exists academy_enrollments_program_idx on public.academy_enrollments(program_id,status);

create table if not exists public.academy_progress (
  enrollment_id bigint not null references public.academy_enrollments(id) on delete cascade,
  program_content_id bigint not null references public.academy_program_contents(id) on delete cascade,
  status text not null default 'not_started',
  started_at timestamptz,
  completed_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key(enrollment_id,program_content_id),
  constraint academy_progress_status_check check (status in ('not_started','in_progress','completed')),
  constraint academy_progress_started_check check ((status in ('in_progress','completed') and started_at is not null) or status='not_started'),
  constraint academy_progress_completed_check check ((status='completed' and completed_at is not null) or status<>'completed')
);
create index if not exists academy_progress_content_idx on public.academy_progress(program_content_id,status);

