drop policy if exists academy_programs_read on public.academy_programs;
create policy academy_programs_read on public.academy_programs for select to authenticated
using (
  (select private.is_staff())
  or (
    active and publication_status='published'
    and exists(
      select 1 from public.academy_enrollments e
      where e.program_id=id
        and e.person_id=(select private.current_person_id())
        and e.status in ('active','completed')
        and e.starts_at<=now()
        and (e.expires_at is null or e.expires_at>now())
    )
  )
);

drop policy if exists academy_program_contents_read on public.academy_program_contents;
create policy academy_program_contents_read on public.academy_program_contents for select to authenticated
using (
  (select private.is_staff())
  or exists(
    select 1
    from public.academy_enrollments e
    join public.academy_programs p on p.id=e.program_id
    where e.program_id=academy_program_contents.program_id
      and e.person_id=(select private.current_person_id())
      and e.status in ('active','completed')
      and e.starts_at<=now()
      and (e.expires_at is null or e.expires_at>now())
      and p.active and p.publication_status='published'
  )
);

drop policy if exists academy_enrollments_read on public.academy_enrollments;
create policy academy_enrollments_read on public.academy_enrollments for select to authenticated
using ((select private.is_staff()) or person_id=(select private.current_person_id()));

drop policy if exists academy_progress_read on public.academy_progress;
create policy academy_progress_read on public.academy_progress for select to authenticated
using (
  (select private.is_staff())
  or exists(
    select 1 from public.academy_enrollments e
    where e.id=enrollment_id and e.person_id=(select private.current_person_id())
  )
);

