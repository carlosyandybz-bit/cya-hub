create or replace function public.bz_record_daily_login()
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_person bigint:=(select private.current_person_id()); v_date date:=(select private.bz_local_date()); v_action_id bigint; v_ledger_id bigint;
begin
  if v_person is null then raise exception 'Necesitas un perfil de alumno activo.' using errcode='42501'; end if;
  insert into public.bz_action_events(person_id,action_key,local_date,idempotency_key,evidence)
  values(v_person,'daily_login',v_date,'bz-action:daily-login:'||v_person||':'||v_date,jsonb_build_object('local_date',v_date))
  on conflict(idempotency_key) do nothing returning id into v_action_id;
  v_ledger_id:=private.bz_award(v_person,'daily_login','daily_login',v_date::text,
    'bz:daily-login:'||v_person||':'||v_date,jsonb_build_object('local_date',v_date),now());
  return jsonb_build_object('person_id',v_person,'local_date',v_date,'action_created',v_action_id is not null,'points_awarded',v_ledger_id is not null);
end;
$$;

create or replace function private.bz_validate_next_class(p_person_id bigint,p_class_id bigint)
returns public.classes
language plpgsql
stable
security definer
set search_path=''
as $$
declare v_class public.classes;
begin
  select c.* into v_class
  from public.classes c join public.class_participants cp on cp.class_id=c.id and cp.person_id=p_person_id
  where c.id=p_class_id and c.scheduled_start_at>now() and c.status not in ('finished','cancelled') and cp.attendance_status<>'absent';
  if not found then raise exception 'La clase indicada no es una próxima clase disponible.' using errcode='42501'; end if;
  if exists(
    select 1 from public.classes earlier join public.class_participants ep on ep.class_id=earlier.id and ep.person_id=p_person_id
    where earlier.scheduled_start_at>now() and earlier.scheduled_start_at<v_class.scheduled_start_at
      and earlier.status not in ('finished','cancelled') and ep.attendance_status<>'absent'
  ) then raise exception 'Solo puedes preparar tu próxima clase.' using errcode='42501'; end if;
  return v_class;
end;
$$;

create or replace function public.bz_confirm_previous_class_review(p_class_id bigint)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_person bigint:=(select private.current_person_id());
  v_date date:=(select private.bz_local_date());
  v_class public.classes;
  v_previous_id bigint;
  v_action_id bigint;
  v_ledger_id bigint;
begin
  if v_person is null then raise exception 'Necesitas un perfil de alumno activo.' using errcode='42501'; end if;
  v_class:=private.bz_validate_next_class(v_person,p_class_id);
  select c.id into v_previous_id
  from public.classes c join public.class_participants cp on cp.class_id=c.id and cp.person_id=v_person
  where c.status='finished' and cp.attendance_status='present' and c.scheduled_start_at<v_class.scheduled_start_at
  order by c.scheduled_start_at desc limit 1;
  if v_previous_id is null then raise exception 'Todavía no hay una clase anterior que repasar.' using errcode='22023'; end if;
  insert into public.bz_action_events(person_id,action_key,local_date,class_id,idempotency_key,evidence)
  values(v_person,'previous_class_review',v_date,p_class_id,'bz-action:review:'||v_person||':'||v_date,
    jsonb_build_object('next_class_id',p_class_id,'previous_class_id',v_previous_id))
  on conflict(idempotency_key) do nothing returning id into v_action_id;
  v_ledger_id:=private.bz_award(v_person,'previous_class_review','class',p_class_id::text,
    'bz:review:'||v_person||':'||v_date,jsonb_build_object('next_class_id',p_class_id,'previous_class_id',v_previous_id,'local_date',v_date),now());
  return jsonb_build_object('class_id',p_class_id,'previous_class_id',v_previous_id,'local_date',v_date,'action_created',v_action_id is not null,'points_awarded',v_ledger_id is not null);
end;
$$;

create or replace function public.bz_choose_next_class_content(p_class_id bigint,p_content_id bigint)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_person bigint:=(select private.current_person_id());
  v_date date:=(select private.bz_local_date());
  v_class public.classes;
  v_content public.teaching_contents;
  v_action_id bigint;
  v_ledger_id bigint;
  v_request_id bigint;
begin
  if v_person is null then raise exception 'Necesitas un perfil de alumno activo.' using errcode='42501'; end if;
  v_class:=private.bz_validate_next_class(v_person,p_class_id);
  select * into v_content from public.teaching_contents
  where id=p_content_id and active and completion_status='complete' and publication_status='published' and visibility='student';
  if not found then raise exception 'Ese contenido no está disponible para el alumno.' using errcode='42501'; end if;

  select id into v_request_id from public.class_preparation_requests
  where class_id=p_class_id and person_id=v_person and request_type='content'
  order by created_at desc limit 1 for update;
  if v_request_id is null then
    insert into public.class_preparation_requests(class_id,person_id,request_type,content_id,body,created_by)
    values(p_class_id,v_person,'content',p_content_id,v_content.title,(select auth.uid())) returning id into v_request_id;
  else
    update public.class_preparation_requests set content_id=p_content_id,body=v_content.title,updated_at=now(),created_by=(select auth.uid())
    where id=v_request_id;
  end if;

  insert into public.bz_action_events(person_id,action_key,local_date,class_id,content_id,idempotency_key,evidence)
  values(v_person,'next_class_content_choice',v_date,p_class_id,p_content_id,
    'bz-action:content-choice:'||v_person||':'||p_class_id,jsonb_build_object('class_id',p_class_id,'content_id',p_content_id))
  on conflict(idempotency_key) do update set content_id=excluded.content_id,evidence=excluded.evidence,updated_at=now()
  returning id into v_action_id;

  v_ledger_id:=private.bz_award(v_person,'next_class_content_choice','class',p_class_id::text,
    'bz:content-choice:'||v_person||':'||p_class_id,jsonb_build_object('class_id',p_class_id,'content_id',p_content_id),now());
  return jsonb_build_object('class_id',p_class_id,'content_id',p_content_id,'request_id',v_request_id,'action_id',v_action_id,'points_awarded',v_ledger_id is not null);
end;
$$;

create or replace function public.bz_snapshot()
returns jsonb
language plpgsql
stable
security definer
set search_path=''
as $$
declare
  v_person bigint:=(select private.current_person_id());
  v_date date:=(select private.bz_local_date());
  v_next_class bigint;
  v_next_start timestamptz;
  v_selected_content bigint;
begin
  if v_person is null then raise exception 'Necesitas un perfil de alumno activo.' using errcode='42501'; end if;
  select c.id,c.scheduled_start_at into v_next_class,v_next_start
  from public.classes c join public.class_participants cp on cp.class_id=c.id and cp.person_id=v_person
  where c.scheduled_start_at>now() and c.status not in ('finished','cancelled') and cp.attendance_status<>'absent'
  order by c.scheduled_start_at limit 1;
  if v_next_class is not null then
    select r.content_id into v_selected_content from public.class_preparation_requests r
    where r.class_id=v_next_class and r.person_id=v_person and r.request_type='content'
    order by r.updated_at desc limit 1;
  end if;
  return jsonb_build_object(
    'person_id',v_person,
    'balance_points',coalesce((select sum(l.points_delta) from public.bz_point_ledger l where l.person_id=v_person),0),
    'earned_points',coalesce((select sum(l.points_delta) from public.bz_point_ledger l where l.person_id=v_person and l.points_delta>0),0),
    'spent_points',coalesce((select -sum(l.points_delta) from public.bz_point_ledger l where l.person_id=v_person and l.points_delta<0),0),
    'today',v_date,
    'daily_login_recorded',exists(select 1 from public.bz_action_events a where a.person_id=v_person and a.action_key='daily_login' and a.local_date=v_date),
    'previous_review_recorded',exists(select 1 from public.bz_action_events a where a.person_id=v_person and a.action_key='previous_class_review' and a.local_date=v_date),
    'next_class',case when v_next_class is null then null else jsonb_build_object('id',v_next_class,'scheduled_start_at',v_next_start,'selected_content_id',v_selected_content) end,
    'rules',(select coalesce(jsonb_agg(jsonb_build_object('rule_key',r.rule_key,'label',r.label,'description',r.description,'points',r.points,'active',r.active) order by r.sort_order,r.rule_key),'[]'::jsonb) from public.bz_point_rules r),
    'recent_ledger',(select coalesce(jsonb_agg(x order by x.created_at desc,x.id desc),'[]'::jsonb) from (select l.id,l.rule_key,l.entry_type,l.points_delta,l.source_type,l.source_id,l.detail,l.created_at from public.bz_point_ledger l where l.person_id=v_person order by l.created_at desc,l.id desc limit 30) x),
    'rewards',(select coalesce(jsonb_agg(jsonb_build_object('id',r.id,'name',r.name,'description',r.description,'cost_points',r.cost_points,'discount_kind',r.discount_kind,'discount_value',r.discount_value,'currency',r.currency) order by r.sort_order,r.id),'[]'::jsonb) from public.bz_rewards r where r.active),
    'redemptions',(select coalesce(jsonb_agg(x order by x.created_at desc,x.id desc),'[]'::jsonb) from (select d.id,d.reward_id,d.reward_name,d.cost_points,d.discount_kind,d.discount_value,d.currency,d.coupon_code,d.status,d.created_at from public.bz_reward_redemptions d where d.person_id=v_person order by d.created_at desc,d.id desc limit 20) x)
  );
end;
$$;

create or replace function public.bz_redeem_reward(p_reward_id bigint)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_person bigint:=(select private.current_person_id());
  v_reward public.bz_rewards;
  v_balance bigint;
  v_redemption_id bigint;
  v_code text;
begin
  if v_person is null then raise exception 'Necesitas un perfil de alumno activo.' using errcode='42501'; end if;
  perform pg_advisory_xact_lock(hashtextextended('bz-person:'||v_person,0));
  select * into v_reward from public.bz_rewards where id=p_reward_id and active for share;
  if not found then raise exception 'La recompensa ya no está disponible.' using errcode='P0002'; end if;
  select coalesce(sum(points_delta),0) into v_balance from public.bz_point_ledger where person_id=v_person;
  if v_balance<v_reward.cost_points then raise exception 'No tienes suficientes BZ Points para esta recompensa.' using errcode='22023'; end if;
  v_code:='CYA-'||upper(substr(md5(v_person::text||':'||p_reward_id||':'||clock_timestamp()::text||':'||random()::text),1,10));
  insert into public.bz_reward_redemptions(person_id,reward_id,reward_name,cost_points,discount_kind,discount_value,currency,coupon_code)
  values(v_person,v_reward.id,v_reward.name,v_reward.cost_points,v_reward.discount_kind,v_reward.discount_value,v_reward.currency,v_code)
  returning id into v_redemption_id;
  insert into public.bz_point_ledger(person_id,rule_key,entry_type,points_delta,source_type,source_id,idempotency_key,detail,created_by)
  values(v_person,null,'redeem',-v_reward.cost_points,'reward_redemption',v_redemption_id::text,'bz:redemption:'||v_redemption_id,
    jsonb_build_object('reward_id',v_reward.id,'reward_name',v_reward.name,'coupon_code',v_code),(select auth.uid()));
  return jsonb_build_object('redemption_id',v_redemption_id,'coupon_code',v_code,'reward_name',v_reward.name,'cost_points',v_reward.cost_points,'balance_points',v_balance-v_reward.cost_points);
end;
$$;

create or replace function public.admin_bz_save_rule(p_rule_key text,p_points integer,p_active boolean)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_rule public.bz_point_rules;
begin
  if not (select private.is_admin()) then raise exception 'Solo administración puede configurar BZ Points.' using errcode='42501'; end if;
  if p_points is null or p_points<0 or p_points>1000000 then raise exception 'Los puntos no son válidos.' using errcode='22023'; end if;
  update public.bz_point_rules set points=p_points,active=coalesce(p_active,false),updated_by=(select auth.uid()),updated_at=now()
  where rule_key=p_rule_key returning * into v_rule;
  if not found then raise exception 'La regla BZ no existe.' using errcode='P0002'; end if;
  return to_jsonb(v_rule);
end;
$$;

create or replace function public.admin_bz_save_reward(
  p_reward_id bigint,
  p_name text,
  p_description text,
  p_cost_points integer,
  p_discount_kind text,
  p_discount_value integer,
  p_active boolean default true
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_reward public.bz_rewards; v_name text:=nullif(btrim(coalesce(p_name,'')),'');
begin
  if not (select private.is_admin()) then raise exception 'Solo administración puede configurar recompensas.' using errcode='42501'; end if;
  if v_name is null then raise exception 'El nombre es obligatorio.' using errcode='22023'; end if;
  if coalesce(p_cost_points,0)<=0 then raise exception 'El coste en puntos debe ser mayor que cero.' using errcode='22023'; end if;
  if p_discount_kind not in ('fixed_cents','percent') or coalesce(p_discount_value,0)<=0 or (p_discount_kind='percent' and p_discount_value>100) then
    raise exception 'Configura un descuento válido.' using errcode='22023';
  end if;
  if p_reward_id is null then
    insert into public.bz_rewards(reward_key,name,description,cost_points,discount_kind,discount_value,active,created_by,updated_by)
    values('reward-'||substr(md5(clock_timestamp()::text||random()::text),1,16),v_name,nullif(btrim(coalesce(p_description,'')),''),p_cost_points,p_discount_kind,p_discount_value,coalesce(p_active,true),(select auth.uid()),(select auth.uid()))
    returning * into v_reward;
  else
    update public.bz_rewards set name=v_name,description=nullif(btrim(coalesce(p_description,'')),''),cost_points=p_cost_points,
      discount_kind=p_discount_kind,discount_value=p_discount_value,active=coalesce(p_active,false),updated_by=(select auth.uid()),updated_at=now()
    where id=p_reward_id returning * into v_reward;
    if not found then raise exception 'La recompensa no existe.' using errcode='P0002'; end if;
  end if;
  return to_jsonb(v_reward);
end;
$$;

create or replace function public.admin_bz_adjust_points(p_person_id bigint,p_points integer,p_note text)
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare v_id bigint; v_key text;
begin
  if not (select private.is_admin()) then raise exception 'Solo administración puede ajustar BZ Points.' using errcode='42501'; end if;
  if p_points is null or p_points=0 or abs(p_points)>1000000 then raise exception 'El ajuste no es válido.' using errcode='22023'; end if;
  if not exists(select 1 from public.people where id=p_person_id and active) then raise exception 'La persona no existe.' using errcode='P0002'; end if;
  v_key:='bz:adjustment:'||p_person_id||':'||md5(clock_timestamp()::text||random()::text);
  insert into public.bz_point_ledger(person_id,entry_type,points_delta,source_type,idempotency_key,detail,created_by)
  values(p_person_id,'adjustment',p_points,'admin_adjustment',v_key,jsonb_build_object('note',nullif(btrim(coalesce(p_note,'')),'')),(select auth.uid()))
  returning id into v_id;
  return jsonb_build_object('ledger_id',v_id,'person_id',p_person_id,'points_delta',p_points);
end;
$$;

create or replace view public.bz_person_statistics with (security_invoker=true) as
