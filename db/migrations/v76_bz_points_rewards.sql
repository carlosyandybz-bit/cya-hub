-- PR-B / v76 — BZ Points and rewards.
-- Separate from pedagogical evaluation points. All balances derive from an immutable ledger.
-- No historical class/credit/exercise backfill: rule active_from gates automatic reconciliation.

create table if not exists public.bz_point_rules (
  rule_key text primary key,
  label text not null,
  description text,
  points integer not null check (points between 0 and 1000000),
  trigger_mode text not null check (trigger_mode in ('automatic','student_action')),
  active boolean not null default true,
  active_from timestamptz not null default now(),
  sort_order integer not null default 100,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.bz_point_ledger (
  id bigint generated by default as identity primary key,
  person_id bigint not null references public.people(id) on delete restrict,
  rule_key text references public.bz_point_rules(rule_key) on delete restrict,
  entry_type text not null check (entry_type in ('earn','redeem','adjustment','reversal')),
  points_delta integer not null check (points_delta <> 0 and points_delta between -1000000 and 1000000),
  source_type text not null,
  source_id text,
  idempotency_key text not null unique,
  detail jsonb not null default '{}'::jsonb,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);
create index if not exists bz_point_ledger_person_created_idx on public.bz_point_ledger(person_id,created_at desc,id desc);
create index if not exists bz_point_ledger_rule_idx on public.bz_point_ledger(rule_key,created_at desc);

create table if not exists public.bz_action_events (
  id bigint generated by default as identity primary key,
  person_id bigint not null references public.people(id) on delete cascade,
  action_key text not null check (action_key in ('daily_login','previous_class_review','next_class_content_choice')),
  local_date date not null,
  class_id bigint references public.classes(id) on delete cascade,
  content_id bigint references public.teaching_contents(id) on delete set null,
  idempotency_key text not null unique,
  evidence jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists bz_action_events_person_date_idx on public.bz_action_events(person_id,local_date desc,action_key);

create table if not exists public.bz_rewards (
  id bigint generated by default as identity primary key,
  reward_key text not null unique,
  name text not null,
  description text,
  reward_type text not null default 'discount_coupon' check (reward_type='discount_coupon'),
  cost_points integer not null check (cost_points > 0),
  discount_kind text not null check (discount_kind in ('fixed_cents','percent')),
  discount_value integer not null check (discount_value > 0),
  currency text not null default 'EUR' check (char_length(currency)=3),
  active boolean not null default true,
  sort_order integer not null default 100,
  metadata jsonb not null default '{}'::jsonb,
  created_by uuid references auth.users(id) on delete set null,
  updated_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((discount_kind='percent' and discount_value <= 100) or discount_kind='fixed_cents')
);

create table if not exists public.bz_reward_redemptions (
  id bigint generated by default as identity primary key,
  person_id bigint not null references public.people(id) on delete restrict,
  reward_id bigint not null references public.bz_rewards(id) on delete restrict,
  reward_name text not null,
  cost_points integer not null check (cost_points > 0),
  discount_kind text not null check (discount_kind in ('fixed_cents','percent')),
  discount_value integer not null check (discount_value > 0),
  currency text not null,
  coupon_code text not null unique,
  status text not null default 'issued' check (status in ('issued','redeemed','cancelled')),
  redeemed_at timestamptz,
  cancelled_at timestamptz,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists bz_reward_redemptions_person_created_idx on public.bz_reward_redemptions(person_id,created_at desc,id desc);

