create or replace function private.bz_local_date()
returns date
language plpgsql
stable
security definer
set search_path=''
as $$
declare
  v_timezone text;
begin
  select coalesce(p.timezone,'Europe/Madrid') into v_timezone
  from public.user_preferences p
  where p.user_id=(select auth.uid());
  v_timezone:=coalesce(v_timezone,'Europe/Madrid');
  begin
    return (now() at time zone v_timezone)::date;
  exception when invalid_parameter_value then
    return (now() at time zone 'Europe/Madrid')::date;
  end;
end;
$$;

create or replace function private.bz_award(
  p_person_id bigint,
  p_rule_key text,
  p_source_type text,
  p_source_id text,
  p_idempotency_key text,
  p_detail jsonb default '{}'::jsonb,
  p_event_at timestamptz default now()
)
returns bigint
language plpgsql
security definer
set search_path=''
as $$
declare
  v_rule public.bz_point_rules;
  v_id bigint;
begin
  if p_person_id is null or p_idempotency_key is null or nullif(btrim(p_idempotency_key),'') is null then
    return null;
  end if;
  select * into v_rule from public.bz_point_rules where rule_key=p_rule_key;
  if not found or not v_rule.active or v_rule.points<=0 or coalesce(p_event_at,now()) < v_rule.active_from then
    return null;
  end if;
  if not exists(select 1 from public.people p where p.id=p_person_id and p.active) then return null; end if;
  insert into public.bz_point_ledger(person_id,rule_key,entry_type,points_delta,source_type,source_id,idempotency_key,detail,created_by)
  values(p_person_id,p_rule_key,'earn',v_rule.points,p_source_type,p_source_id,p_idempotency_key,
         coalesce(p_detail,'{}'::jsonb)||jsonb_build_object('rule_label',v_rule.label,'rule_points',v_rule.points),
         (select auth.uid()))
  on conflict(idempotency_key) do nothing
  returning id into v_id;
  return v_id;
end;
$$;

create or replace function private.bz_reconcile_registration(p_person_id bigint)
returns void
language plpgsql
security definer
set search_path=''
as $$
declare v_event_at timestamptz;
begin
  select greatest(p.updated_at,sp.created_at) into v_event_at
  from public.people p join public.student_profiles sp on sp.person_id=p.id and sp.active
  where p.id=p_person_id and p.active and p.auth_user_id is not null;
  if v_event_at is null then return; end if;
  perform private.bz_award(p_person_id,'registration','person',p_person_id::text,'bz:registration:'||p_person_id,
    jsonb_build_object('person_id',p_person_id),v_event_at);
end;
$$;

create or replace function private.bz_reconcile_credit_grant(p_grant_id bigint)
returns void
language plpgsql
security definer
set search_path=''
as $$
declare v_grant public.credit_grants; v_member record;
begin
  select * into v_grant from public.credit_grants where id=p_grant_id;
  if not found or v_grant.payment_status<>'paid' or v_grant.price_cents<=0 then return; end if;
  for v_member in select person_id from public.credit_grant_members where grant_id=p_grant_id loop
    perform private.bz_award(v_member.person_id,'bonus_purchase','credit_grant',p_grant_id::text,
      'bz:bonus:'||p_grant_id||':'||v_member.person_id,
      jsonb_build_object('grant_id',p_grant_id,'price_cents',v_grant.price_cents,'modality',v_grant.modality),v_grant.purchased_at);
  end loop;
end;
$$;

create or replace function private.bz_reconcile_class(p_class_id bigint)
returns void
language plpgsql
security definer
set search_path=''
as $$
declare v_class public.classes; v_participant record;
begin
  select * into v_class from public.classes where id=p_class_id;
  if not found or v_class.status<>'finished' or v_class.administrative_finished_at is null then return; end if;
  for v_participant in select person_id from public.class_participants where class_id=p_class_id and attendance_status='present' loop
    perform private.bz_award(v_participant.person_id,'class_attended','class',p_class_id::text,
      'bz:class:'||p_class_id||':'||v_participant.person_id,
      jsonb_build_object('class_id',p_class_id,'duration_minutes',v_class.actual_duration_minutes),v_class.administrative_finished_at);
  end loop;
end;
$$;

create or replace function private.bz_reconcile_exercise(p_person_id bigint,p_content_id bigint)
returns void
language plpgsql
security definer
set search_path=''
as $$
declare v_event_at timestamptz;
begin
  if not exists(select 1 from public.teaching_contents t where t.id=p_content_id and t.active and t.content_type='exercise') then return; end if;
  select max(event_at) into v_event_at from (
    select a.completed_at as event_at
    from public.student_content_assignments a
    where a.person_id=p_person_id and a.content_id=p_content_id and a.assignment_status='completed' and a.completed_at is not null
    union all
    select e.created_at
    from public.class_content_events e
    where e.person_id=p_person_id and e.content_id=p_content_id and e.event_type='exercise_completed'
  ) q;
  if v_event_at is null then return; end if;
  perform private.bz_award(p_person_id,'exercise_completed','teaching_content',p_content_id::text,
    'bz:exercise:'||p_person_id||':'||p_content_id,
    jsonb_build_object('person_id',p_person_id,'content_id',p_content_id),v_event_at);
end;
$$;

