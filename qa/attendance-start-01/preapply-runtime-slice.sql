    check (attendance_status <> 'present' or absence_reason is null),
  constraint class_attendance_events_correction_contract
    check (
      (source='correction' and supersedes_event_id is not null and nullif(btrim(correction_reason),'') is not null)
      or
      (source<>'correction' and supersedes_event_id is null and correction_reason is null)
    )
