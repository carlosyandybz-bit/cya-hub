create or replace function public.correct_class_attendance(
  p_class_id bigint,
  p_person_id bigint,
  p_attendance_status text,
  p_absence_reason text,
  p_reason text
)
returns public.class_attendance_events
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_class public.classes;
  v_previous public.class_attendance_events;
begin
  if not (select private.is_staff()) then
    raise exception 'No tienes permiso para corregir asistencia.' using errcode='42501';
  end if;
  if nullif(btrim(p_reason),'') is null then
    raise exception 'Indica el motivo de la corrección.' using errcode='22023';
  end if;
  select * into v_class from public.classes where id=p_class_id for update;
  if not found then raise exception 'La clase no existe.' using errcode='P0002'; end if;
  if v_class.administrative_finished_at is not null then
    raise exception 'Reabre primero el cierre administrativo antes de corregir asistencia para mantener coherencia económica.' using errcode='22023';
  end if;
  perform 1 from public.class_participants where class_id=p_class_id and person_id=p_person_id for update;
  if not found then raise exception 'La persona no participa en esta clase.' using errcode='22023'; end if;
  select * into v_previous from private.class_attendance_latest_event(p_class_id,p_person_id);
  if v_previous.id is null then
    raise exception 'No existe una asistencia durable que corregir.' using errcode='P0002';
  end if;
  return private.record_class_attendance_fact(
    p_class_id,p_person_id,p_attendance_status,p_absence_reason,v_previous.effective_at,
    'correction',v_previous.id,p_reason,
    jsonb_build_object(
      'before',jsonb_build_object('attendance_status',v_previous.attendance_status,'absence_reason',v_previous.absence_reason),
      'after',jsonb_build_object('attendance_status',p_attendance_status,'absence_reason',p_absence_reason)
    )
  );
end;
$function$;

