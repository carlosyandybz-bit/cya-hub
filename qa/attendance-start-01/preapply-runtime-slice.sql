create table public.class_attendance_events (
  id bigint generated by default as identity primary key,
  class_id bigint not null references public.classes(id) on delete restrict,
  person_id bigint not null references public.people(id) on delete restrict,
  attendance_status text not null check (attendance_status in ('present','absent')),
  absence_reason text check (absence_reason is null or absence_reason in ('no_show','excused','cancelled_by_student','other')),
