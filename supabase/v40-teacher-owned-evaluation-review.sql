-- 5) Preparar una revisión crea preguntas sin marcarlas como revisadas.
-- Mantiene la puerta Bachata -> Bachazouk de v39.
create or replace function public.prepare_post_class_evaluation(p_class_id bigint,p_person_id bigint)
returns public.evaluation_sessions
language plpgsql
set search_path=''
as $$
declare
  v_class public.classes;
  v_style bigint;
  v_style_key text;
  v_role bigint;
  v_level bigint;
  v_session public.evaluation_sessions;
  v_kind text;
  v_progress public.student_aptitude_progress;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para evaluar alumnos.' using errcode='42501'; end if;
  select * into v_class from public.classes where id=p_class_id for update;
  if not found then raise exception 'La clase no existe.' using errcode='P0002'; end if;
  if v_class.status<>'finished' or v_class.administrative_finished_at is null then raise exception 'La evaluación se realiza después de terminar la parte administrativa de la clase.' using errcode='22023'; end if;
  if v_class.pedagogy_closed_at is not null then raise exception 'La clase ya está cerrada pedagógicamente.' using errcode='22023'; end if;

  select v_class.style_term_id,style.term_key,cp.role_term_id,cp.level_term_id
  into v_style,v_style_key,v_role,v_level
  from public.class_participants cp
  left join public.catalog_terms style on style.id=v_class.style_term_id and style.taxonomy='dance_style'
  where cp.class_id=p_class_id and cp.person_id=p_person_id;
  if not found or v_style is null or v_style_key is null or v_role is null or v_level is null then raise exception 'La clase no tiene estilo, rol o nivel suficiente para evaluar.' using errcode='22023'; end if;

  if v_style_key='bachazouk'
     and not exists(select 1 from public.evaluation_sessions s where s.person_id=p_person_id and s.style_term_id=v_style and s.role_term_id=v_role and s.status='completed')
     and not private.initial_evaluation_is_complete(p_person_id,'bachata',v_role) then
    raise exception 'Completa primero toda la evaluación inicial de Bachata antes de abrir Bachazouk.' using errcode='22023';
  end if;

  perform public.ensure_student_aptitude_progress(p_person_id,v_style,v_role,v_level);

  select * into v_session
  from public.evaluation_sessions
  where class_id=p_class_id and person_id=p_person_id and style_term_id=v_style and role_term_id=v_role and level_term_id=v_level
  order by id desc limit 1;

  if not found then
    v_kind:=case when exists(
      select 1 from public.evaluation_sessions s
      where s.person_id=p_person_id and s.style_term_id=v_style and s.role_term_id=v_role and s.status='completed'
    ) then 'class' else 'initial' end;
    insert into public.evaluation_sessions(person_id,class_id,style_term_id,role_term_id,level_term_id,evaluation_kind,status,evaluated_by,started_at)
    values(p_person_id,p_class_id,v_style,v_role,v_level,v_kind,'draft',(select auth.uid()),now())
    returning * into v_session;
  elsif v_session.status='completed' then
    return v_session;
  end if;

  for v_progress in
    select * from public.student_aptitude_progress p
    where p.person_id=p_person_id and p.style_term_id=v_style and p.role_term_id=v_role and p.level_term_id=v_level
  loop
    insert into public.student_evaluations(
      session_id,person_id,class_id,style_term_id,role_term_id,level_term_id,
      aptitude_term_id,evaluation_kind,score,note,evaluated_by,
      answer_scale_term_id,descriptor_id,answer_label,reviewed_at,reviewed_by
    )
    values(
      v_session.id,p_person_id,p_class_id,v_style,v_role,v_level,
      v_progress.aptitude_term_id,v_session.evaluation_kind,v_progress.effective_score,
      null,(select auth.uid()),null,null,null,null,null
    )
    on conflict(session_id,aptitude_term_id) where session_id is not null do nothing;

    update public.student_aptitude_progress
    set last_evaluation_session_id=v_session.id,updated_at=now()
    where id=v_progress.id;
  end loop;

  return v_session;
end $$;

-- 6) Cerrar exige que TODAS las preguntas hayan sido revisadas por un profesor.
create or replace function public.complete_post_class_evaluation(p_session_id bigint)
returns public.evaluation_sessions
language plpgsql
set search_path=''
as $$
declare
  v_session public.evaluation_sessions;
  v_expected integer;
  v_reviewed integer;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para cerrar evaluaciones.' using errcode='42501'; end if;
  select * into v_session from public.evaluation_sessions where id=p_session_id for update;
  if not found then raise exception 'La evaluación no existe.' using errcode='P0002'; end if;
  if v_session.status='completed' then return v_session; end if;
  if v_session.class_id is null then raise exception 'Esta operación es solo para revisiones posteriores a una clase.' using errcode='22023'; end if;
  if not exists(
    select 1 from public.classes c
    where c.id=v_session.class_id and c.status='finished' and c.administrative_finished_at is not null and c.pedagogy_closed_at is null
  ) then raise exception 'La evaluación debe cerrarse después de la parte administrativa y antes del cierre pedagógico.' using errcode='22023'; end if;

  select count(*) into v_expected
  from public.student_aptitude_progress p
  where p.person_id=v_session.person_id
    and p.style_term_id=v_session.style_term_id
    and p.role_term_id=v_session.role_term_id
    and p.level_term_id=v_session.level_term_id;

  select count(*) into v_reviewed
  from public.student_evaluations e
  where e.session_id=v_session.id and e.reviewed_at is not null;

  if v_expected=0 then raise exception 'Esta evaluación no tiene preguntas configuradas.' using errcode='22023'; end if;
  if v_reviewed<v_expected then
    raise exception 'Revisa todas las preguntas antes de cerrar la evaluación (% de %).',v_reviewed,v_expected using errcode='22023';
  end if;

  update public.evaluation_sessions
  set status='completed',completed_at=now(),updated_at=now()
  where id=v_session.id
  returning * into v_session;

  return v_session;
end $$;

