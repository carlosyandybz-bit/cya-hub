create or replace function private.backup_tables_for_domain(p_domain text)
returns text[]
language sql
stable
set search_path=''
as $$
  select case
    when p_domain in ('teaching','settings','complete') then
      case
        when 'teaching_content_evaluation_recommendations'=any(private.backup_tables_for_domain_pre_v40(p_domain))
          then private.backup_tables_for_domain_pre_v40(p_domain)
        else array_append(private.backup_tables_for_domain_pre_v40(p_domain),'teaching_content_evaluation_recommendations')
      end
    else private.backup_tables_for_domain_pre_v40(p_domain)
  end;
$$;
