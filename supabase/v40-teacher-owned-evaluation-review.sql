create or replace function private.validate_teaching_content_evaluation_recommendation()
returns trigger language plpgsql set search_path='' as $$
begin
  if not exists(select 1 from public.catalog_terms where id=new.style_term_id and taxonomy='dance_style' and active) then raise exception 'El estilo de recomendación no es válido.' using errcode='22023'; end if;
  if not exists(select 1 from public.catalog_terms where id=new.role_term_id and taxonomy='dance_role' and active) then raise exception 'El rol de recomendación no es válido.' using errcode='22023'; end if;
  if not exists(select 1 from public.catalog_terms where id=new.level_term_id and taxonomy='dance_level' and active) then raise exception 'El nivel de recomendación no es válido.' using errcode='22023'; end if;
  if not exists(select 1 from public.catalog_terms where id=new.aptitude_term_id and taxonomy='aptitude' and active) then raise exception 'La aptitud de recomendación no es válida.' using errcode='22023'; end if;
  if not exists(select 1 from public.teaching_contents where id=new.content_id and active) then raise exception 'El contenido no está disponible.' using errcode='22023'; end if;
  new.updated_at:=now();
  return new;
end $$;
drop trigger if exists trg_validate_teaching_content_eval_recommendation on public.teaching_content_evaluation_recommendations;
create trigger trg_validate_teaching_content_eval_recommendation
before insert or update on public.teaching_content_evaluation_recommendations
for each row execute function private.validate_teaching_content_evaluation_recommendation();

