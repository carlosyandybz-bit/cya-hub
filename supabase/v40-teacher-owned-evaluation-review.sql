create or replace function private.validate_student_evaluation_answer()
returns trigger language plpgsql set search_path='' as $$
begin
  if new.reviewed_at is not null then
    if (new.answer_scale_term_id is null) = (new.descriptor_id is null) then
      raise exception 'Una revisión debe guardar exactamente una respuesta.' using errcode='22023';
    end if;
    if new.answer_scale_term_id is not null and not exists(
      select 1 from public.catalog_terms t
      where t.id=new.answer_scale_term_id and t.taxonomy='evaluation_scale' and t.active
    ) then
      raise exception 'La respuesta de evaluación no es válida.' using errcode='22023';
    end if;
  end if;
  return new;
end $$;
drop trigger if exists trg_validate_student_evaluation_answer on public.student_evaluations;
create trigger trg_validate_student_evaluation_answer
before insert or update on public.student_evaluations
for each row execute function private.validate_student_evaluation_answer();

