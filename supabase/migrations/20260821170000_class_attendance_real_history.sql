-- CLASS-ATTENDANCE-01 — durable real attendance history
-- R1 Wave 1, STAGING-first. No historical attendance backfill is performed here.

create table if not exists public.class_attendance_events (
  id bigint generated by default as identity primary key,
  class_id bigint not null references public.classes(id) on delete restrict,
  person_id bigint not null references public.people(id) on delete restrict,
  attendance_status text not null check (attendance_status in ('present','absent')),
  absence_reason text null check (absence_reason is null or absence_reason in ('no_show','excused','cancelled_by_student','other')),
  effective_at timestamptz not null,
  recorded_at timestamptz not null default now(),
  recorded_by uuid null references auth.users(id) on delete set null,
  source text not null check (source in ('administrative_finish','explicit_record','correction')),
  supersedes_event_id bigint null references public.class_attendance_events(id) on delete restrict,
  correction_reason text null,
  detail jsonb not null default '{}'::jsonb,
  constraint class_attendance_events_present_has_no_absence_reason
    check (attendance_status <> 'present' or absence_reason is null),
  constraint class_attendance_events_correction_contract
    check ((source='correction' and supersedes_event_id is not null and nullif(btrim(correction_reason),'') is not null)
       or (source<>'correction' and supersedes_event_id is null and correction_reason is null))
);

create index if not exists class_attendance_events_person_effective_idx
  on public.class_attendance_events(person_id,effective_at desc,id desc);
create index if not exists class_attendance_events_class_person_latest_idx
  on public.class_attendance_events(class_id,person_id,recorded_at desc,id desc);
create unique index if not exists class_attendance_events_supersedes_once_uidx
  on public.class_attendance_events(supersedes_event_id)
  where supersedes_event_id is not null;

alter table public.class_attendance_events enable row level security;

drop policy if exists class_attendance_events_read on public.class_attendance_events;
create policy class_attendance_events_read
on public.class_attendance_events
for select to authenticated
using (
  (select private.is_staff())
  or person_id=(select private.current_person_id())
);

revoke insert,update,delete,truncate,references,trigger on public.class_attendance_events from anon,authenticated;
grant select on public.class_attendance_events to authenticated;

