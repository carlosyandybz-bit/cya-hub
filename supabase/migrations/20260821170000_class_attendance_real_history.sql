create or replace function private.record_class_attendance_fact(
  p_class_id bigint,
  p_person_id bigint,
  p_attendance_status text,
  p_absence_reason text,
  p_effective_at timestamptz,
  p_source text,
  p_supersedes_event_id bigint default null,
  p_correction_reason text default null,
  p_detail jsonb default '{}'::jsonb
)
returns public.class_attendance_events
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_existing public.class_attendance_events;
  v_event public.class_attendance_events;
  v_actor uuid:=(select auth.uid());
begin
  if p_attendance_status not in ('present','absent') then
    raise exception 'Asistencia no válida.' using errcode='22023';
  end if;
  if p_attendance_status='present' and p_absence_reason is not null then
    raise exception 'Una asistencia presente no admite motivo de ausencia.' using errcode='22023';
  end if;
  if p_attendance_status='absent' and p_absence_reason is not null
     and p_absence_reason not in ('no_show','excused','cancelled_by_student','other') then
    raise exception 'Motivo de ausencia no válido.' using errcode='22023';
  end if;
  if not exists(
    select 1 from public.class_participants cp
    where cp.class_id=p_class_id and cp.person_id=p_person_id
  ) then
    raise exception 'La persona no participa en esta clase.' using errcode='22023';
  end if;

  select * into v_existing
  from public.class_attendance_events e
  where e.class_id=p_class_id and e.person_id=p_person_id
  order by e.recorded_at desc,e.id desc
  limit 1
  for update;

  if p_source<>'correction' and v_existing.id is not null then
    if v_existing.attendance_status=p_attendance_status
       and v_existing.absence_reason is not distinct from p_absence_reason then
      return v_existing;
    end if;
    raise exception 'La asistencia ya fue registrada; utiliza correct_class_attendance().' using errcode='22023';
  end if;

  if p_source='correction' then
    if v_existing.id is null or p_supersedes_event_id is distinct from v_existing.id then
      raise exception 'La corrección debe superseder el último hecho de asistencia.' using errcode='40001';
    end if;
    if nullif(btrim(p_correction_reason),'') is null then
      raise exception 'La corrección requiere motivo.' using errcode='22023';
    end if;
  elsif p_source not in ('administrative_finish','explicit_record') then
    raise exception 'Origen de asistencia no válido.' using errcode='22023';
  end if;

  insert into public.class_attendance_events(
    class_id,person_id,attendance_status,absence_reason,effective_at,recorded_by,
    source,supersedes_event_id,correction_reason,detail
  ) values(
    p_class_id,p_person_id,p_attendance_status,p_absence_reason,p_effective_at,v_actor,
    p_source,p_supersedes_event_id,nullif(btrim(p_correction_reason),''),coalesce(p_detail,'{}'::jsonb)
  ) returning * into v_event;

  insert into public.audit_events(event_type,entity_type,entity_id,summary,detail,actor_user_id)
  values(
    case when p_source='correction' then 'class_attendance_corrected' else 'class_attendance_recorded' end,
    'class_attendance',v_event.id::text,
    case when p_source='correction' then 'Asistencia corregida' else 'Asistencia real registrada' end,
    jsonb_build_object(
      'class_id',p_class_id,'person_id',p_person_id,'attendance_status',p_attendance_status,
      'absence_reason',p_absence_reason,'effective_at',p_effective_at,'source',p_source,
      'supersedes_event_id',p_supersedes_event_id,'correction_reason',nullif(btrim(p_correction_reason),'')
    ),v_actor
  );

  return v_event;
end;
$function$;

create or replace function public.record_class_attendance(
  p_class_id bigint,
  p_person_id bigint,
  p_attendance_status text,
  p_absence_reason text default null
)
returns public.class_attendance_events
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_class public.classes;
begin
  if not (select private.is_staff()) then
    raise exception 'No tienes permiso para registrar asistencia.' using errcode='42501';
  end if;
  select * into v_class from public.classes where id=p_class_id for update;
  if not found then raise exception 'La clase no existe.' using errcode='P0002'; end if;
  if v_class.status<>'active' or v_class.administrative_finished_at is not null then
    raise exception 'La asistencia inicial solo puede registrarse durante una clase activa.' using errcode='22023';
  end if;
  perform 1 from public.class_participants where class_id=p_class_id and person_id=p_person_id for update;
  if not found then raise exception 'La persona no participa en esta clase.' using errcode='22023'; end if;
  return private.record_class_attendance_fact(
    p_class_id,p_person_id,p_attendance_status,p_absence_reason,v_class.scheduled_start_at,
    'explicit_record',null,null,jsonb_build_object('class_status',v_class.status)
  );
end;
$function$;

create or replace function public.correct_class_attendance(
  p_class_id bigint,
  p_person_id bigint,
  p_attendance_status text,
  p_absence_reason text,
  p_reason text
)
returns public.class_attendance_events
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_class public.classes;
  v_previous public.class_attendance_events;
begin
  if not (select private.is_staff()) then
    raise exception 'No tienes permiso para corregir asistencia.' using errcode='42501';
  end if;
  if nullif(btrim(p_reason),'') is null then
    raise exception 'Indica el motivo de la corrección.' using errcode='22023';
  end if;
  select * into v_class from public.classes where id=p_class_id for update;
  if not found then raise exception 'La clase no existe.' using errcode='P0002'; end if;
  if v_class.administrative_finished_at is not null then
    raise exception 'Reabre primero el cierre administrativo antes de corregir asistencia para mantener coherencia económica.' using errcode='22023';
  end if;
  perform 1 from public.class_participants where class_id=p_class_id and person_id=p_person_id for update;
  if not found then raise exception 'La persona no participa en esta clase.' using errcode='22023'; end if;
  select * into v_previous from private.class_attendance_latest_event(p_class_id,p_person_id);
  if v_previous.id is null then
    raise exception 'No existe una asistencia durable que corregir.' using errcode='P0002';
  end if;
  return private.record_class_attendance_fact(
    p_class_id,p_person_id,p_attendance_status,p_absence_reason,v_previous.effective_at,
    'correction',v_previous.id,p_reason,
    jsonb_build_object(
      'before',jsonb_build_object('attendance_status',v_previous.attendance_status,'absence_reason',v_previous.absence_reason),
      'after',jsonb_build_object('attendance_status',p_attendance_status,'absence_reason',p_absence_reason)
    )
  );
end;
$function$;

revoke all on function public.record_class_attendance(bigint,bigint,text,text) from public,anon;
grant execute on function public.record_class_attendance(bigint,bigint,text,text) to authenticated,service_role;
revoke all on function public.correct_class_attendance(bigint,bigint,text,text,text) from public,anon;
grant execute on function public.correct_class_attendance(bigint,bigint,text,text,text) to authenticated,service_role;

