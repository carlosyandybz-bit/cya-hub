create or replace function private.protect_durable_attendance_projection()
returns trigger
language plpgsql
security definer
set search_path=''
as $function$
begin
  if new.attendance_status is not distinct from old.attendance_status then
    return new;
  end if;
  if exists(
    select 1 from public.class_attendance_events e
    where e.class_id=old.class_id and e.person_id=old.person_id
  ) and pg_trigger_depth()<=1 then
    raise exception 'La asistencia ya tiene historia durable; utiliza correct_class_attendance().' using errcode='22023';
  end if;
  return new;
end;
$function$;

drop trigger if exists class_participants_protect_durable_attendance on public.class_participants;
create trigger class_participants_protect_durable_attendance
before update of attendance_status on public.class_participants
for each row execute function private.protect_durable_attendance_projection();

