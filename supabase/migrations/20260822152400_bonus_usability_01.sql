create or replace function public.edit_credit_grant(
  p_grant_id bigint,
  p_label text,
  p_total_minutes integer,
  p_price_cents integer,
  p_purchased_at timestamptz,
  p_starts_at timestamptz,
  p_expires_at timestamptz,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_grant public.credit_grants;
  v_before jsonb;
  v_after jsonb;
  v_balance integer;
  v_balance_without_refunds integer;
  v_consumed integer;
  v_capacity_delta integer;
  v_reason text := nullif(btrim(p_reason),'');
begin
  if not (select private.is_staff()) then
    raise exception 'No tienes permiso para editar bonos.' using errcode='42501';
  end if;
  if v_reason is null then
    raise exception 'Indica el motivo del cambio.' using errcode='22023';
  end if;
  if p_total_minutes is null or p_total_minutes <= 0 or p_total_minutes > 100000 then
    raise exception 'La capacidad del bono no es válida.' using errcode='22023';
  end if;
  if p_price_cents is null or p_price_cents < 0 then
    raise exception 'El importe no puede ser negativo.' using errcode='22023';
  end if;
  if p_purchased_at is null or p_starts_at is null then
    raise exception 'Compra e inicio son obligatorios.' using errcode='22023';
  end if;
  if p_expires_at is not null and p_expires_at <= p_starts_at then
    raise exception 'La caducidad debe ser posterior al inicio.' using errcode='22023';
  end if;

  select * into v_grant
  from public.credit_grants
  where id=p_grant_id
  for update;
  if not found then raise exception 'El bono no existe.' using errcode='P0002'; end if;
  if v_grant.status='cancelled' or v_grant.payment_status='refunded' then
    raise exception 'Este bono está en estado terminal y no puede editarse.' using errcode='22023';
  end if;

  v_before := to_jsonb(v_grant) || jsonb_build_object(
    'balance_minutes', private.credit_grant_balance_minutes_unchecked(p_grant_id)
  );

  select coalesce(sum(m.delta_minutes) filter (where m.movement_type <> 'refund'),0)::integer
  into v_balance_without_refunds
  from public.credit_movements m
  where m.grant_id=p_grant_id;

  v_consumed := greatest(v_grant.total_minutes - v_balance_without_refunds, 0);
  if p_total_minutes < v_consumed then
    raise exception 'La capacidad no puede quedar por debajo del consumo histórico válido (% min).',v_consumed using errcode='22023';
  end if;

  v_capacity_delta := p_total_minutes - v_grant.total_minutes;
  if v_capacity_delta <> 0 then
    insert into public.credit_movements(
      grant_id,movement_type,delta_minutes,note,created_by,occurred_at,provenance
    ) values (
      p_grant_id,'adjustment',v_capacity_delta,
      'Corrección de capacidad · '||v_reason,(select auth.uid()),now(),
      jsonb_build_object('operation','capacity_edit','old_total_minutes',v_grant.total_minutes,'new_total_minutes',p_total_minutes)
    );
  end if;

  update public.credit_grants
  set label=nullif(btrim(p_label),''),
      total_minutes=p_total_minutes,
      price_cents=p_price_cents,
      purchased_at=p_purchased_at,
      starts_at=p_starts_at,
      expires_at=p_expires_at,
      updated_at=now()
  where id=p_grant_id
  returning * into v_grant;

  v_balance := private.credit_grant_balance_minutes_unchecked(p_grant_id);
  v_after := to_jsonb(v_grant) || jsonb_build_object('balance_minutes',v_balance);

  insert into public.audit_events(event_type,entity_type,entity_id,summary,detail,actor_user_id)
  values(
    'credit_grant_edited','credit_grant',p_grant_id::text,'Bono editado',
    jsonb_build_object('before',v_before,'after',v_after,'reason',v_reason,'valid_consumption_minutes',v_consumed),
    (select auth.uid())
  );

  return jsonb_build_object('grant',to_jsonb(v_grant),'balance_minutes',v_balance,'valid_consumption_minutes',v_consumed);
end;
$$;

create or replace function public.pause_credit_grant(
  p_grant_id bigint,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_grant public.credit_grants;
  v_pause public.credit_grant_pause_periods;
  v_reason text := nullif(btrim(p_reason),'');
  v_before jsonb;
begin
  if not (select private.is_staff()) then
    raise exception 'No tienes permiso para pausar bonos.' using errcode='42501';
  end if;
  if v_reason is null then raise exception 'Indica el motivo de la pausa.' using errcode='22023'; end if;

  select * into v_grant from public.credit_grants where id=p_grant_id for update;
  if not found then raise exception 'El bono no existe.' using errcode='P0002'; end if;
  if v_grant.status <> 'active' or v_grant.payment_status not in ('paid','pending') then
    raise exception 'Este bono está en un estado terminal y no puede pausarse.' using errcode='22023';
  end if;
  if private.credit_grant_balance_minutes_unchecked(p_grant_id) <= 0 then
    raise exception 'Un bono sin saldo no puede pausarse.' using errcode='22023';
  end if;
  if private.credit_grant_effective_expires_at_unchecked(p_grant_id,now()) is not null
     and private.credit_grant_effective_expires_at_unchecked(p_grant_id,now()) <= now() then
    raise exception 'Un bono caducado no puede pausarse.' using errcode='22023';
  end if;
