-- A total refund is terminal, not an "exhausted by use" event. Preserve the
-- existing credit notification producer while preventing a false exhausted notice.
create or replace function private.aud017_notify_student_credit_balance()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_balance integer;
  v_row record;
  v_event text;
  v_title text;
  v_body text;
begin
  if new.movement_type='refund' then return new; end if;
  select coalesce(sum(delta_minutes),0)::integer into v_balance
  from public.credit_movements where grant_id=new.grant_id;
  if v_balance<=0 then
    v_event:='student.credit.exhausted'; v_title:='Tu bono se ha agotado'; v_body:='Ya no quedan minutos disponibles en este bono.';
  elsif v_balance<=60 then
    v_event:='student.credit.low'; v_title:='Te queda poco saldo'; v_body:='Te quedan '||v_balance::text||' minutos disponibles en este bono.';
  else
    return new;
  end if;
  for v_row in
    select distinct p.id as person_id,p.auth_user_id
    from public.credit_grant_members gm
    join public.people p on p.id=gm.person_id
    where gm.grant_id=new.grant_id and p.active and p.auth_user_id is not null
  loop
    perform private.enqueue_notification(
      v_event,v_row.auth_user_id,v_title,v_body,'student:formation','credit_grant',new.grant_id::text,
      jsonb_build_object('audience','student','person_id',v_row.person_id,'grant_id',new.grant_id,'balance_minutes',v_balance)
    );
  end loop;
  return new;
end;
$$;

