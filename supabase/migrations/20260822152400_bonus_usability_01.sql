create or replace function public.create_credit_grant_v2(
  p_person_ids bigint[],
  p_modality text,
  p_minutes integer,
  p_price_cents integer default 0,
  p_label text default null,
  p_payment_status text default 'paid',
  p_starts_at timestamptz default now(),
  p_expires_at timestamptz default null,
  p_reason text default null
)
returns public.credit_grants
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_clean_ids bigint[];
  v_expected integer;
  v_grant public.credit_grants;
  v_reason text := coalesce(nullif(btrim(p_reason),''), 'Alta de bono');
begin
  if not (select private.is_staff()) then
    raise exception 'No tienes permiso para crear bonos.' using errcode='42501';
  end if;
  if p_modality not in ('individual','pair') then
    raise exception 'Modalidad no válida.' using errcode='22023';
  end if;
  if p_minutes is null or p_minutes <= 0 or p_minutes > 100000 then
    raise exception 'La capacidad del bono no es válida.' using errcode='22023';
  end if;
  if coalesce(p_price_cents,0) < 0 then
    raise exception 'El importe no puede ser negativo.' using errcode='22023';
  end if;
  if p_payment_status not in ('paid','pending') then
    raise exception 'Estado de pago no válido.' using errcode='22023';
  end if;
  if p_starts_at is null then
    raise exception 'La fecha de inicio es obligatoria.' using errcode='22023';
  end if;
  if p_expires_at is not null and p_expires_at <= p_starts_at then
    raise exception 'La caducidad debe ser posterior al inicio.' using errcode='22023';
  end if;

  select coalesce(array_agg(id order by id),'{}'::bigint[])
  into v_clean_ids
  from (select distinct unnest(coalesce(p_person_ids,'{}'::bigint[])) id) s;

  v_expected := case when p_modality='pair' then 2 else 1 end;
  if cardinality(v_clean_ids) <> v_expected then
    raise exception 'El bono requiere % persona(s) distintas.', v_expected using errcode='22023';
  end if;
  if (select count(*) from public.people p where p.id=any(v_clean_ids) and p.active) <> v_expected then
    raise exception 'Hay personas no válidas o inactivas.' using errcode='22023';
  end if;

  insert into public.credit_grants(
    modality,label,total_minutes,price_cents,payment_status,status,
    purchased_at,starts_at,expires_at,created_by
  ) values (
    p_modality,nullif(btrim(p_label),''),p_minutes,coalesce(p_price_cents,0),p_payment_status,'active',
    now(),p_starts_at,p_expires_at,(select auth.uid())
  ) returning * into v_grant;

  insert into public.credit_grant_members(grant_id,person_id)
  select v_grant.id, unnest(v_clean_ids);

  insert into public.credit_movements(
    grant_id,movement_type,delta_minutes,note,created_by,occurred_at,provenance
  ) values (
    v_grant.id,'grant',p_minutes,v_reason,(select auth.uid()),now(),
    jsonb_build_object('operation','grant_created')
  );

  insert into public.audit_events(event_type,entity_type,entity_id,summary,detail,actor_user_id)
  values(
    'credit_grant_created','credit_grant',v_grant.id::text,'Bono creado',
    jsonb_build_object('before',null,'after',to_jsonb(v_grant),'person_ids',v_clean_ids,'reason',v_reason),
    (select auth.uid())
  );

  return v_grant;
end;
$$;

