  p_grant_id bigint,
  p_at timestamptz default now()
)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_person_id bigint;
begin
  if (select private.is_staff()) then
    return private.credit_grant_is_usable_unchecked(p_grant_id, p_at);
