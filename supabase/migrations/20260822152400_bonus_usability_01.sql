    from public.credit_grant_members gm
    where gm.grant_id = p_grant_id and gm.person_id = v_person_id
  ) then
    raise exception 'No tienes permiso para consultar este bono.' using errcode='42501';
  end if;

  return private.credit_grant_is_usable_unchecked(p_grant_id, p_at);
end;
$$;

