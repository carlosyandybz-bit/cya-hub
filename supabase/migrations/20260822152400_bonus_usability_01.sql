create or replace function public.import_historical_credit_grant(
  p_person_ids bigint[],
  p_modality text,
  p_total_minutes integer,
  p_price_cents integer,
  p_label text,
  p_payment_status text,
  p_purchased_at timestamptz,
  p_purchase_date_approximate boolean,
  p_starts_at timestamptz,
  p_expires_at timestamptz,
  p_prior_consumption jsonb,
  p_provenance text,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_grant public.credit_grants;
  v_clean_ids bigint[];
  v_expected integer;
  v_item jsonb;
  v_minutes integer;
  v_consumed integer := 0;
  v_occurred_at timestamptz;
  v_item_provenance text;
  v_reason text := nullif(btrim(p_reason),'');
  v_provenance text := nullif(btrim(p_provenance),'');
begin
  if not (select private.billing_is_admin()) then
    raise exception 'Solo Administración puede importar bonos históricos.' using errcode='42501';
  end if;
  if not coalesce((select s.allow_historical_bonus_import from public.billing_admin_settings s where s.singleton),false) then
    raise exception 'El modo de alta histórica de bonos está desactivado.' using errcode='42501';
  end if;
  if v_reason is null or v_provenance is null then
    raise exception 'Motivo y procedencia histórica son obligatorios.' using errcode='22023';
  end if;
  if p_modality not in ('individual','pair') then raise exception 'Modalidad no válida.' using errcode='22023'; end if;
  if p_total_minutes is null or p_total_minutes<=0 or p_total_minutes>100000 then raise exception 'La capacidad no es válida.' using errcode='22023'; end if;
  if p_price_cents is null or p_price_cents<0 then raise exception 'El importe no puede ser negativo.' using errcode='22023'; end if;
  if p_payment_status not in ('paid','pending') then raise exception 'Estado de pago histórico no válido.' using errcode='22023'; end if;
  if p_purchased_at is null or p_starts_at is null then raise exception 'Compra e inicio históricos son obligatorios.' using errcode='22023'; end if;
  if p_expires_at is not null and p_expires_at<=p_starts_at then raise exception 'La caducidad debe ser posterior al inicio.' using errcode='22023'; end if;
  if p_prior_consumption is null then p_prior_consumption := '[]'::jsonb; end if;
  if jsonb_typeof(p_prior_consumption)<>'array' or jsonb_array_length(p_prior_consumption)>1000 then
    raise exception 'Los consumos históricos no son válidos.' using errcode='22023';
  end if;

  select coalesce(array_agg(id order by id),'{}'::bigint[])
  into v_clean_ids
  from (select distinct unnest(coalesce(p_person_ids,'{}'::bigint[])) id) s;
  v_expected := case when p_modality='pair' then 2 else 1 end;
  if cardinality(v_clean_ids)<>v_expected then raise exception 'Número de personas no válido para el bono.' using errcode='22023'; end if;
  if (select count(*) from public.people p where p.id=any(v_clean_ids) and p.active)<>v_expected then
    raise exception 'Hay personas no válidas o inactivas.' using errcode='22023';
  end if;

  for v_item in select value from jsonb_array_elements(p_prior_consumption) s(value) loop
    if jsonb_typeof(v_item)<>'object' then raise exception 'Consumo histórico no válido.' using errcode='22023'; end if;
    if coalesce(v_item->>'minutes','') !~ '^[0-9]+$' then raise exception 'Minutos históricos no válidos.' using errcode='22023'; end if;
    v_minutes := (v_item->>'minutes')::integer;
    if v_minutes<=0 then raise exception 'Los minutos históricos deben ser positivos.' using errcode='22023'; end if;
    if coalesce(v_item->>'occurred_at','')='' then raise exception 'Falta fecha del consumo histórico.' using errcode='22023'; end if;
    begin
      v_occurred_at := (v_item->>'occurred_at')::timestamptz;
    exception when others then
      raise exception 'Fecha de consumo histórico no válida.' using errcode='22023';
    end;
    v_item_provenance := nullif(btrim(v_item->>'provenance'),'');
    if v_item_provenance is null then raise exception 'Falta procedencia del consumo histórico.' using errcode='22023'; end if;
    v_consumed := v_consumed + v_minutes;
  end loop;

  if v_consumed > p_total_minutes then
    raise exception 'El consumo histórico supera la capacidad del bono.' using errcode='22023';
  end if;

  insert into public.credit_grants(
    modality,label,total_minutes,price_cents,payment_status,status,purchased_at,
    starts_at,expires_at,purchased_at_approximate,historical_provenance,created_by
  ) values (
    p_modality,nullif(btrim(p_label),''),p_total_minutes,p_price_cents,p_payment_status,
    case when v_consumed=p_total_minutes then 'exhausted' else 'active' end,
    p_purchased_at,p_starts_at,p_expires_at,coalesce(p_purchase_date_approximate,false),v_provenance,(select auth.uid())
  ) returning * into v_grant;

  insert into public.credit_grant_members(grant_id,person_id)
  select v_grant.id,unnest(v_clean_ids);

  insert into public.credit_movements(
    grant_id,movement_type,delta_minutes,note,created_by,occurred_at,date_approximate,provenance
  ) values (
    v_grant.id,'grant',p_total_minutes,'Alta histórica de bono',(select auth.uid()),p_purchased_at,
    coalesce(p_purchase_date_approximate,false),jsonb_build_object('origin','historical_import','provenance',v_provenance)
  );

  for v_item in select value from jsonb_array_elements(p_prior_consumption) s(value) loop
    v_minutes := (v_item->>'minutes')::integer;
    v_occurred_at := (v_item->>'occurred_at')::timestamptz;
    v_item_provenance := btrim(v_item->>'provenance');
    insert into public.credit_movements(
      grant_id,movement_type,delta_minutes,note,created_by,occurred_at,date_approximate,provenance
    ) values (
      v_grant.id,'adjustment',-v_minutes,
      coalesce(nullif(btrim(v_item->>'note'),''),'Consumo histórico importado'),
      (select auth.uid()),v_occurred_at,coalesce((v_item->>'date_approximate')::boolean,false),
      jsonb_build_object('origin','historical_import','provenance',v_item_provenance,'grant_provenance',v_provenance)
    );
  end loop;

  insert into public.audit_events(event_type,entity_type,entity_id,summary,detail,actor_user_id)
  values(
    'credit_grant_historical_imported','credit_grant',v_grant.id::text,'Bono histórico importado',
    jsonb_build_object(
      'before',null,
      'after',to_jsonb(v_grant) || jsonb_build_object('balance_minutes',private.credit_grant_balance_minutes_unchecked(v_grant.id)),
      'person_ids',v_clean_ids,'historical_consumed_minutes',v_consumed,'provenance',v_provenance,'reason',v_reason
    ),
    (select auth.uid())
  );

  return jsonb_build_object('grant',to_jsonb(v_grant),'balance_minutes',private.credit_grant_balance_minutes_unchecked(v_grant.id));
end;
$$;

-- -----------------------------------------------------------------------------
-- 8. Append-only correction contract (DP-BONUS-15 = 15A)
-- -----------------------------------------------------------------------------
create or replace function public.correct_credit_consumption(
  p_original_movement_id bigint,
  p_replacement_consumed_minutes integer,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_original public.credit_movements;
  v_grant public.credit_grants;
  v_correction_sum integer;
  v_current_effective_delta integer;
  v_target_delta integer;
  v_delta integer;
  v_balance_before integer;
  v_balance_after integer;
  v_reason text := nullif(btrim(p_reason),'');
  v_new_movement_id bigint;
begin
  if not (select private.is_staff()) then
    raise exception 'No tienes permiso para corregir consumos de bonos.' using errcode='42501';
  end if;
  if v_reason is null then raise exception 'Indica el motivo de la corrección.' using errcode='22023'; end if;
  if p_replacement_consumed_minutes is null or p_replacement_consumed_minutes < 0 then
    raise exception 'El consumo corregido no puede ser negativo.' using errcode='22023';
  end if;

  select * into v_original
  from public.credit_movements
  where id=p_original_movement_id
  for update;
  if not found then raise exception 'El movimiento original no existe.' using errcode='P0002'; end if;
  if v_original.reverses_movement_id is not null then
    raise exception 'La corrección debe apuntar al movimiento original, no a otra corrección.' using errcode='22023';
  end if;
  if v_original.delta_minutes >= 0 or v_original.movement_type not in ('class','adjustment') then
    raise exception 'Este movimiento no representa un consumo corregible.' using errcode='22023';
  end if;

  select * into v_grant from public.credit_grants where id=v_original.grant_id for update;
  if not found then raise exception 'El bono del movimiento ya no existe.' using errcode='P0002'; end if;
  if p_replacement_consumed_minutes > v_grant.total_minutes then
    raise exception 'El consumo corregido supera la capacidad del bono.' using errcode='22023';
  end if;

  select coalesce(sum(m.delta_minutes),0)::integer
  into v_correction_sum
  from public.credit_movements m
  where m.reverses_movement_id=v_original.id;

  v_current_effective_delta := v_original.delta_minutes + v_correction_sum;
  v_target_delta := -p_replacement_consumed_minutes;
  v_delta := v_target_delta - v_current_effective_delta;
  v_balance_before := private.credit_grant_balance_minutes_unchecked(v_grant.id);
  v_balance_after := v_balance_before + v_delta;

  if v_balance_after < 0 then
    raise exception 'La corrección dejaría el bono con saldo negativo.' using errcode='22023';
  end if;

  if v_delta <> 0 then
    insert into public.credit_movements(
      grant_id,person_id,class_id,movement_type,delta_minutes,note,created_by,
      occurred_at,date_approximate,reverses_movement_id,provenance
    ) values (
      v_original.grant_id,v_original.person_id,v_original.class_id,'adjustment',v_delta,
      'Corrección de consumo · '||v_reason,(select auth.uid()),now(),false,v_original.id,
      jsonb_build_object(
        'operation','consumption_correction',
        'original_movement_id',v_original.id,
        'original_movement_type',v_original.movement_type,
        'original_class_id',v_original.class_id,
        'original_provenance',v_original.provenance,
        'replacement_consumed_minutes',p_replacement_consumed_minutes
      )
    ) returning id into v_new_movement_id;
  end if;

  if v_grant.payment_status <> 'refunded' and v_grant.status <> 'cancelled' then
    update public.credit_grants
    set status=case when v_balance_after<=0 then 'exhausted' else 'active' end,updated_at=now()
    where id=v_grant.id;
  end if;

  insert into public.audit_events(event_type,entity_type,entity_id,summary,detail,actor_user_id)
  values(
    'credit_consumption_corrected','credit_grant',v_grant.id::text,'Consumo de bono corregido',
    jsonb_build_object(
      'before',jsonb_build_object(
        'original_movement_id',v_original.id,'effective_delta_minutes',v_current_effective_delta,
        'effective_consumed_minutes',greatest(-v_current_effective_delta,0),'balance_minutes',v_balance_before,
        'class_id',v_original.class_id,'source_provenance',v_original.provenance
      ),
      'after',jsonb_build_object(
        'replacement_consumed_minutes',p_replacement_consumed_minutes,'correction_delta_minutes',v_delta,
        'balance_minutes',v_balance_after,'correction_movement_id',v_new_movement_id,
        'class_id',v_original.class_id,'source_provenance',v_original.provenance
      ),
      'reason',v_reason
    ),
    (select auth.uid())
  );

  return jsonb_build_object(
    'grant_id',v_grant.id,
    'original_movement_id',v_original.id,
    'correction_movement_id',v_new_movement_id,
    'replacement_consumed_minutes',p_replacement_consumed_minutes,
    'balance_minutes',v_balance_after,
    'class_id',v_original.class_id
  );
end;
$$;

-- Compatibility endpoint remains append-only but refuses to erase source-linked history.
create or replace function public.set_credit_grant_consumed_minutes(
  p_grant_id bigint,
  p_consumed_minutes integer,
  p_note text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_grant public.credit_grants;
  v_balance integer;
  v_target_balance integer;
  v_delta integer;
  v_before jsonb;
  v_note text := coalesce(nullif(btrim(p_note),''),'Ajuste manual de consumo');
begin
  if not (select private.is_staff()) then
    raise exception 'No tienes permiso para ajustar el consumo de bonos.' using errcode='42501';
  end if;

  select * into v_grant from public.credit_grants where id=p_grant_id for update;
  if not found then raise exception 'El bono no existe.' using errcode='P0002'; end if;
  if v_grant.status='cancelled' or v_grant.payment_status='refunded' then
    raise exception 'Este bono está en estado terminal; utiliza un flujo de corrección explícito.' using errcode='22023';
  end if;
  if exists(
    select 1 from public.credit_movements m
    where m.grant_id=p_grant_id
      and (
        m.class_id is not null
        or m.provenance->>'origin'='historical_import'
        or m.reverses_movement_id is not null
      )
  ) then
    raise exception 'Este bono tiene consumo con origen trazable. Corrige el movimiento original para preservar su fuente.' using errcode='22023';
  end if;
  if p_consumed_minutes is null or p_consumed_minutes<0 or p_consumed_minutes>v_grant.total_minutes then
    raise exception 'Los minutos consumidos deben estar entre 0 y %.',v_grant.total_minutes using errcode='22023';
  end if;

  v_balance := private.credit_grant_balance_minutes_unchecked(p_grant_id);
  v_before := jsonb_build_object('consumed_minutes',greatest(v_grant.total_minutes-v_balance,0),'balance_minutes',v_balance,'status',v_grant.status);
  v_target_balance := v_grant.total_minutes-p_consumed_minutes;
  v_delta := v_target_balance-v_balance;

  if v_delta<>0 then
    insert into public.credit_movements(
      grant_id,movement_type,delta_minutes,note,created_by,occurred_at,provenance
    ) values (
      p_grant_id,'adjustment',v_delta,v_note,(select auth.uid()),now(),
      jsonb_build_object('operation','manual_consumption_target','target_consumed_minutes',p_consumed_minutes)
    );
  end if;

  update public.credit_grants
  set status=case when v_target_balance=0 then 'exhausted' else 'active' end,updated_at=now()
  where id=p_grant_id;

  insert into public.audit_events(event_type,entity_type,entity_id,summary,detail,actor_user_id)
  values(
    'credit_consumption_target_adjusted','credit_grant',p_grant_id::text,'Consumo manual de bono ajustado',
    jsonb_build_object(
      'before',v_before,
      'after',jsonb_build_object('consumed_minutes',p_consumed_minutes,'balance_minutes',v_target_balance,'status',case when v_target_balance=0 then 'exhausted' else 'active' end),
      'reason',v_note
    ),
    (select auth.uid())
  );

  return jsonb_build_object(
    'grant_id',p_grant_id,'total_minutes',v_grant.total_minutes,'consumed_minutes',p_consumed_minutes,
    'remaining_minutes',v_target_balance,'adjustment_minutes',v_delta
  );
end;
$$;

