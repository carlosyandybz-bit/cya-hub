create or replace function private.assert_credit_transfer_operation_balanced()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  v_out_count integer;
  v_in_count integer;
  v_out_sum integer;
  v_in_sum integer;
  v_minutes integer;
  v_operation_type text;
  v_reverses_transfer_id bigint;
  v_source_grant_id bigint;
  v_destination_grant_id bigint;
  v_source_balance_after integer;
  v_destination_balance_after integer;
  v_actual_source_balance integer;
  v_actual_destination_balance integer;
begin
  select
    op.minutes,
    op.operation_type,
    op.reverses_transfer_id,
    op.source_grant_id,
    op.destination_grant_id,
    op.source_balance_after,
    op.destination_balance_after
  into
    v_minutes,
    v_operation_type,
    v_reverses_transfer_id,
    v_source_grant_id,
    v_destination_grant_id,
    v_source_balance_after,
    v_destination_balance_after
  from public.credit_transfer_operations op
  where op.id=new.id;

  select
    count(*) filter (where cm.movement_type='transfer_out')::integer,
    count(*) filter (where cm.movement_type='transfer_in')::integer,
    coalesce(sum(cm.delta_minutes) filter (where cm.movement_type='transfer_out'),0)::integer,
    coalesce(sum(cm.delta_minutes) filter (where cm.movement_type='transfer_in'),0)::integer
  into v_out_count,v_in_count,v_out_sum,v_in_sum
  from public.credit_movements cm
  where cm.transfer_id=new.id;

  if v_out_count<>1
     or v_in_count<>1
     or v_out_sum<>-v_minutes
     or v_in_sum<>v_minutes
     or (v_out_sum+v_in_sum)<>0 then
    raise exception 'TRANSFER_LEDGER_INVARIANT_VIOLATION'
      using errcode='23514',
            detail='Each canonical transfer operation must commit exactly one transfer_out=-X and one transfer_in=+X.';
  end if;

  v_actual_source_balance :=
    private.credit_grant_balance_minutes_unchecked(v_source_grant_id);
  v_actual_destination_balance :=
    private.credit_grant_balance_minutes_unchecked(v_destination_grant_id);

  if v_actual_source_balance<>v_source_balance_after
     or v_actual_destination_balance<>v_destination_balance_after then
    raise exception 'TRANSFER_BALANCE_SNAPSHOT_INVARIANT_VIOLATION'
      using errcode='23514',
            detail='Committed ledger balances must equal the canonical operation after-snapshots.';
  end if;

  if v_operation_type='reversal' and not exists (
    select 1
    from public.credit_transfer_operations original
    where original.id=v_reverses_transfer_id
      and original.operation_type='transfer'
  ) then
    raise exception 'TRANSFER_REVERSAL_LINK_INVALID'
      using errcode='23514';
  end if;

  return null;
end;
$$;

alter function private.assert_credit_transfer_operation_balanced() owner to postgres;
revoke all on function private.assert_credit_transfer_operation_balanced()
  from public, anon, authenticated, service_role;

create constraint trigger credit_transfer_operation_balanced
after insert on public.credit_transfer_operations
deferrable initially deferred
for each row execute function private.assert_credit_transfer_operation_balanced();

create or replace function public.preview_individual_credit_to_pair_transfer(
  p_source_grant_id bigint,
  p_partner_person_id bigint,
  p_minutes integer,
  p_class_id bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_now timestamptz := now();
  v_source public.credit_grants%rowtype;
  v_source_person_id bigint;
  v_source_members bigint[];
  v_pair_low bigint;
  v_pair_high bigint;
  v_balance integer;
  v_effective_expires_at timestamptz;
  v_paused boolean;
  v_destination_id bigint;
  v_destination_balance integer := 0;
begin
  if not (select private.is_staff()) then
    raise exception 'No tienes permiso para transferir saldo de bonos.'
      using errcode='42501';
  end if;

  if p_source_grant_id is null or p_partner_person_id is null then
    raise exception 'Bono origen y segunda persona son obligatorios.'
      using errcode='22023';
  end if;
  if p_minutes is null or p_minutes<=0 then
    raise exception 'Los minutos deben ser mayores que cero.'
      using errcode='22023';
  end if;
  if p_class_id is not null
     and not exists (select 1 from public.classes c where c.id=p_class_id) then
    raise exception 'La clase indicada como contexto no existe.'
      using errcode='22023';
  end if;

  select * into v_source
  from public.credit_grants g
  where g.id=p_source_grant_id;

  if not found then
    raise exception 'El bono origen no existe.'
      using errcode='P0002';
  end if;
  if v_source.modality<>'individual'
     or v_source.status<>'active'
     or v_source.payment_status not in ('paid','pending') then
    raise exception 'El bono origen no admite esta transferencia.'
      using errcode='22023';
  end if;

  select coalesce(array_agg(gm.person_id order by gm.person_id),'{}'::bigint[])
  into v_source_members
  from public.credit_grant_members gm
  where gm.grant_id=v_source.id;

  if cardinality(v_source_members)<>1 then
    raise exception 'El bono individual debe tener exactamente una persona titular.'
      using errcode='23514';
  end if;

  v_source_person_id := v_source_members[1];

  if not exists (
    select 1 from public.people p
    where p.id=v_source_person_id and p.active
  ) then
    raise exception 'La persona titular del bono no está activa.'
      using errcode='22023';
  end if;

  if p_partner_person_id=v_source_person_id
     or not exists (
       select 1 from public.people p
       where p.id=p_partner_person_id and p.active
     ) then
    raise exception 'La segunda persona debe ser distinta y estar activa.'
      using errcode='22023';
  end if;

  v_balance := private.credit_grant_balance_minutes_unchecked(v_source.id);
  if v_balance<=0 or p_minutes>v_balance then
    raise exception 'No hay saldo suficiente para transferir esos minutos.'
      using errcode='22023';
  end if;

  v_effective_expires_at :=
    private.credit_grant_effective_expires_at_unchecked(v_source.id,v_now);
  v_paused := private.credit_grant_is_paused_unchecked(v_source.id,v_now);
  v_pair_low := least(v_source_person_id,p_partner_person_id);
  v_pair_high := greatest(v_source_person_id,p_partner_person_id);

  select g.id
  into v_destination_id
  from public.credit_pair_transfer_pools tp
  join public.credit_grants g on g.id=tp.destination_grant_id
  where tp.economic_source_grant_id=v_source.id
    and tp.member_person_id_low=v_pair_low
    and tp.member_person_id_high=v_pair_high
    and private.credit_pair_transfer_pool_compatible_unchecked(
      g.id,v_source.id,v_pair_low,v_pair_high,v_source.payment_status,
      v_source.starts_at,v_effective_expires_at,v_paused,v_now
    )
  order by g.id
  limit 1;

  if v_destination_id is not null then
    v_destination_balance :=
      private.credit_grant_balance_minutes_unchecked(v_destination_id);
    if v_destination_balance<0 then
      raise exception 'El pool de pareja compatible tiene un saldo inválido.'
        using errcode='23514';
    end if;
  end if;

  return jsonb_build_object(
    'status','preview',
    'authoritative_at',v_now,
    'confirmation_required',true,
    'minutes',p_minutes,
    'all_source_balance',p_minutes=v_balance,
    'class_id',p_class_id,
    'source',jsonb_build_object(
      'grant_id',v_source.id,
      'person_id',v_source_person_id,
      'balance_before',v_balance,
      'balance_after',v_balance-p_minutes,
      'payment_status',v_source.payment_status,
      'starts_at',v_source.starts_at,
      'effective_expires_at',v_effective_expires_at,
      'is_paused',v_paused
    ),
    'pair',jsonb_build_object(
      'source_person_id',v_source_person_id,
      'partner_person_id',p_partner_person_id,
      'member_person_ids',jsonb_build_array(v_pair_low,v_pair_high)
    ),
    'destination',jsonb_build_object(
      'grant_id',v_destination_id,
      'will_create_destination',v_destination_id is null,
      'transfer_derived',true,
      'balance_before',v_destination_balance,
      'balance_after',v_destination_balance+p_minutes,
      'payment_status',v_source.payment_status,
      'starts_at',v_source.starts_at,
      'effective_expires_at',v_effective_expires_at,
      'is_paused',v_paused
    )
  );
end;
$$;

