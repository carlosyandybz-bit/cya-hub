create or replace function private.credit_transfer_result_unchecked(
  p_operation_id bigint,
  p_idempotent_replay boolean default false,
  p_reconciled boolean default false
)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select jsonb_build_object(
    'status','committed',
    'result','committed',
    'operation_id',op.id,
    'operation_type',op.operation_type,
    'transfer_id',case when op.operation_type='transfer' then op.id else op.reverses_transfer_id end,
    'reversal_id',case when op.operation_type='reversal' then op.id else null end,
    'request_key',op.request_key,
    'minutes',op.minutes,
    'class_id',op.class_id,
    'pair',jsonb_build_object(
      'source_person_id',op.source_person_id,
      'partner_person_id',op.partner_person_id,
      'member_person_ids',
        case
          when op.source_person_id < op.partner_person_id
            then jsonb_build_array(op.source_person_id,op.partner_person_id)
          else jsonb_build_array(op.partner_person_id,op.source_person_id)
        end
    ),
    'source',jsonb_build_object(
      'grant_id',op.source_grant_id,
      'balance_before',op.source_balance_before,
      'balance_after',op.source_balance_after,
      'payment_status',op.source_payment_status,
      'starts_at',op.source_starts_at,
      'effective_expires_at',op.source_effective_expires_at,
      'is_paused',op.source_was_paused
    ),
    'destination',jsonb_build_object(
      'grant_id',op.destination_grant_id,
      'balance_before',op.destination_balance_before,
      'balance_after',op.destination_balance_after,
      'transfer_derived',true
    ),
    'idempotent_replay',p_idempotent_replay,
    'reconciled',p_reconciled,
    'reconciliation',jsonb_build_object(
      'status','committed',
      'request_key',op.request_key,
      'retry_with_same_key',true,
      'blind_retry_with_new_key',false
    ),
    'created_at',op.created_at
  )
  from public.credit_transfer_operations op
  where op.id=p_operation_id;
$$;

