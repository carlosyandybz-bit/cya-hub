create or replace function public.reverse_individual_credit_to_pair_transfer(
  p_transfer_id bigint,
  p_request_key text,
  p_reason text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_now timestamptz := now();
  v_actor uuid := (select auth.uid());
  v_request_key text := nullif(btrim(p_request_key),'');
  v_reason text := nullif(btrim(p_reason),'');
  v_existing public.credit_transfer_operations%rowtype;
  v_original public.credit_transfer_operations%rowtype;
  v_source public.credit_grants%rowtype;
  v_destination public.credit_grants%rowtype;
  v_original_out public.credit_movements%rowtype;
  v_original_in public.credit_movements%rowtype;
  v_source_members bigint[];
  v_pair_low bigint;
  v_pair_high bigint;
  v_source_effective_expires_at timestamptz;
  v_source_paused boolean;
  v_source_balance_before integer;
  v_source_balance_after integer;
  v_destination_balance_before integer;
  v_destination_balance_after integer;
  v_operation public.credit_transfer_operations%rowtype;
begin
  if not (select private.is_staff()) or v_actor is null then
    raise exception 'No tienes permiso para revertir transferencias.'
      using errcode='42501';
  end if;
  if p_transfer_id is null then
    raise exception 'transfer_id es obligatorio.'
      using errcode='22023';
  end if;
  if v_request_key is null or char_length(v_request_key)>200 then
    raise exception 'request_key debe contener entre 1 y 200 caracteres.'
      using errcode='22023';
  end if;
  if v_reason is null or char_length(v_reason)>500 then
    raise exception 'La reversión requiere un motivo de entre 1 y 500 caracteres.'
      using errcode='22023';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('cya:bonus-pair-transfer:request:'||v_request_key,0)
  );

  select * into v_existing
  from public.credit_transfer_operations op
  where op.request_key=v_request_key;

  if found then
    if v_existing.operation_type='reversal'
       and v_existing.reverses_transfer_id=p_transfer_id
       and v_existing.reason=v_reason
       and v_existing.actor_user_id=v_actor then
      return private.credit_transfer_result_unchecked(v_existing.id,true,false);
    end if;

    raise exception 'IDEMPOTENCY_CONFLICT'
      using errcode='23505',
            detail='request_key already belongs to a different canonical reversal request.';
  end if;

  select * into v_original
  from public.credit_transfer_operations op
  where op.id=p_transfer_id
    and op.operation_type='transfer';

  if not found then
    raise exception 'La transferencia original no existe.'
      using errcode='P0002';
  end if;

  if exists (
    select 1
    from public.credit_transfer_operations op
    where op.reverses_transfer_id=v_original.id
  ) then
    raise exception 'TRANSFER_ALREADY_REVERSED'
      using errcode='23505';
  end if;

  -- Lock order matches forward semantics: original individual source first,
  -- then transfer-derived pair destination.
  select * into v_source
  from public.credit_grants g
  where g.id=v_original.source_grant_id
  for update;

  select * into v_destination
  from public.credit_grants g
  where g.id=v_original.destination_grant_id
  for update;

  if v_source.id is null or v_destination.id is null then
    raise exception 'TRANSFER_REVERSAL_REQUIRES_ADMIN_CORRECTION'
      using errcode='55000',
            detail='Source or destination grant is no longer available.';
  end if;

  if v_source.modality<>'individual'
     or v_source.status='cancelled'
     or v_source.payment_status not in ('paid','pending') then
    raise exception 'TRANSFER_REVERSAL_REQUIRES_ADMIN_CORRECTION'
      using errcode='55000',
            detail='Source grant semantics no longer permit an ordinary reversal.';
  end if;

  select coalesce(array_agg(gm.person_id order by gm.person_id),'{}'::bigint[])
  into v_source_members
  from public.credit_grant_members gm
  where gm.grant_id=v_source.id;

  if v_source_members<>array[v_original.source_person_id]::bigint[] then
    raise exception 'TRANSFER_REVERSAL_REQUIRES_ADMIN_CORRECTION'
      using errcode='55000',
            detail='Source membership changed after the transfer.';
  end if;

  v_pair_low := least(v_original.source_person_id,v_original.partner_person_id);
  v_pair_high := greatest(v_original.source_person_id,v_original.partner_person_id);
  v_source_effective_expires_at :=
    private.credit_grant_effective_expires_at_unchecked(v_source.id,v_now);
  v_source_paused := private.credit_grant_is_paused_unchecked(v_source.id,v_now);

  if not private.credit_pair_transfer_pool_compatible_unchecked(
    v_destination.id,
    v_source.id,
    v_pair_low,
    v_pair_high,
    v_source.payment_status,
    v_source.starts_at,
    v_source_effective_expires_at,
    v_source_paused,
    v_now
  ) then
    raise exception 'TRANSFER_REVERSAL_REQUIRES_ADMIN_CORRECTION'
      using errcode='55000',
            detail='Destination semantics diverged from the source after the transfer.';
  end if;

  select * into v_original_out
  from public.credit_movements cm
  where cm.transfer_id=v_original.id
    and cm.movement_type='transfer_out';

  select * into v_original_in
  from public.credit_movements cm
  where cm.transfer_id=v_original.id
    and cm.movement_type='transfer_in';

  if v_original_out.id is null or v_original_in.id is null then
    raise exception 'TRANSFER_REVERSAL_REQUIRES_ADMIN_CORRECTION'
      using errcode='55000',
            detail='Canonical transfer movements are incomplete.';
  end if;

  if exists (
    select 1
    from public.credit_movements cm
    where cm.grant_id=v_destination.id
      and cm.delta_minutes<0
      and (
        cm.occurred_at>v_original_in.occurred_at
        or (cm.occurred_at=v_original_in.occurred_at and cm.id>v_original_in.id)
      )
      and not (
        cm.movement_type='transfer_out'
        and cm.transfer_id is not null
        and cm.reverses_movement_id is not null
        and exists (
          select 1
          from public.credit_transfer_operations reversal_op
          join public.credit_transfer_operations reversed_transfer
            on reversed_transfer.id=reversal_op.reverses_transfer_id
           and reversed_transfer.operation_type='transfer'
          join public.credit_movements reversed_in
            on reversed_in.id=cm.reverses_movement_id
           and reversed_in.transfer_id=reversed_transfer.id
           and reversed_in.movement_type='transfer_in'
           and reversed_in.grant_id=v_destination.id
          where reversal_op.id=cm.transfer_id
            and reversal_op.operation_type='reversal'
            and reversal_op.destination_grant_id=v_destination.id
            and reversed_transfer.destination_grant_id=v_destination.id
            and reversal_op.source_grant_id=reversed_transfer.source_grant_id
            and reversal_op.source_person_id=reversed_transfer.source_person_id
            and reversal_op.partner_person_id=reversed_transfer.partner_person_id
            and reversal_op.minutes=reversed_transfer.minutes
            and cm.delta_minutes=-reversal_op.minutes
            and reversed_in.delta_minutes=reversal_op.minutes
        )
      )
  ) then
    raise exception 'TRANSFER_REVERSAL_REQUIRES_ADMIN_CORRECTION'
      using errcode='55000',
            detail='Destination balance has subsequent incompatible negative use; ordinary reversal is unsafe.';
  end if;

  v_source_balance_before :=
    private.credit_grant_balance_minutes_unchecked(v_source.id);
  v_destination_balance_before :=
    private.credit_grant_balance_minutes_unchecked(v_destination.id);

  if v_source_balance_before<0
     or v_destination_balance_before<v_original.minutes then
    raise exception 'TRANSFER_REVERSAL_REQUIRES_ADMIN_CORRECTION'
      using errcode='55000',
            detail='Current balances do not permit an ordinary reversal.';
  end if;

  v_source_balance_after := v_source_balance_before+v_original.minutes;
  v_destination_balance_after := v_destination_balance_before-v_original.minutes;

  insert into public.credit_transfer_operations(
    operation_type,
    request_key,
    source_grant_id,
    destination_grant_id,
    source_person_id,
    partner_person_id,
    minutes,
    class_id,
    source_payment_status,
    source_starts_at,
