create or replace function public.transfer_individual_credit_to_pair_v2(
  p_source_grant_id bigint,
  p_partner_person_id bigint,
  p_minutes integer,
  p_request_key text,
  p_class_id bigint default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_now timestamptz := now();
  v_actor uuid := (select auth.uid());
  v_request_key text := nullif(btrim(p_request_key),'');
  v_existing public.credit_transfer_operations%rowtype;
  v_source public.credit_grants%rowtype;
  v_destination public.credit_grants%rowtype;
  v_source_members bigint[];
  v_source_person_id bigint;
  v_pair_low bigint;
  v_pair_high bigint;
  v_source_balance_before integer;
  v_source_balance_after integer;
  v_destination_balance_before integer := 0;
  v_destination_balance_after integer;
  v_effective_expires_at timestamptz;
  v_paused boolean;
  v_compatibility_key text;
  v_operation public.credit_transfer_operations%rowtype;
begin
  if not (select private.is_staff()) or v_actor is null then
    raise exception 'No tienes permiso para transferir saldo de bonos.'
      using errcode='42501';
  end if;

  if p_source_grant_id is null or p_partner_person_id is null then
    raise exception 'Bono origen y segunda persona son obligatorios.'
      using errcode='22023';
  end if;
  if p_minutes is null or p_minutes<=0 then
    raise exception 'Los minutos deben ser mayores que cero.'
      using errcode='22023';
  end if;
  if v_request_key is null or char_length(v_request_key)>200 then
    raise exception 'request_key debe contener entre 1 y 200 caracteres.'
      using errcode='22023';
  end if;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('cya:bonus-pair-transfer:request:'||v_request_key,0)
  );

  select * into v_existing
  from public.credit_transfer_operations op
  where op.request_key=v_request_key;

  if found then
    if v_existing.operation_type='transfer'
       and v_existing.source_grant_id=p_source_grant_id
       and v_existing.partner_person_id=p_partner_person_id
       and v_existing.minutes=p_minutes
       and v_existing.class_id is not distinct from p_class_id
       and v_existing.actor_user_id=v_actor then
      return private.credit_transfer_result_unchecked(v_existing.id,true,false);
    end if;

    raise exception 'IDEMPOTENCY_CONFLICT'
      using errcode='23505',
            detail='request_key already belongs to a different canonical transfer request.';
  end if;

  if p_class_id is not null
     and not exists (select 1 from public.classes c where c.id=p_class_id) then
    raise exception 'La clase indicada como contexto no existe.'
      using errcode='22023';
  end if;

  select * into v_source
  from public.credit_grants g
  where g.id=p_source_grant_id
  for update;

  if not found then
    raise exception 'El bono origen no existe.'
      using errcode='P0002';
  end if;
  if v_source.modality<>'individual'
     or v_source.status<>'active'
     or v_source.payment_status not in ('paid','pending') then
    raise exception 'El bono origen no admite esta transferencia.'
      using errcode='22023';
  end if;

  select coalesce(array_agg(gm.person_id order by gm.person_id),'{}'::bigint[])
  into v_source_members
  from public.credit_grant_members gm
  where gm.grant_id=v_source.id;

  if cardinality(v_source_members)<>1 then
    raise exception 'El bono individual debe tener exactamente una persona titular.'
      using errcode='23514';
  end if;

  v_source_person_id := v_source_members[1];

  if not exists (
    select 1 from public.people p
    where p.id=v_source_person_id and p.active
  ) then
    raise exception 'La persona titular del bono no está activa.'
      using errcode='22023';
  end if;

  if p_partner_person_id=v_source_person_id
     or not exists (
       select 1 from public.people p
       where p.id=p_partner_person_id and p.active
     ) then
    raise exception 'La segunda persona debe ser distinta y estar activa.'
      using errcode='22023';
  end if;

  v_source_balance_before :=
    private.credit_grant_balance_minutes_unchecked(v_source.id);
  if v_source_balance_before<=0 or p_minutes>v_source_balance_before then
    raise exception 'No hay saldo suficiente para transferir esos minutos.'
      using errcode='22023';
  end if;

  v_source_balance_after := v_source_balance_before-p_minutes;
  v_effective_expires_at :=
    private.credit_grant_effective_expires_at_unchecked(v_source.id,v_now);
  v_paused := private.credit_grant_is_paused_unchecked(v_source.id,v_now);
  v_pair_low := least(v_source_person_id,p_partner_person_id);
  v_pair_high := greatest(v_source_person_id,p_partner_person_id);

  v_compatibility_key := jsonb_build_array(
    v_source.id,
    v_pair_low,
    v_pair_high,
    v_source.payment_status,
    v_source.starts_at,
    v_effective_expires_at,
    v_paused
  )::text;

  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended('cya:bonus-pair-transfer:pool:'||v_compatibility_key,0)
  );

  select g.* into v_destination
  from public.credit_pair_transfer_pools tp
  join public.credit_grants g on g.id=tp.destination_grant_id
  where tp.economic_source_grant_id=v_source.id
    and tp.member_person_id_low=v_pair_low
    and tp.member_person_id_high=v_pair_high
    and private.credit_pair_transfer_pool_compatible_unchecked(
      g.id,v_source.id,v_pair_low,v_pair_high,v_source.payment_status,
      v_source.starts_at,v_effective_expires_at,v_paused,v_now
    )
  order by g.id
  limit 1
  for update of g;

  if found then
    v_destination_balance_before :=
      private.credit_grant_balance_minutes_unchecked(v_destination.id);
    if v_destination_balance_before<0 then
      raise exception 'El pool de pareja compatible tiene un saldo inválido.'
        using errcode='23514';
    end if;

    update public.credit_grants
    set total_minutes=total_minutes+p_minutes,
        status='active',
        updated_at=v_now
    where id=v_destination.id
    returning * into v_destination;
  else
    insert into public.credit_grants(
      modality,
      label,
      total_minutes,
      price_cents,
      payment_status,
      status,
      purchased_at,
      expires_at,
      created_by,
      starts_at,
      purchased_at_approximate,
      historical_provenance
    )
    values(
      'pair',
      'Transferencia individual a pareja',
      p_minutes,
      0,
      v_source.payment_status,
      'active',
      v_source.purchased_at,
      v_effective_expires_at,
      v_actor,
      v_source.starts_at,
      v_source.purchased_at_approximate,
      null
    )
    returning * into v_destination;

    insert into public.credit_grant_members(grant_id,person_id)
    values
      (v_destination.id,v_pair_low),
      (v_destination.id,v_pair_high);

    insert into public.credit_pair_transfer_pools(
      destination_grant_id,
      economic_source_grant_id,
      member_person_id_low,
      member_person_id_high,
      created_by
    )
    values(
      v_destination.id,
      v_source.id,
      v_pair_low,
      v_pair_high,
      v_actor
    );

    if v_paused then
      insert into public.credit_grant_pause_periods(
        grant_id,
        paused_at,
        pause_reason,
        paused_by
      )
      values(
        v_destination.id,
        v_now,
        'Transferencia: pausa heredada del bono origen',
        v_actor
      );
    end if;

    v_destination_balance_before := 0;
  end if;

  v_destination_balance_after := v_destination_balance_before+p_minutes;

  insert into public.credit_transfer_operations(
    operation_type,
    request_key,
    source_grant_id,
    destination_grant_id,
    source_person_id,
    partner_person_id,
    minutes,
    class_id,
    source_payment_status,
    source_starts_at,
    source_effective_expires_at,
    source_was_paused,
    source_provenance,
    source_balance_before,
    source_balance_after,
    destination_balance_before,
    destination_balance_after,
    actor_user_id
  )
  values(
    'transfer',
    v_request_key,
    v_source.id,
    v_destination.id,
    v_source_person_id,
    p_partner_person_id,
    p_minutes,
    p_class_id,
    v_source.payment_status,
    v_source.starts_at,
    v_effective_expires_at,
    v_paused,
    private.credit_transfer_source_provenance_unchecked(v_source.id),
    v_source_balance_before,
    v_source_balance_after,
    v_destination_balance_before,
    v_destination_balance_after,
    v_actor
  )
  returning * into v_operation;

  insert into public.credit_movements(
    grant_id,
    person_id,
    class_id,
    movement_type,
    delta_minutes,
    note,
    created_by,
    occurred_at,
    date_approximate,
    provenance,
    source_operation_key,
    transfer_id
  )
  values(
    v_source.id,
    v_source_person_id,
    p_class_id,
    'transfer_out',
    -p_minutes,
    'Transferencia canónica a bono de pareja',
    v_actor,
    v_now,
    false,
    jsonb_build_object(
      'authority','BONUS-INDIVIDUAL-TO-PAIR-TRANSFER-01',
      'operation','individual_to_pair_transfer',
      'direction','out',
      'request_key',v_request_key,
      'transfer_id',v_operation.id,
      'source_grant_id',v_source.id,
      'destination_grant_id',v_destination.id
    ),
    'pair-transfer:'||v_request_key||':out',
    v_operation.id
  );

  insert into public.credit_movements(
    grant_id,
    person_id,
    class_id,
    movement_type,
    delta_minutes,
    note,
    created_by,
    occurred_at,
    date_approximate,
    provenance,
    source_operation_key,
    transfer_id
  )
  values(
    v_destination.id,
    null,
    p_class_id,
    'transfer_in',
    p_minutes,
    'Transferencia canónica desde bono individual',
    v_actor,
    v_now,
    false,
    jsonb_build_object(
      'authority','BONUS-INDIVIDUAL-TO-PAIR-TRANSFER-01',
      'operation','individual_to_pair_transfer',
      'direction','in',
      'request_key',v_request_key,
      'transfer_id',v_operation.id,
      'source_grant_id',v_source.id,
      'destination_grant_id',v_destination.id,
      'economic_provenance',private.credit_transfer_source_provenance_unchecked(v_source.id)
    ),
    'pair-transfer:'||v_request_key||':in',
    v_operation.id
  );

  if v_source_balance_after=0 then
    update public.credit_grants
    set status='exhausted',
        updated_at=v_now
    where id=v_source.id
      and status='active';
  end if;

  insert into public.audit_events(
    event_type,
    entity_type,
    entity_id,
    summary,
    detail,
    actor_user_id
  )
  values(
    'credit_individual_to_pair_transferred',
    'credit_transfer',
    v_operation.id::text,
    'Saldo individual transferido a bono de pareja',
    jsonb_build_object(
      'transfer_id',v_operation.id,
      'request_key',v_request_key,
      'source_grant_id',v_source.id,
      'destination_grant_id',v_destination.id,
      'source_person_id',v_source_person_id,
      'partner_person_id',p_partner_person_id,
      'minutes',p_minutes,
      'class_id',p_class_id,
      'source_balance_before',v_source_balance_before,
      'source_balance_after',v_source_balance_after,
      'destination_balance_before',v_destination_balance_before,
      'destination_balance_after',v_destination_balance_after,
      'payment_status',v_source.payment_status,
      'starts_at',v_source.starts_at,
      'effective_expires_at',v_effective_expires_at,
      'paused',v_paused,
      'revenue_created_cents',0,
      'debt_created_cents',0
    ),
    v_actor
  );

  return private.credit_transfer_result_unchecked(v_operation.id,false,false);
end;
$$;

