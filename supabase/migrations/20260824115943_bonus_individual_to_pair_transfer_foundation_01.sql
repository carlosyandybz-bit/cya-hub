create table public.credit_transfer_operations (
  id bigint generated by default as identity primary key,
  operation_type text not null,
  request_key text not null,
  source_grant_id bigint not null
    references public.credit_grants(id) on delete restrict,
  destination_grant_id bigint not null
    references public.credit_grants(id) on delete restrict,
  source_person_id bigint not null
    references public.people(id) on delete restrict,
  partner_person_id bigint not null
    references public.people(id) on delete restrict,
  minutes integer not null,
  class_id bigint references public.classes(id) on delete restrict,
  source_payment_status text not null,
  source_starts_at timestamptz not null,
  source_effective_expires_at timestamptz,
  source_was_paused boolean not null,
  source_provenance jsonb not null default '{}'::jsonb,
  source_balance_before integer not null,
  source_balance_after integer not null,
  destination_balance_before integer not null,
  destination_balance_after integer not null,
  actor_user_id uuid not null,
  reason text,
  reverses_transfer_id bigint
    references public.credit_transfer_operations(id) on delete restrict,
  created_at timestamptz not null default now(),
  constraint credit_transfer_operations_operation_type_check
    check (operation_type in ('transfer','reversal')),
  constraint credit_transfer_operations_request_key_check
    check (char_length(btrim(request_key)) between 1 and 200),
  constraint credit_transfer_operations_minutes_check
    check (minutes > 0),
  constraint credit_transfer_operations_pair_check
    check (source_person_id <> partner_person_id),
  constraint credit_transfer_operations_payment_check
    check (source_payment_status in ('paid','pending')),
  constraint credit_transfer_operations_balances_check
    check (
      source_balance_before >= 0
      and source_balance_after >= 0
      and destination_balance_before >= 0
      and destination_balance_after >= 0
    ),
  constraint credit_transfer_operations_balance_delta_check
    check (
      (
        operation_type='transfer'
        and source_balance_after=source_balance_before-minutes
        and destination_balance_after=destination_balance_before+minutes
      )
      or
      (
        operation_type='reversal'
        and source_balance_after=source_balance_before+minutes
        and destination_balance_after=destination_balance_before-minutes
      )
    ),
  constraint credit_transfer_operations_reversal_shape_check
    check (
      (operation_type='transfer' and reverses_transfer_id is null)
      or
      (
        operation_type='reversal'
        and reverses_transfer_id is not null
        and reason is not null
        and char_length(btrim(reason)) between 1 and 500
      )
    ),
  constraint credit_transfer_operations_no_self_reversal_check
    check (reverses_transfer_id is null or reverses_transfer_id <> id)
);

