create or replace function private.credit_pair_transfer_pool_compatible_unchecked(
  p_grant_id bigint,
  p_economic_source_grant_id bigint,
  p_member_person_id_low bigint,
  p_member_person_id_high bigint,
  p_payment_status text,
  p_starts_at timestamptz,
  p_effective_expires_at timestamptz,
  p_paused boolean,
  p_at timestamptz default now()
)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select coalesce((
    select
      g.modality='pair'
      and g.price_cents=0
      and g.payment_status=p_payment_status
      and g.status in ('active','exhausted')
      and g.starts_at=p_starts_at
      and private.credit_grant_effective_expires_at_unchecked(g.id,p_at)
            is not distinct from p_effective_expires_at
      and private.credit_grant_is_paused_unchecked(g.id,p_at)=p_paused
      and tp.economic_source_grant_id=p_economic_source_grant_id
      and tp.member_person_id_low=p_member_person_id_low
      and tp.member_person_id_high=p_member_person_id_high
      and (
        select coalesce(array_agg(gm.person_id order by gm.person_id),'{}'::bigint[])
        from public.credit_grant_members gm
        where gm.grant_id=g.id
      ) = array[p_member_person_id_low,p_member_person_id_high]::bigint[]
      and not exists (
        select 1
        from public.credit_movements cm
        where cm.grant_id=g.id
          and cm.movement_type='grant'
      )
    from public.credit_pair_transfer_pools tp
    join public.credit_grants g on g.id=tp.destination_grant_id
    where tp.destination_grant_id=p_grant_id
  ),false);
$$;

