create or replace function public.reopen_administratively_finished_class(p_class_id bigint)
returns public.classes
language plpgsql
set search_path=''
as $$
declare
  v_class public.classes;
  v_original_duration integer;
  v_financial_snapshot jsonb;
  v_m record;
  v_item record;
  v_art record;
  v_balance integer;
  v_incident_ids bigint[];
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para reabrir clases.' using errcode='42501'; end if;
  select * into v_class from public.classes where id=p_class_id for update;
  if not found then raise exception 'La clase no existe.' using errcode='P0002'; end if;
  if v_class.status<>'finished' or v_class.administrative_finished_at is null then
    raise exception 'La clase no tiene un cierre administrativo que deshacer.' using errcode='22023';
  end if;

  select case when detail->>'original_scheduled_duration_minutes' ~ '^[0-9]+$' then (detail->>'original_scheduled_duration_minutes')::integer else null end
    into v_original_duration
    from public.audit_events
    where event_type='class_administratively_finished' and entity_type='class' and entity_id=p_class_id::text
    order by created_at desc limit 1;

  select jsonb_build_object(
    'account',(select to_jsonb(a) from public.class_financial_accounts a where a.class_id=p_class_id),
    'items',coalesce((select jsonb_agg(to_jsonb(i) order by i.id) from public.class_financial_items i where i.class_id=p_class_id),'[]'::jsonb),
    'payments',coalesce((select jsonb_agg(to_jsonb(pm) order by pm.id) from public.class_payment_movements pm where pm.class_id=p_class_id),'[]'::jsonb)
  ) into v_financial_snapshot;

  for v_m in
    select grant_id,coalesce(sum(-delta_minutes),0)::integer as minutes
    from public.credit_movements
    where class_id=p_class_id and movement_type='class' and delta_minutes<0
    group by grant_id
  loop
    if v_m.minutes>0 then
      insert into public.credit_movements(grant_id,class_id,movement_type,delta_minutes,note,created_by)
      values(v_m.grant_id,p_class_id,'adjustment',v_m.minutes,'Reapertura de clase · devolución de consumo',(select auth.uid()));
      update public.credit_grants set status='active',updated_at=now() where id=v_m.grant_id;
    end if;
  end loop;

  for v_item in select * from public.class_financial_items where class_id=p_class_id and item_type='pair_transfer' order by id loop
    if v_item.source_grant_id is not null and coalesce(v_item.minutes,0)>0 then
      insert into public.credit_movements(grant_id,person_id,class_id,movement_type,delta_minutes,note,created_by)
      values(v_item.source_grant_id,v_item.person_id,p_class_id,'adjustment',v_item.minutes,'Reapertura de clase · devolución de transferencia',(select auth.uid()));
      update public.credit_grants set status='active',updated_at=now() where id=v_item.source_grant_id;
    end if;
    if v_item.target_grant_id is not null then
      select coalesce(sum(delta_minutes),0)::integer into v_balance from public.credit_movements where grant_id=v_item.target_grant_id;
      if v_balance>0 then
        insert into public.credit_movements(grant_id,class_id,movement_type,delta_minutes,note,created_by)
        values(v_item.target_grant_id,p_class_id,'adjustment',-v_balance,'Reapertura de clase · anulación del saldo transferido',(select auth.uid()));
      end if;
      update public.credit_grants set status='cancelled',updated_at=now() where id=v_item.target_grant_id;
    end if;
  end loop;

  for v_art in select * from public.class_close_grant_artifacts where class_id=p_class_id order by id loop
    select coalesce(sum(delta_minutes),0)::integer into v_balance from public.credit_movements where grant_id=v_art.grant_id;
    if v_art.artifact_type in ('direct_payment','regularization') then
      if v_balance<>0 then
        insert into public.credit_movements(grant_id,class_id,movement_type,delta_minutes,note,created_by)
        values(v_art.grant_id,p_class_id,'adjustment',-v_balance,'Reapertura de clase · anulación de bono generado en el cierre',(select auth.uid()));
      end if;
      update public.credit_grants set status='cancelled',payment_status='pending',updated_at=now() where id=v_art.grant_id;
    elsif v_art.artifact_type='quick_bonus' then
      update public.credit_grants set status=case when v_balance>0 then 'active' else status end,payment_status='pending',updated_at=now() where id=v_art.grant_id;
    end if;
  end loop;

  select coalesce(array_agg(id),'{}'::bigint[]) into v_incident_ids
    from public.student_incidents where related_class_id=p_class_id and incident_type='negative_balance';
  delete from public.student_incident_people where incident_id=any(v_incident_ids);
  delete from public.student_incidents where id=any(v_incident_ids);

  delete from public.class_payment_movements where class_id=p_class_id;
  delete from public.class_financial_accounts where class_id=p_class_id;
  delete from public.class_financial_items where class_id=p_class_id;
  delete from public.class_close_grant_artifacts where class_id=p_class_id;

  update public.class_participants
    set attendance_status='planned',billing_grant_id=null,billed_minutes=0,uncovered_minutes=0,billing_status='planned',updated_at=now()
    where class_id=p_class_id;

  update public.classes
    set status='active',duration_minutes=coalesce(v_original_duration,duration_minutes),
        administrative_finished_at=null,administratively_finished_by=null,pedagogy_closed_at=null,
        billed_duration_minutes=null,duration_source=null,actual_end_at=null,actual_duration_minutes=null,updated_at=now()
    where id=p_class_id returning * into v_class;

  insert into public.audit_events(event_type,entity_type,entity_id,summary,detail,actor_user_id)
  values('class_administrative_reopened','class',p_class_id::text,'Cierre administrativo deshecho',
    jsonb_build_object('financial_snapshot',v_financial_snapshot,'original_duration_restored',v_original_duration,'incident_ids',v_incident_ids),
    (select auth.uid()));
  return v_class;
end;
$$;

grant execute on function public.reopen_administratively_finished_class(bigint) to authenticated;

create or replace function private.backup_tables_for_domain(p_domain text)
returns text[]
language sql
stable
set search_path=''
as $$
  select case p_domain
    when 'people' then array[
      'people','student_profiles','student_dance_profiles','crm_profiles','crm_activities',
      'student_incidents','student_incident_people'
    ]::text[]
    when 'classes' then array[
      'catalog_terms','classes','class_participants','class_notes','student_evaluations',
      'class_financial_items','class_financial_accounts','class_payment_movements','class_video_resources','class_close_grant_artifacts'
    ]::text[]
    when 'credits' then array[
      'people','student_profiles','credit_grants','credit_grant_members','credit_movements',
      'student_incidents','student_incident_people','class_financial_items','class_financial_accounts','class_payment_movements','class_close_grant_artifacts'
    ]::text[]
    when 'teaching' then array[
