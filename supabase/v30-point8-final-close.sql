create or replace function public.transfer_individual_credit_to_pair(
  p_class_id bigint,
  p_source_grant_id bigint,
  p_minutes integer,
  p_fee_cents integer default 0
)
returns public.credit_grants
language plpgsql
set search_path=''
as $$
declare
  v_class public.classes;
  v_source public.credit_grants;
  v_source_people bigint[];
  v_class_people bigint[];
  v_source_balance integer;
  v_target public.credit_grants;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para transferir saldo.' using errcode='42501'; end if;
  if p_minutes is null or p_minutes<=0 then raise exception 'Indica los minutos que quieres transferir.' using errcode='22023'; end if;
  if coalesce(p_fee_cents,0)<0 then raise exception 'El coste adicional no puede ser negativo.' using errcode='22023'; end if;

  select * into v_class from public.classes where id=p_class_id for update;
  if not found then raise exception 'La clase no existe.' using errcode='P0002'; end if;
  if v_class.class_type<>'pair' then raise exception 'La transferencia solo está disponible en clases en pareja.' using errcode='22023'; end if;
  if v_class.status not in ('scheduled','active') or v_class.administrative_finished_at is not null then
    raise exception 'La clase ya no admite transferencias de saldo.' using errcode='22023';
  end if;
  if exists(select 1 from public.class_financial_accounts where class_id=p_class_id) then
    raise exception 'La clase ya tiene un cierre económico.' using errcode='22023';
  end if;

  select coalesce(array_agg(person_id order by person_id),'{}'::bigint[]) into v_class_people
    from public.class_participants where class_id=p_class_id;
  if cardinality(v_class_people)<>2 then raise exception 'La clase en pareja debe tener dos alumnos.' using errcode='22023'; end if;

  select * into v_source from public.credit_grants
    where id=p_source_grant_id and modality='individual' and status='active'
      and (expires_at is null or expires_at>now())
    for update;
  if not found then raise exception 'El bono individual no está activo o ha caducado.' using errcode='22023'; end if;
  select coalesce(array_agg(person_id order by person_id),'{}'::bigint[]) into v_source_people
    from public.credit_grant_members where grant_id=v_source.id;
  if cardinality(v_source_people)<>1 or not (v_source_people[1]=any(v_class_people)) then
    raise exception 'El bono individual no pertenece a uno de los alumnos de esta clase.' using errcode='22023';
  end if;
  select coalesce(sum(delta_minutes),0)::integer into v_source_balance
    from public.credit_movements where grant_id=v_source.id;
  if p_minutes>v_source_balance then raise exception 'No hay tantos minutos disponibles en el bono individual.' using errcode='22023'; end if;

  select * into v_target from public.create_credit_grant(
    v_class_people,'pair',p_minutes,0,'Transferencia a pareja','paid'
  );
  update public.credit_grants set expires_at=v_source.expires_at,updated_at=now() where id=v_target.id returning * into v_target;

  insert into public.credit_movements(grant_id,person_id,class_id,movement_type,delta_minutes,note,created_by)
  values(v_source.id,v_source_people[1],p_class_id,'adjustment',-p_minutes,
    'Transferencia a bono de pareja '||v_target.id::text,(select auth.uid()));
  if v_source_balance-p_minutes<=0 then
    update public.credit_grants set status='exhausted',updated_at=now() where id=v_source.id;
  end if;

  insert into public.class_financial_items(class_id,item_type,concept,amount_cents,minutes,person_id,source_grant_id,target_grant_id,created_by)
  values(p_class_id,'pair_transfer','Conversión de saldo individual a pareja',coalesce(p_fee_cents,0),p_minutes,v_source_people[1],v_source.id,v_target.id,(select auth.uid()));

  insert into public.audit_events(event_type,entity_type,entity_id,summary,detail,actor_user_id)
  values('pair_credit_transfer','class',p_class_id::text,'Saldo individual transferido a pareja',
    jsonb_build_object('source_grant_id',v_source.id,'target_grant_id',v_target.id,'minutes',p_minutes,'fee_cents',coalesce(p_fee_cents,0)),
    (select auth.uid()));
  return v_target;
end;
$$;

grant execute on function public.transfer_individual_credit_to_pair(bigint,bigint,integer,integer) to authenticated;

create or replace function public.administratively_finish_class_v6(
  p_class_id bigint,
  p_person_ids bigint[],
  p_grant_ids bigint[] default null,
  p_duration_minutes integer default null,
  p_direct_payment_price_cents integer default null,
  p_supplements jsonb default '[]'::jsonb,
  p_regularizations jsonb default '[]'::jsonb,
  p_paid_now_cents integer default null,
  p_quick_created_grant_id bigint default null
)
returns public.classes
language plpgsql
set search_path=''
as $$
declare
  v_class public.classes;
  v_result public.classes;
  v_account public.class_financial_accounts;
  v_item_total integer:=0;
  v_quick_price integer:=0;
  v_total integer:=0;
  v_paid integer:=0;
  v_direct_grant_id bigint;
  v_reg jsonb;
  v_source_grant_id bigint;
  v_reg_minutes integer;
  v_reg_amount integer;
  v_reg_person_ids bigint[];
  v_source_modality text;
  v_class_people bigint[];
  v_shortfall integer;
  v_new_grant public.credit_grants;
  v_seen_sources bigint[]:='{}'::bigint[];
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para terminar clases.' using errcode='42501'; end if;
  select * into v_class from public.classes where id=p_class_id for update;
  if not found then raise exception 'La clase no existe.' using errcode='P0002'; end if;
  select * into v_account from public.class_financial_accounts where class_id=p_class_id;
  if found then return v_class; end if;

  if p_regularizations is null then p_regularizations:='[]'::jsonb; end if;
  if jsonb_typeof(p_regularizations)<>'array' or jsonb_array_length(p_regularizations)>10 then
    raise exception 'Las regularizaciones no son válidas.' using errcode='22023';
  end if;

  if p_quick_created_grant_id is not null then
    if not p_quick_created_grant_id=any(coalesce(p_grant_ids,'{}'::bigint[])) then
      raise exception 'El bono rápido no coincide con el bono usado en la clase.' using errcode='22023';
    end if;
    select price_cents into v_quick_price from public.credit_grants
      where id=p_quick_created_grant_id and created_by=(select auth.uid());
    if not found then raise exception 'El bono rápido no pertenece a este cierre.' using errcode='22023'; end if;
  end if;

  v_result:=public.administratively_finish_class_v4(
    p_class_id,p_person_ids,p_grant_ids,p_duration_minutes,p_direct_payment_price_cents,
    null,0,p_supplements
  );

  select coalesce(array_agg(person_id order by person_id),'{}'::bigint[]) into v_class_people
    from public.class_participants where class_id=p_class_id;

  for v_reg in select value from jsonb_array_elements(p_regularizations) s(value) loop
    if jsonb_typeof(v_reg)<>'object' then raise exception 'Regularización no válida.' using errcode='22023'; end if;
    if coalesce(v_reg->>'source_grant_id','') !~ '^[0-9]+$'
       or coalesce(v_reg->>'minutes','') !~ '^[0-9]+$'
       or coalesce(v_reg->>'amount_cents','') !~ '^[0-9]+$' then
      raise exception 'Regularización no válida.' using errcode='22023';
    end if;
    v_source_grant_id:=(v_reg->>'source_grant_id')::bigint;
    v_reg_minutes:=(v_reg->>'minutes')::integer;
    v_reg_amount:=(v_reg->>'amount_cents')::integer;
    if v_reg_minutes<=0 or v_reg_minutes>480 or v_reg_amount<0 or v_reg_amount>10000000 then
      raise exception 'Los minutos o el importe de regularización no son válidos.' using errcode='22023';
    end if;
    if v_source_grant_id=any(v_seen_sources) then raise exception 'Un bono no puede regularizarse dos veces en el mismo cierre.' using errcode='22023'; end if;
    v_seen_sources:=array_append(v_seen_sources,v_source_grant_id);

    select modality into v_source_modality from public.credit_grants where id=v_source_grant_id;
    if not found or v_source_modality<>v_class.class_type then raise exception 'El bono de la regularización no es compatible.' using errcode='22023'; end if;

    if v_source_modality='pair' then
      v_reg_person_ids:=v_class_people;
      if (select count(*) from public.class_participants where class_id=p_class_id and billing_grant_id=v_source_grant_id)<>cardinality(v_class_people) then
        raise exception 'El bono de pareja no coincide con el usado en la clase.' using errcode='22023';
      end if;
      select min(uncovered_minutes) into v_shortfall from public.class_participants
        where class_id=p_class_id and billing_grant_id=v_source_grant_id;
    else
      select array[person_id]::bigint[],uncovered_minutes into v_reg_person_ids,v_shortfall
        from public.class_participants
        where class_id=p_class_id and billing_grant_id=v_source_grant_id
        order by person_id limit 1;
      if v_reg_person_ids is null then raise exception 'El bono individual no coincide con el usado en la clase.' using errcode='22023'; end if;
    end if;
    if coalesce(v_shortfall,0)<=0 or v_reg_minutes>v_shortfall then
      raise exception 'La regularización supera los minutos pendientes.' using errcode='22023';
    end if;

    select * into v_new_grant from public.create_credit_grant(
      v_reg_person_ids,v_source_modality,v_reg_minutes,v_reg_amount,'Regularización de clase','pending'
    );
    insert into public.credit_movements(grant_id,person_id,class_id,movement_type,delta_minutes,note,created_by)
    values(v_new_grant.id,case when cardinality(v_reg_person_ids)=1 then v_reg_person_ids[1] else null end,p_class_id,'class',-v_reg_minutes,'Regularización consumida en la clase',(select auth.uid()));
    update public.credit_grants set status='exhausted',updated_at=now() where id=v_new_grant.id;

    update public.class_participants
      set uncovered_minutes=greatest(uncovered_minutes-v_reg_minutes,0),
          billing_status=case when greatest(uncovered_minutes-v_reg_minutes,0)=0 then 'covered' else 'partial' end,
          updated_at=now()
      where class_id=p_class_id and person_id=any(v_reg_person_ids);

    update public.student_incidents
      set remaining_minutes=greatest(remaining_minutes-v_reg_minutes,0),
          status=case when greatest(remaining_minutes-v_reg_minutes,0)=0 then 'resolved' else status end,
          resolution_mode=case when greatest(remaining_minutes-v_reg_minutes,0)=0 then 'regularized_at_close' else resolution_mode end,
          resolution_note=case when greatest(remaining_minutes-v_reg_minutes,0)=0 then 'Regularizado durante el cierre de la clase.' else resolution_note end,
          resolution_grant_id=case when greatest(remaining_minutes-v_reg_minutes,0)=0 then v_new_grant.id else resolution_grant_id end,
          resolved_by=case when greatest(remaining_minutes-v_reg_minutes,0)=0 then (select auth.uid()) else resolved_by end,
          resolved_at=case when greatest(remaining_minutes-v_reg_minutes,0)=0 then now() else resolved_at end,
          updated_at=now()
      where related_class_id=p_class_id and incident_type='negative_balance' and status='open'
        and (related_grant_id=v_source_grant_id or (related_grant_id is null and exists(select 1 from public.student_incident_people sip where sip.incident_id=student_incidents.id and sip.person_id=any(v_reg_person_ids))));

    insert into public.class_financial_items(class_id,item_type,concept,amount_cents,minutes,person_id,source_grant_id,target_grant_id,created_by)
    values(p_class_id,'regularization','Regularización de saldo',v_reg_amount,v_reg_minutes,
      case when cardinality(v_reg_person_ids)=1 then v_reg_person_ids[1] else null end,
      v_source_grant_id,v_new_grant.id,(select auth.uid()));
    insert into public.class_close_grant_artifacts(class_id,grant_id,artifact_type,created_by)
    values(p_class_id,v_new_grant.id,'regularization',(select auth.uid())) on conflict do nothing;
  end loop;

  if p_quick_created_grant_id is not null then
    insert into public.class_close_grant_artifacts(class_id,grant_id,artifact_type,created_by)
    values(p_class_id,p_quick_created_grant_id,'quick_bonus',(select auth.uid())) on conflict do nothing;
  end if;

  if p_direct_payment_price_cents is not null then
    select min(billing_grant_id) into v_direct_grant_id from public.class_participants
      where class_id=p_class_id and billing_grant_id is not null;
    if v_direct_grant_id is not null then
      insert into public.class_close_grant_artifacts(class_id,grant_id,artifact_type,created_by)
      values(p_class_id,v_direct_grant_id,'direct_payment',(select auth.uid())) on conflict do nothing;
    end if;
  end if;

  select coalesce(sum(amount_cents),0)::integer into v_item_total from public.class_financial_items where class_id=p_class_id;
  v_total:=v_item_total+coalesce(p_direct_payment_price_cents,0)+coalesce(v_quick_price,0);
  v_paid:=coalesce(p_paid_now_cents,v_total);
  if v_paid<0 or v_paid>v_total then raise exception 'El pago recibido debe estar entre 0 y el total de la clase.' using errcode='22023'; end if;

  insert into public.class_financial_accounts(class_id,total_due_cents,paid_cents,status,created_by)
  values(p_class_id,v_total,v_paid,
    case when v_paid>=v_total then 'paid' when v_paid=0 then 'unpaid' else 'partial' end,
    (select auth.uid())) returning * into v_account;
  if v_paid>0 then
    insert into public.class_payment_movements(class_id,amount_cents,note,created_by)
    values(p_class_id,v_paid,'Pago registrado al terminar la clase',(select auth.uid()));
  end if;

  update public.credit_grants g
    set payment_status=case when v_paid>=v_total then 'paid' else 'pending' end,updated_at=now()
    where exists(select 1 from public.class_close_grant_artifacts a where a.class_id=p_class_id and a.grant_id=g.id);

  insert into public.audit_events(event_type,entity_type,entity_id,summary,detail,actor_user_id)
  values('class_payment_status','class',p_class_id::text,'Pago de clase registrado',
    jsonb_build_object('total_due_cents',v_total,'paid_now_cents',v_paid,'outstanding_cents',v_total-v_paid,'status',v_account.status,'regularizations',p_regularizations),
    (select auth.uid()));
  return v_result;
end;
$$;

