create table if not exists public.evaluation_sessions(
  id bigint generated by default as identity primary key,
  person_id bigint not null references public.student_profiles(person_id) on delete cascade,
  class_id bigint references public.classes(id) on delete set null,
  style_term_id bigint not null references public.catalog_terms(id) on delete restrict,
  role_term_id bigint not null references public.catalog_terms(id) on delete restrict,
  level_term_id bigint not null references public.catalog_terms(id) on delete restrict,
  evaluation_kind text not null check (evaluation_kind in ('initial','class','manual','reevaluation')),
  status text not null default 'draft' check (status in ('draft','completed')),
  note text,
  evaluated_by uuid references auth.users(id) on delete set null,
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check ((status='draft' and completed_at is null) or status='completed')
);

create index if not exists evaluation_sessions_person_idx on public.evaluation_sessions(person_id,started_at desc);
create index if not exists evaluation_sessions_context_idx on public.evaluation_sessions(person_id,style_term_id,role_term_id,level_term_id,started_at desc);
create unique index if not exists evaluation_sessions_one_class_context_uidx
  on public.evaluation_sessions(class_id,person_id,style_term_id,role_term_id,level_term_id)
  where class_id is not null;

alter table public.student_evaluations add column if not exists session_id bigint references public.evaluation_sessions(id) on delete cascade;
alter table public.student_evaluations drop constraint if exists student_evaluations_class_id_person_id_aptitude_term_id_key;
alter table public.student_evaluations drop constraint if exists student_evaluations_evaluation_kind_check;
alter table public.student_evaluations add constraint student_evaluations_evaluation_kind_check
  check (evaluation_kind in ('initial','class','manual','reevaluation'));
create unique index if not exists student_evaluations_session_aptitude_uidx
  on public.student_evaluations(session_id,aptitude_term_id) where session_id is not null;
create index if not exists student_evaluations_person_created_idx on public.student_evaluations(person_id,created_at desc);

-- Conserva íntegramente las evaluaciones históricas y las agrupa en sesiones reales.
insert into public.evaluation_sessions(person_id,class_id,style_term_id,role_term_id,level_term_id,evaluation_kind,status,note,evaluated_by,started_at,completed_at,created_at,updated_at)
select e.person_id,e.class_id,e.style_term_id,e.role_term_id,e.level_term_id,e.evaluation_kind,'completed',null,
       (array_agg(e.evaluated_by order by e.created_at) filter (where e.evaluated_by is not null))[1],
       min(e.created_at),max(e.updated_at),min(e.created_at),max(e.updated_at)
from public.student_evaluations e
where e.session_id is null
group by e.person_id,e.class_id,e.style_term_id,e.role_term_id,e.level_term_id,e.evaluation_kind
on conflict do nothing;

update public.student_evaluations e
set session_id=s.id
from public.evaluation_sessions s
where e.session_id is null
  and s.person_id=e.person_id
  and s.class_id is not distinct from e.class_id
  and s.style_term_id=e.style_term_id
  and s.role_term_id=e.role_term_id
  and s.level_term_id=e.level_term_id
  and s.evaluation_kind=e.evaluation_kind;

alter table public.evaluation_sessions enable row level security;
drop policy if exists evaluation_sessions_staff_all on public.evaluation_sessions;
create policy evaluation_sessions_staff_all on public.evaluation_sessions for all to authenticated
  using ((select private.is_staff())) with check ((select private.is_staff()) and evaluated_by=(select auth.uid()));
drop policy if exists evaluation_sessions_student_select on public.evaluation_sessions;
create policy evaluation_sessions_student_select on public.evaluation_sessions for select to authenticated
  using (person_id=(select private.current_person_id()) and status='completed');

drop policy if exists student_evaluations_select on public.student_evaluations;
create policy student_evaluations_select on public.student_evaluations for select to authenticated using (
  (select private.is_staff())
  or (
    person_id=(select private.current_person_id())
    and session_id is not null
    and exists(select 1 from public.evaluation_sessions s where s.id=session_id and s.status='completed')
  )
);

grant select,insert,update,delete on public.evaluation_sessions to authenticated;
grant usage,select on sequence public.evaluation_sessions_id_seq to authenticated;

create or replace function public.start_student_evaluation(
  p_person_id bigint,
  p_level_term_id bigint,
  p_evaluation_kind text,
  p_style_term_id bigint default null,
  p_role_term_id bigint default null,
  p_class_id bigint default null,
  p_note text default null
) returns public.evaluation_sessions
language plpgsql set search_path='' as $$
declare
  v_session public.evaluation_sessions;
  v_style bigint:=p_style_term_id;
  v_role bigint:=p_role_term_id;
  v_class_style bigint;
  v_class_role bigint;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para evaluar alumnos.' using errcode='42501'; end if;
  if p_evaluation_kind not in ('initial','class','manual','reevaluation') then raise exception 'Tipo de evaluación no válido.' using errcode='22023'; end if;
  if not exists(select 1 from public.student_profiles sp join public.people p on p.id=sp.person_id where sp.person_id=p_person_id and sp.active and p.active) then raise exception 'El alumno no está disponible.' using errcode='22023'; end if;
  if not exists(select 1 from public.catalog_terms where id=p_level_term_id and taxonomy='dance_level' and active) then raise exception 'Selecciona un nivel válido.' using errcode='22023'; end if;

  if p_class_id is not null then
    select c.style_term_id,cp.role_term_id into v_class_style,v_class_role
    from public.classes c join public.class_participants cp on cp.class_id=c.id
    where c.id=p_class_id and cp.person_id=p_person_id and c.status in ('active','finished') and c.pedagogy_closed_at is null;
    if not found or v_class_style is null or v_class_role is null then raise exception 'La clase no tiene contexto suficiente para evaluar.' using errcode='22023'; end if;
    if v_style is not null and v_style<>v_class_style then raise exception 'El estilo no coincide con esta clase.' using errcode='22023'; end if;
    if v_role is not null and v_role<>v_class_role then raise exception 'El rol no coincide con esta clase.' using errcode='22023'; end if;
    v_style:=v_class_style; v_role:=v_class_role;
    if p_evaluation_kind not in ('initial','class') then raise exception 'Las evaluaciones manuales o reevaluaciones se crean desde la ficha del alumno.' using errcode='22023'; end if;
    select * into v_session from public.evaluation_sessions
      where class_id=p_class_id and person_id=p_person_id and style_term_id=v_style and role_term_id=v_role and level_term_id=p_level_term_id
      order by id desc limit 1;
    if found then
      if v_session.status='completed' then raise exception 'La evaluación de esta clase ya está cerrada.' using errcode='22023'; end if;
      return v_session;
    end if;
  else
    if p_evaluation_kind='class' then raise exception 'Una evaluación de clase necesita una clase.' using errcode='22023'; end if;
    if v_style is null or not exists(select 1 from public.catalog_terms where id=v_style and taxonomy='dance_style' and active) then raise exception 'Selecciona un estilo válido.' using errcode='22023'; end if;
    if v_role is null or not exists(select 1 from public.catalog_terms where id=v_role and taxonomy='dance_role' and active) then raise exception 'Selecciona un rol válido.' using errcode='22023'; end if;
    if p_evaluation_kind='initial' and exists(select 1 from public.evaluation_sessions where person_id=p_person_id and style_term_id=v_style and role_term_id=v_role and status='completed') then
      raise exception 'Este contexto ya tiene una evaluación inicial; utiliza reevaluación.' using errcode='22023';
    end if;
  end if;

  insert into public.evaluation_sessions(person_id,class_id,style_term_id,role_term_id,level_term_id,evaluation_kind,status,note,evaluated_by)
  values(p_person_id,p_class_id,v_style,v_role,p_level_term_id,p_evaluation_kind,'draft',nullif(btrim(coalesce(p_note,'')),''),(select auth.uid()))
  returning * into v_session;
  return v_session;
end $$;

create or replace function public.save_evaluation_score(
  p_session_id bigint,
  p_aptitude_term_id bigint,
  p_score smallint,
  p_note text default null
) returns public.student_evaluations
language plpgsql set search_path='' as $$
declare
  v_session public.evaluation_sessions;
  v_level_key text;
  v_style_key text;
  v_role_key text;
  v_eval public.student_evaluations;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para evaluar alumnos.' using errcode='42501'; end if;
  if p_score not in (0,25,50,75,100) then raise exception 'La puntuación debe ser 0, 25, 50, 75 o 100.' using errcode='22023'; end if;
  select * into v_session from public.evaluation_sessions where id=p_session_id for update;
  if not found then raise exception 'La evaluación no existe.' using errcode='P0002'; end if;
  if v_session.status<>'draft' then raise exception 'Esta evaluación ya está cerrada.' using errcode='22023'; end if;
  select term_key into v_level_key from public.catalog_terms where id=v_session.level_term_id and taxonomy='dance_level' and active;
  select term_key into v_style_key from public.catalog_terms where id=v_session.style_term_id and taxonomy='dance_style' and active;
  select term_key into v_role_key from public.catalog_terms where id=v_session.role_term_id and taxonomy='dance_role' and active;
  if not exists(
    select 1 from public.catalog_terms a
    where a.id=p_aptitude_term_id and a.taxonomy='aptitude' and a.active
      and (not (a.metadata ? 'levels') or coalesce((a.metadata->'levels') ? v_level_key,false))
      and (not (a.metadata ? 'styles') or coalesce((a.metadata->'styles') ? v_style_key,false))
      and (not (a.metadata ? 'roles') or coalesce((a.metadata->'roles') ? v_role_key,false))
  ) then raise exception 'Este parámetro no corresponde al nivel, estilo o rol evaluado.' using errcode='22023'; end if;

  insert into public.student_evaluations(session_id,person_id,class_id,style_term_id,role_term_id,level_term_id,aptitude_term_id,evaluation_kind,score,note,evaluated_by)
  values(v_session.id,v_session.person_id,v_session.class_id,v_session.style_term_id,v_session.role_term_id,v_session.level_term_id,p_aptitude_term_id,v_session.evaluation_kind,p_score,nullif(btrim(coalesce(p_note,'')),''),(select auth.uid()))
  on conflict(session_id,aptitude_term_id) where session_id is not null do update
    set score=excluded.score,note=excluded.note,evaluated_by=excluded.evaluated_by,updated_at=now()
  returning * into v_eval;
  update public.evaluation_sessions set updated_at=now() where id=v_session.id;
  return v_eval;
end $$;

create or replace function public.complete_evaluation_session(p_session_id bigint)
returns public.evaluation_sessions
language plpgsql set search_path='' as $$
declare v_session public.evaluation_sessions;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para cerrar evaluaciones.' using errcode='42501'; end if;
  select * into v_session from public.evaluation_sessions where id=p_session_id for update;
  if not found then raise exception 'La evaluación no existe.' using errcode='P0002'; end if;
  if v_session.status='completed' then return v_session; end if;
  if not exists(select 1 from public.student_evaluations where session_id=p_session_id) then raise exception 'Añade al menos un parámetro antes de finalizar.' using errcode='22023'; end if;
  update public.evaluation_sessions set status='completed',completed_at=now(),updated_at=now() where id=p_session_id returning * into v_session;
  return v_session;
end $$;

create or replace function public.save_class_evaluation_v2(
  p_class_id bigint,
  p_person_id bigint,
  p_level_term_id bigint,
  p_aptitude_term_id bigint,
  p_score smallint
) returns public.student_evaluations
language plpgsql set search_path='' as $$
declare
  v_style bigint;
  v_role bigint;
  v_kind text;
  v_session public.evaluation_sessions;
  v_eval public.student_evaluations;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para evaluar alumnos.' using errcode='42501'; end if;
  select c.style_term_id,cp.role_term_id into v_style,v_role
  from public.classes c join public.class_participants cp on cp.class_id=c.id
  where c.id=p_class_id and cp.person_id=p_person_id and c.status in ('active','finished') and c.pedagogy_closed_at is null;
  if not found or v_style is null or v_role is null then raise exception 'La clase no tiene estilo o rol suficiente para evaluar.' using errcode='22023'; end if;

  select * into v_session from public.evaluation_sessions
  where class_id=p_class_id and person_id=p_person_id and style_term_id=v_style and role_term_id=v_role and level_term_id=p_level_term_id
  order by id desc limit 1;
  if not found then
    v_kind:=case when exists(
      select 1 from public.evaluation_sessions s
      where s.person_id=p_person_id and s.style_term_id=v_style and s.role_term_id=v_role and s.status='completed'
    ) then 'class' else 'initial' end;
    v_session:=public.start_student_evaluation(p_person_id,p_level_term_id,v_kind,v_style,v_role,p_class_id,null);
  end if;
  v_eval:=public.save_evaluation_score(v_session.id,p_aptitude_term_id,p_score,null);
  return v_eval;
end $$;

-- Compatibilidad con la llamada histórica: usa el nivel actual de la clase.
create or replace function public.save_class_evaluation(p_class_id bigint,p_person_id bigint,p_aptitude_term_id bigint,p_score smallint)
returns public.student_evaluations
language plpgsql set search_path='' as $$
declare v_level bigint; v_eval public.student_evaluations;
begin
  select cp.level_term_id into v_level from public.class_participants cp where cp.class_id=p_class_id and cp.person_id=p_person_id;
  if v_level is null then raise exception 'Selecciona primero el nivel que quieres evaluar.' using errcode='22023'; end if;
  v_eval:=public.save_class_evaluation_v2(p_class_id,p_person_id,v_level,p_aptitude_term_id,p_score);
  return v_eval;
end $$;

-- Las evaluaciones hechas durante una clase quedan ocultas al alumno hasta el cierre pedagógico.
create or replace function private.complete_class_evaluation_sessions()
returns trigger language plpgsql set search_path='' as $$
begin
  if new.pedagogy_closed_at is not null and old.pedagogy_closed_at is null then
    update public.evaluation_sessions
    set status='completed',completed_at=coalesce(completed_at,new.pedagogy_closed_at),updated_at=now()
    where class_id=new.id and status='draft' and exists(select 1 from public.student_evaluations e where e.session_id=evaluation_sessions.id);
  end if;
  return new;
end $$;
drop trigger if exists trg_complete_class_evaluation_sessions on public.classes;
create trigger trg_complete_class_evaluation_sessions after update of pedagogy_closed_at on public.classes
for each row execute function private.complete_class_evaluation_sessions();

