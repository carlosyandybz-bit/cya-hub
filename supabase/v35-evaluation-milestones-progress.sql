create or replace function private.refresh_aptitude_progress(p_progress_id bigint,p_class_id bigint default null)
returns public.student_aptitude_progress
language plpgsql set search_path='' as $$
declare
  v_progress public.student_aptitude_progress;
  v_pending_threshold smallint;
  v_accepted_threshold smallint:=0;
  v_next public.evaluation_milestones;
begin
  select * into v_progress from public.student_aptitude_progress where id=p_progress_id for update;
  if not found then raise exception 'El progreso no existe.' using errcode='P0002'; end if;

  select coalesce(max(m.threshold_score),0)::smallint into v_accepted_threshold
  from public.evaluation_milestone_decisions d
  join public.evaluation_milestones m on m.id=d.milestone_id
  where d.progress_id=v_progress.id and d.decision='accepted';

  if v_progress.pending_milestone_id is not null then
    select threshold_score into v_pending_threshold from public.evaluation_milestones where id=v_progress.pending_milestone_id and active;
    if v_pending_threshold is not null and not exists(
      select 1 from public.evaluation_milestone_decisions d
      where d.progress_id=v_progress.id and d.milestone_id=v_progress.pending_milestone_id and d.decision='accepted'
    ) then
      update public.student_aptitude_progress
      set effective_score=least(raw_score,v_pending_threshold),updated_at=now()
      where id=v_progress.id returning * into v_progress;
      return v_progress;
    end if;
    update public.student_aptitude_progress set pending_milestone_id=null,pending_since_class_id=null,updated_at=now() where id=v_progress.id returning * into v_progress;
  end if;

  select m.* into v_next
  from public.evaluation_milestones m
  where m.active
    and m.style_term_id=v_progress.style_term_id
    and m.role_term_id=v_progress.role_term_id
    and m.level_term_id=v_progress.level_term_id
    and m.aptitude_term_id=v_progress.aptitude_term_id
    and m.threshold_score>v_accepted_threshold
    and m.threshold_score<=v_progress.raw_score
  order by m.threshold_score,m.sort_order,m.id
  limit 1;

  if found then
    update public.student_aptitude_progress
    set pending_milestone_id=v_next.id,
        pending_since_class_id=coalesce(p_class_id,pending_since_class_id),
        effective_score=least(raw_score,v_next.threshold_score),
        updated_at=now()
    where id=v_progress.id returning * into v_progress;
  else
    update public.student_aptitude_progress
    set effective_score=raw_score,pending_milestone_id=null,pending_since_class_id=null,updated_at=now()
    where id=v_progress.id returning * into v_progress;
  end if;
  return v_progress;
end $$;

create or replace function public.ensure_student_aptitude_progress(
  p_person_id bigint,p_style_term_id bigint,p_role_term_id bigint,p_level_term_id bigint
) returns setof public.student_aptitude_progress
language plpgsql set search_path='' as $$
declare v_style_key text; v_role_key text; v_level_key text;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para preparar evaluaciones.' using errcode='42501'; end if;
  if not exists(select 1 from public.student_profiles sp join public.people p on p.id=sp.person_id where sp.person_id=p_person_id and sp.active and p.active) then raise exception 'El alumno no está disponible.' using errcode='22023'; end if;
  select term_key into v_style_key from public.catalog_terms where id=p_style_term_id and taxonomy='dance_style' and active;
  select term_key into v_role_key from public.catalog_terms where id=p_role_term_id and taxonomy='dance_role' and active;
  select term_key into v_level_key from public.catalog_terms where id=p_level_term_id and taxonomy='dance_level' and active;
  if v_style_key is null or v_role_key is null or v_level_key is null then raise exception 'Falta contexto válido de estilo, rol o nivel.' using errcode='22023'; end if;

  insert into public.student_aptitude_progress(person_id,style_term_id,role_term_id,level_term_id,aptitude_term_id,raw_score,effective_score)
  select p_person_id,p_style_term_id,p_role_term_id,p_level_term_id,a.id,0,0
  from public.catalog_terms a
  where a.taxonomy='aptitude' and a.active
    and (not (a.metadata ? 'styles') or coalesce((a.metadata->'styles') ? v_style_key,false))
    and (not (a.metadata ? 'roles') or coalesce((a.metadata->'roles') ? v_role_key,false))
    and (not (a.metadata ? 'levels') or coalesce((a.metadata->'levels') ? v_level_key,false))
  on conflict(person_id,style_term_id,role_term_id,level_term_id,aptitude_term_id) do nothing;

  return query select p.* from public.student_aptitude_progress p
  where p.person_id=p_person_id and p.style_term_id=p_style_term_id and p.role_term_id=p_role_term_id and p.level_term_id=p_level_term_id
  order by p.aptitude_term_id;
end $$;

create or replace function private.award_teaching_content_points(
  p_class_id bigint,p_person_id bigint,p_content_id bigint,p_source_event_id bigint default null
) returns void
language plpgsql set search_path='' as $$
declare
  v_style bigint; v_role bigint; v_level bigint; v_map public.teaching_content_evaluation_points;
  v_progress public.student_aptitude_progress; v_award_id bigint;
begin
  select c.style_term_id,cp.role_term_id,cp.level_term_id into v_style,v_role,v_level
  from public.classes c join public.class_participants cp on cp.class_id=c.id
  where c.id=p_class_id and cp.person_id=p_person_id;
  if not found or v_style is null or v_role is null or v_level is null then return; end if;

  for v_map in
    select * from public.teaching_content_evaluation_points m
    where m.content_id=p_content_id and m.style_term_id=v_style and m.role_term_id=v_role and m.level_term_id=v_level and m.active
  loop
    insert into public.student_aptitude_progress(person_id,style_term_id,role_term_id,level_term_id,aptitude_term_id,raw_score,effective_score)
    values(p_person_id,v_style,v_role,v_level,v_map.aptitude_term_id,0,0)
    on conflict(person_id,style_term_id,role_term_id,level_term_id,aptitude_term_id) do nothing;

    select * into v_progress from public.student_aptitude_progress
    where person_id=p_person_id and style_term_id=v_style and role_term_id=v_role and level_term_id=v_level and aptitude_term_id=v_map.aptitude_term_id
    for update;

    v_award_id:=null;
    insert into public.evaluation_progress_awards(progress_id,class_id,person_id,content_id,style_term_id,role_term_id,level_term_id,aptitude_term_id,points,source_event_id,awarded_by)
    values(v_progress.id,p_class_id,p_person_id,p_content_id,v_style,v_role,v_level,v_map.aptitude_term_id,v_map.points,p_source_event_id,(select auth.uid()))
    on conflict(person_id,content_id,style_term_id,role_term_id,level_term_id,aptitude_term_id) do nothing
    returning id into v_award_id;

    if v_award_id is not null then
      update public.student_aptitude_progress
      set raw_score=least(100,raw_score+v_map.points),updated_at=now()
      where id=v_progress.id;
      perform private.refresh_aptitude_progress(v_progress.id,p_class_id);
    end if;
  end loop;
end $$;

create or replace function private.class_content_progress_trigger()
returns trigger language plpgsql set search_path='' as $$
begin
  if (new.event_type='status_changed' and new.new_status in ('corrected','explained','completed'))
     or new.event_type='exercise_completed' then
    perform private.award_teaching_content_points(new.class_id,new.person_id,new.content_id,new.id);
  end if;
  return new;
end $$;
drop trigger if exists trg_class_content_progress on public.class_content_events;
create trigger trg_class_content_progress after insert on public.class_content_events
for each row execute function private.class_content_progress_trigger();

create or replace function public.prepare_post_class_evaluation(p_class_id bigint,p_person_id bigint)
returns public.evaluation_sessions
language plpgsql set search_path='' as $$
declare
  v_class public.classes; v_style bigint; v_role bigint; v_level bigint; v_session public.evaluation_sessions;
  v_kind text; v_progress public.student_aptitude_progress;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para evaluar alumnos.' using errcode='42501'; end if;
  select * into v_class from public.classes where id=p_class_id for update;
  if not found then raise exception 'La clase no existe.' using errcode='P0002'; end if;
  if v_class.status<>'finished' or v_class.administrative_finished_at is null then
    raise exception 'La evaluación se realiza después de terminar la parte administrativa de la clase.' using errcode='22023';
  end if;
  if v_class.pedagogy_closed_at is not null then raise exception 'La clase ya está cerrada pedagógicamente.' using errcode='22023'; end if;

  select v_class.style_term_id,cp.role_term_id,cp.level_term_id into v_style,v_role,v_level
  from public.class_participants cp where cp.class_id=p_class_id and cp.person_id=p_person_id;
  if not found or v_style is null or v_role is null or v_level is null then raise exception 'La clase no tiene estilo, rol o nivel suficiente para evaluar.' using errcode='22023'; end if;

  perform public.ensure_student_aptitude_progress(p_person_id,v_style,v_role,v_level);

  select * into v_session from public.evaluation_sessions
  where class_id=p_class_id and person_id=p_person_id and style_term_id=v_style and role_term_id=v_role and level_term_id=v_level
  order by id desc limit 1;

  if not found then
    v_kind:=case when exists(
      select 1 from public.evaluation_sessions s
      where s.person_id=p_person_id and s.style_term_id=v_style and s.role_term_id=v_role and s.status='completed'
    ) then 'class' else 'initial' end;
    insert into public.evaluation_sessions(person_id,class_id,style_term_id,role_term_id,level_term_id,evaluation_kind,status,evaluated_by,started_at)
    values(p_person_id,p_class_id,v_style,v_role,v_level,v_kind,'draft',(select auth.uid()),now()) returning * into v_session;
  elsif v_session.status='completed' then
    return v_session;
  end if;

  for v_progress in select * from public.student_aptitude_progress p
    where p.person_id=p_person_id and p.style_term_id=v_style and p.role_term_id=v_role and p.level_term_id=v_level
  loop
    v_progress:=private.refresh_aptitude_progress(v_progress.id,p_class_id);
    insert into public.student_evaluations(session_id,person_id,class_id,style_term_id,role_term_id,level_term_id,aptitude_term_id,evaluation_kind,score,note,evaluated_by)
    values(v_session.id,p_person_id,p_class_id,v_style,v_role,v_level,v_progress.aptitude_term_id,v_session.evaluation_kind,v_progress.effective_score,null,(select auth.uid()))
    on conflict(session_id,aptitude_term_id) where session_id is not null do update
      set score=excluded.score,evaluated_by=excluded.evaluated_by,updated_at=now();
    update public.student_aptitude_progress set last_evaluation_session_id=v_session.id,updated_at=now() where id=v_progress.id;
  end loop;

  return v_session;
end $$;

create or replace function public.decide_evaluation_milestone(
  p_session_id bigint,p_progress_id bigint,p_decision text,p_descriptor_id bigint default null,p_note text default null
) returns public.evaluation_milestone_decisions
language plpgsql set search_path='' as $$
declare
  v_session public.evaluation_sessions; v_progress public.student_aptitude_progress; v_milestone public.evaluation_milestones;
  v_descriptor public.evaluation_descriptors; v_decision public.evaluation_milestone_decisions; v_has_descriptors boolean;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para confirmar hitos.' using errcode='42501'; end if;
  if p_decision not in ('accepted','rejected') then raise exception 'Decisión de hito no válida.' using errcode='22023'; end if;
  select * into v_session from public.evaluation_sessions where id=p_session_id for update;
  if not found then raise exception 'La evaluación no existe.' using errcode='P0002'; end if;
  if v_session.status<>'draft' or v_session.class_id is null then raise exception 'Esta evaluación no admite decisiones.' using errcode='22023'; end if;
  if not exists(select 1 from public.classes c where c.id=v_session.class_id and c.status='finished' and c.administrative_finished_at is not null and c.pedagogy_closed_at is null) then
    raise exception 'Los hitos se confirman después de terminar la parte administrativa y antes del cierre pedagógico.' using errcode='22023';
  end if;

  select * into v_progress from public.student_aptitude_progress where id=p_progress_id for update;
  if not found or v_progress.person_id<>v_session.person_id or v_progress.style_term_id<>v_session.style_term_id or v_progress.role_term_id<>v_session.role_term_id or v_progress.level_term_id<>v_session.level_term_id then
    raise exception 'El progreso no corresponde a esta evaluación.' using errcode='22023';
  end if;
  if v_progress.pending_milestone_id is null then raise exception 'Este parámetro no tiene ningún hito pendiente.' using errcode='22023'; end if;
  select * into v_milestone from public.evaluation_milestones where id=v_progress.pending_milestone_id and active;
  if not found then raise exception 'El hito pendiente ya no está disponible.' using errcode='22023'; end if;

  select exists(select 1 from public.evaluation_descriptors d where d.milestone_id=v_milestone.id and d.active) into v_has_descriptors;
  if v_has_descriptors and p_descriptor_id is null then raise exception 'Selecciona el descriptor observable que mejor represente al alumno.' using errcode='22023'; end if;
  if p_descriptor_id is not null then
    select * into v_descriptor from public.evaluation_descriptors where id=p_descriptor_id and milestone_id=v_milestone.id and active;
    if not found then raise exception 'El descriptor no corresponde a este hito.' using errcode='22023'; end if;
  end if;

  insert into public.evaluation_milestone_decisions(session_id,progress_id,milestone_id,class_id,decision,descriptor_id,note,decided_by)
  values(v_session.id,v_progress.id,v_milestone.id,v_session.class_id,p_decision,p_descriptor_id,nullif(btrim(coalesce(p_note,'')),''),(select auth.uid()))
  returning * into v_decision;

  if p_decision='accepted' then
    update public.student_aptitude_progress
    set pending_milestone_id=null,pending_since_class_id=null,last_descriptor_id=p_descriptor_id,effective_score=raw_score,updated_at=now()
    where id=v_progress.id;
    v_progress:=private.refresh_aptitude_progress(v_progress.id,v_session.class_id);
  else
    update public.student_aptitude_progress
    set pending_milestone_id=v_milestone.id,pending_since_class_id=coalesce(pending_since_class_id,v_session.class_id),last_descriptor_id=p_descriptor_id,
        effective_score=least(raw_score,v_milestone.threshold_score),updated_at=now()
    where id=v_progress.id returning * into v_progress;
  end if;

  insert into public.student_evaluations(session_id,person_id,class_id,style_term_id,role_term_id,level_term_id,aptitude_term_id,evaluation_kind,score,note,evaluated_by)
  values(v_session.id,v_session.person_id,v_session.class_id,v_session.style_term_id,v_session.role_term_id,v_session.level_term_id,v_progress.aptitude_term_id,v_session.evaluation_kind,v_progress.effective_score,null,(select auth.uid()))
  on conflict(session_id,aptitude_term_id) where session_id is not null do update
    set score=excluded.score,evaluated_by=excluded.evaluated_by,updated_at=now();

  return v_decision;
end $$;

create or replace function public.complete_post_class_evaluation(p_session_id bigint)
returns public.evaluation_sessions
language plpgsql set search_path='' as $$
declare v_session public.evaluation_sessions; v_progress public.student_aptitude_progress;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para cerrar evaluaciones.' using errcode='42501'; end if;
  select * into v_session from public.evaluation_sessions where id=p_session_id for update;
  if not found then raise exception 'La evaluación no existe.' using errcode='P0002'; end if;
  if v_session.status='completed' then return v_session; end if;
  if v_session.class_id is null then raise exception 'Esta operación es solo para evaluaciones posteriores a una clase.' using errcode='22023'; end if;
  if not exists(select 1 from public.classes c where c.id=v_session.class_id and c.status='finished' and c.administrative_finished_at is not null and c.pedagogy_closed_at is null) then
    raise exception 'La evaluación debe cerrarse después de la parte administrativa y antes del cierre pedagógico.' using errcode='22023';
  end if;

  for v_progress in select * from public.student_aptitude_progress p
    where p.person_id=v_session.person_id and p.style_term_id=v_session.style_term_id and p.role_term_id=v_session.role_term_id and p.level_term_id=v_session.level_term_id
  loop
    v_progress:=private.refresh_aptitude_progress(v_progress.id,v_session.class_id);
    if v_progress.pending_milestone_id is not null and not exists(
      select 1 from public.evaluation_milestone_decisions d
      where d.session_id=v_session.id and d.progress_id=v_progress.id and d.milestone_id=v_progress.pending_milestone_id and d.class_id=v_session.class_id
    ) then
      raise exception 'Hay hitos pendientes de confirmar o rechazar antes de cerrar la evaluación.' using errcode='22023';
    end if;
    insert into public.student_evaluations(session_id,person_id,class_id,style_term_id,role_term_id,level_term_id,aptitude_term_id,evaluation_kind,score,note,evaluated_by)
    values(v_session.id,v_session.person_id,v_session.class_id,v_session.style_term_id,v_session.role_term_id,v_session.level_term_id,v_progress.aptitude_term_id,v_session.evaluation_kind,v_progress.effective_score,null,(select auth.uid()))
    on conflict(session_id,aptitude_term_id) where session_id is not null do update
      set score=excluded.score,evaluated_by=excluded.evaluated_by,updated_at=now();
  end loop;

  update public.evaluation_sessions
  set status='completed',completed_at=now(),updated_at=now()
  where id=v_session.id returning * into v_session;
  return v_session;
end $$;

