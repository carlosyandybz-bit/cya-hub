  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (btrim(descriptor_key)<>'' and btrim(label)<>'')
);
create unique index if not exists evaluation_descriptors_milestone_key_uidx
  on public.evaluation_descriptors(milestone_id,descriptor_key);
create index if not exists evaluation_descriptors_milestone_idx
  on public.evaluation_descriptors(milestone_id,sort_order,id);

