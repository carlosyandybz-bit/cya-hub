-- CYA Hub · v35 · Puntos 12–13 · evaluación final por progreso, descriptores e hitos
--
-- Principios:
-- 1) El profesor no introduce puntuaciones numéricas directamente.
-- 2) Los números se conservan únicamente como valor interno/histórico para radar y evolución.
-- 3) El contenido puede aportar puntos de forma idempotente.
-- 4) Al alcanzar un hito, el progreso visible se bloquea en el umbral hasta decisión docente.
-- 5) La evaluación de clase se prepara únicamente después de terminar la parte administrativa.
-- 6) Se conserva evaluation_sessions/student_evaluations para no perder ningún histórico existente.

create table if not exists public.evaluation_milestones(
  id bigint generated by default as identity primary key,
  style_term_id bigint not null references public.catalog_terms(id) on delete restrict,
  role_term_id bigint not null references public.catalog_terms(id) on delete restrict,
  level_term_id bigint not null references public.catalog_terms(id) on delete restrict,
  aptitude_term_id bigint not null references public.catalog_terms(id) on delete restrict,
  milestone_key text not null,
  label text not null,
  threshold_score smallint not null check (threshold_score between 1 and 100),
  sort_order integer not null default 0,
  active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (btrim(milestone_key)<>'' and btrim(label)<>'')
);
create unique index if not exists evaluation_milestones_context_key_uidx
  on public.evaluation_milestones(style_term_id,role_term_id,level_term_id,aptitude_term_id,milestone_key);
create unique index if not exists evaluation_milestones_context_threshold_uidx
  on public.evaluation_milestones(style_term_id,role_term_id,level_term_id,aptitude_term_id,threshold_score);
create index if not exists evaluation_milestones_context_idx
  on public.evaluation_milestones(style_term_id,role_term_id,level_term_id,aptitude_term_id,threshold_score);

create table if not exists public.evaluation_descriptors(
