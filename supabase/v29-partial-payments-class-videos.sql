create or replace function public.record_class_payment(
  p_class_id bigint,
  p_amount_cents integer,
  p_note text default null
)
returns public.class_financial_accounts
language plpgsql
set search_path=''
as $$
declare
  v_account public.class_financial_accounts;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para registrar pagos.' using errcode='42501'; end if;
  if p_amount_cents is null or p_amount_cents<=0 then raise exception 'El importe debe ser mayor que cero.' using errcode='22023'; end if;
  select * into v_account from public.class_financial_accounts where class_id=p_class_id for update;
  if not found then raise exception 'La clase no tiene una cuenta económica abierta.' using errcode='P0002'; end if;
  if p_amount_cents>v_account.outstanding_cents then raise exception 'El pago supera el importe pendiente.' using errcode='22023'; end if;
  insert into public.class_payment_movements(class_id,amount_cents,note,created_by)
  values(p_class_id,p_amount_cents,nullif(btrim(p_note),''),(select auth.uid()));
  update public.class_financial_accounts
    set paid_cents=paid_cents+p_amount_cents,
        status=case when paid_cents+p_amount_cents>=total_due_cents then 'paid' else 'partial' end,
        updated_at=now()
    where class_id=p_class_id
    returning * into v_account;
  return v_account;
end;
$$;

create table if not exists public.class_video_resources (
  id bigint generated by default as identity primary key,
  class_id bigint not null references public.classes(id) on delete cascade,
  person_id bigint references public.people(id) on delete cascade,
  visibility_scope text not null check (visibility_scope in ('private_student','reusable')),
  provider text not null default 'google_drive' check (provider='google_drive'),
  external_file_id text not null unique check (external_file_id ~ '^[A-Za-z0-9_-]{10,200}$'),
  title text,
  mime_type text check (mime_type is null or mime_type like 'video/%'),
  size_bytes bigint check (size_bytes is null or (size_bytes>0 and size_bytes<=1073741824)),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  check (
    (visibility_scope='private_student' and person_id is not null)
    or (visibility_scope='reusable' and person_id is null)
  )
);

create index if not exists class_video_resources_class_idx on public.class_video_resources(class_id,created_at desc);
create index if not exists class_video_resources_person_idx on public.class_video_resources(person_id,created_at desc) where person_id is not null;
create index if not exists class_video_resources_reusable_idx on public.class_video_resources(created_at desc) where visibility_scope='reusable';

alter table public.class_video_resources enable row level security;
