create or replace function public.register_class_video_resource(
  p_class_id bigint,
  p_person_id bigint default null,
  p_visibility_scope text default 'private_student',
  p_external_file_id text default null,
  p_title text default null,
  p_mime_type text default null,
  p_size_bytes bigint default null,
  p_content_id bigint default null
)
returns public.class_video_resources
language plpgsql
set search_path=''
as $$
declare
  v_resource public.class_video_resources;
  v_content_type text;
  v_sort integer;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para guardar vídeos de clase.' using errcode='42501'; end if;
  if not exists(select 1 from public.classes where id=p_class_id) then raise exception 'La clase no existe.' using errcode='P0002'; end if;
  if p_visibility_scope not in ('private_student','reusable') then raise exception 'Visibilidad de vídeo no válida.' using errcode='22023'; end if;
  if p_external_file_id is null or p_external_file_id !~ '^[A-Za-z0-9_-]{10,200}$' then raise exception 'El archivo de Drive no es válido.' using errcode='22023'; end if;
  if p_mime_type is not null and p_mime_type not like 'video/%' then raise exception 'El recurso debe ser un vídeo.' using errcode='22023'; end if;
  if p_size_bytes is not null and (p_size_bytes<=0 or p_size_bytes>1073741824) then raise exception 'El vídeo debe ser menor de 1 GB.' using errcode='22023'; end if;

  if p_visibility_scope='private_student' then
    if p_person_id is null or not exists(
      select 1 from public.class_participants where class_id=p_class_id and person_id=p_person_id
    ) then raise exception 'Selecciona un alumno de esta clase.' using errcode='22023'; end if;
    if p_content_id is not null then raise exception 'Un vídeo privado no se vincula a contenido general.' using errcode='22023'; end if;
  else
    p_person_id:=null;
  end if;

  if p_content_id is not null then
    select content_type into v_content_type from public.teaching_contents where id=p_content_id and active;
    if not found or v_content_type not in ('correction','explanation','sequence') then
      raise exception 'El vídeo solo puede añadirse como recurso de una corrección, explicación o secuencia.' using errcode='22023';
    end if;
  end if;

  insert into public.class_video_resources(class_id,person_id,visibility_scope,provider,external_file_id,title,mime_type,size_bytes,created_by)
  values(p_class_id,p_person_id,p_visibility_scope,'google_drive',p_external_file_id,nullif(btrim(p_title),''),p_mime_type,p_size_bytes,(select auth.uid()))
  returning * into v_resource;

  if p_content_id is not null then
    select coalesce(max(sort_order),-1)+1 into v_sort from public.teaching_content_media where content_id=p_content_id;
    insert into public.teaching_content_media(
      content_id,media_type,provider,external_file_id,title,mime_type,sort_order,created_by,group_label,is_cover,is_preview,display_in_resources
    ) values(
      p_content_id,'video','google_drive',p_external_file_id,v_resource.title,p_mime_type,v_sort,(select auth.uid()),'Vídeo de clase',false,false,true
    ) on conflict (content_id,provider,external_file_id) do nothing;
  end if;

  return v_resource;
end;
$$;

create or replace function public.can_access_teaching_media(p_external_file_id text)
returns boolean
language plpgsql
stable
set search_path=''
as $$
declare
  v_person bigint;
begin
  if (select private.is_staff()) then
    return exists(
      select 1 from public.teaching_content_media m
      where m.external_file_id=p_external_file_id or m.thumbnail_external_file_id=p_external_file_id
    ) or exists(
      select 1 from public.class_video_resources v where v.external_file_id=p_external_file_id
    );
  end if;

  select private.current_person_id() into v_person;
  if v_person is null or not (select private.has_app_role('student')) then return false; end if;

  if exists(
    select 1 from public.class_video_resources v
    where v.external_file_id=p_external_file_id
      and v.visibility_scope='private_student'
      and v.person_id=v_person
  ) then return true; end if;

  return exists(
    select 1
    from public.teaching_content_media m
    join public.teaching_contents tc on tc.id=m.content_id
    join public.student_content_assignments a on a.content_id=tc.id and a.person_id=v_person
    where (m.external_file_id=p_external_file_id or m.thumbnail_external_file_id=p_external_file_id)
      and tc.active and tc.completion_status='complete' and tc.publication_status='published' and tc.visibility='student'
  );
end;
$$;

create or replace function public.administratively_finish_class_v5(
  p_class_id bigint,
  p_person_ids bigint[],
  p_grant_ids bigint[] default null,
  p_duration_minutes integer default null,
  p_direct_payment_price_cents integer default null,
  p_pair_transfer_source_grant_id bigint default null,
  p_pair_transfer_fee_cents integer default 0,
  p_supplements jsonb default '[]'::jsonb,
  p_paid_now_cents integer default null,
  p_quick_created_grant_id bigint default null
)
returns public.classes
language plpgsql
set search_path=''
as $$
declare
  v_class public.classes;
  v_result public.classes;
  v_account public.class_financial_accounts;
  v_item_total integer:=0;
  v_quick_price integer:=0;
  v_total integer:=0;
  v_paid integer:=0;
  v_direct_grant_id bigint;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para terminar clases.' using errcode='42501'; end if;
  select * into v_class from public.classes where id=p_class_id for update;
  if not found then raise exception 'La clase no existe.' using errcode='P0002'; end if;

  select * into v_account from public.class_financial_accounts where class_id=p_class_id;
  if found then return v_class; end if;

  if p_quick_created_grant_id is not null then
    if not p_quick_created_grant_id=any(coalesce(p_grant_ids,'{}'::bigint[])) then
      raise exception 'El bono rápido no coincide con el bono usado en la clase.' using errcode='22023';
    end if;
    select price_cents into v_quick_price
      from public.credit_grants
      where id=p_quick_created_grant_id and created_by=(select auth.uid());
    if not found then raise exception 'El bono rápido no pertenece a este cierre.' using errcode='22023'; end if;
  end if;

  v_result:=public.administratively_finish_class_v4(
    p_class_id,
    p_person_ids,
    p_grant_ids,
    p_duration_minutes,
    p_direct_payment_price_cents,
    p_pair_transfer_source_grant_id,
    p_pair_transfer_fee_cents,
    p_supplements
  );

  select coalesce(sum(amount_cents),0)::integer into v_item_total
    from public.class_financial_items where class_id=p_class_id;

  v_total:=v_item_total+coalesce(p_direct_payment_price_cents,0)+coalesce(v_quick_price,0);
  v_paid:=coalesce(p_paid_now_cents,v_total);
  if v_paid<0 or v_paid>v_total then raise exception 'El pago recibido debe estar entre 0 y el total de la clase.' using errcode='22023'; end if;

  insert into public.class_financial_accounts(class_id,total_due_cents,paid_cents,status,created_by)
  values(
    p_class_id,
    v_total,
    v_paid,
    case when v_paid>=v_total then 'paid' when v_paid=0 then 'unpaid' else 'partial' end,
    (select auth.uid())
  ) returning * into v_account;

  if v_paid>0 then
    insert into public.class_payment_movements(class_id,amount_cents,note,created_by)
    values(p_class_id,v_paid,'Pago registrado al terminar la clase',(select auth.uid()));
  end if;

  if p_quick_created_grant_id is not null then
    update public.credit_grants
      set payment_status=case when v_paid>=v_quick_price then 'paid' else 'pending' end,
          updated_at=now()
      where id=p_quick_created_grant_id;
  end if;

  if p_direct_payment_price_cents is not null then
    select min(billing_grant_id) into v_direct_grant_id
      from public.class_participants
      where class_id=p_class_id and billing_grant_id is not null;
    if v_direct_grant_id is not null then
      update public.credit_grants
        set payment_status=case when v_paid>=p_direct_payment_price_cents then 'paid' else 'pending' end,
            updated_at=now()
        where id=v_direct_grant_id;
    end if;
  end if;

  insert into public.audit_events(event_type,entity_type,entity_id,summary,detail,actor_user_id)
  values(
    'class_payment_status','class',p_class_id::text,'Pago de clase registrado',
    jsonb_build_object('total_due_cents',v_total,'paid_now_cents',v_paid,'outstanding_cents',v_total-v_paid,'status',v_account.status),
    (select auth.uid())
  );

  return v_result;
end;
$$;

