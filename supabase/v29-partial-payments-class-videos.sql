create table if not exists public.class_financial_accounts (
  class_id bigint primary key references public.classes(id) on delete cascade,
  total_due_cents integer not null default 0 check (total_due_cents >= 0),
  paid_cents integer not null default 0 check (paid_cents >= 0),
  outstanding_cents integer generated always as (greatest(total_due_cents-paid_cents,0)) stored,
  status text not null default 'unpaid' check (status in ('paid','partial','unpaid')),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (paid_cents <= total_due_cents)
);

create table if not exists public.class_payment_movements (
  id bigint generated by default as identity primary key,
  class_id bigint not null references public.class_financial_accounts(class_id) on delete cascade,
  amount_cents integer not null check (amount_cents > 0),
  note text,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists class_payment_movements_class_idx on public.class_payment_movements(class_id,created_at);

alter table public.class_financial_accounts enable row level security;
alter table public.class_payment_movements enable row level security;

