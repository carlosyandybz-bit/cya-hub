select s.id,l.id,l.sort_order,true
from public.catalog_terms s cross join public.catalog_terms l
where s.taxonomy='dance_style' and s.active
  and l.taxonomy='dance_level' and l.active
  and not (s.term_key='bachazouk' and l.term_key='desde_cero')
on conflict(style_term_id,level_term_id) do update set sort_order=excluded.sort_order,active=true,updated_at=now();

delete from public.evaluation_level_contexts c
using public.catalog_terms s, public.catalog_terms l
where c.style_term_id=s.id and c.level_term_id=l.id and s.term_key='bachazouk' and l.term_key='desde_cero';

