-- 14. Bachata/Bachazouk comparten contenido en clases en ambos sentidos, manteniendo identidad del contenido.
create or replace function public.search_class_teaching_content(p_class_id bigint,p_person_id bigint,p_query text default '',p_content_type text default null,p_limit integer default 30)
returns table(content_id bigint,title text,content_type text,description text,correction_guidance text,completion_status text,publication_status text,visibility text,measurement_mode text,ready boolean)
language plpgsql stable set search_path='' as $$
declare v_style_id bigint;v_role_id bigint;v_level_id bigint;v_query text;v_limit integer;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para buscar contenido de clase.' using errcode='42501'; end if;
  if p_content_type is not null and p_content_type not in ('correction','explanation','exercise','sequence') then raise exception 'Tipo de contenido no válido.' using errcode='22023'; end if;
  if length(coalesce(p_query,''))>120 then raise exception 'La búsqueda es demasiado larga.' using errcode='22023'; end if;
  v_limit:=greatest(1,least(coalesce(p_limit,30),50));v_query:=lower(btrim(coalesce(p_query,'')));
  select c.style_term_id,cp.role_term_id,cp.level_term_id into v_style_id,v_role_id,v_level_id from public.classes c join public.class_participants cp on cp.class_id=c.id where c.id=p_class_id and cp.person_id=p_person_id and c.status='active' and c.pedagogy_closed_at is null;
  if not found or v_style_id is null or v_role_id is null or v_level_id is null then raise exception 'Falta estilo, rol o nivel para buscar contenido compatible.' using errcode='22023'; end if;
  return query
  with allowed_styles as (
    select v_style_id id union
    select case when r.parent_style_term_id=v_style_id then r.complement_style_term_id else r.parent_style_term_id end from public.dance_style_relations r where r.active and r.share_class_content and (r.parent_style_term_id=v_style_id or r.complement_style_term_id=v_style_id)
  )
  select t.id,t.title,t.content_type,t.description,t.correction_guidance,t.completion_status,t.publication_status,t.visibility,t.measurement_mode,(t.completion_status='complete' and t.publication_status='published')
  from public.teaching_contents t
  where t.active and (p_content_type is null or t.content_type=p_content_type)
    and exists(select 1 from public.teaching_content_styles s join allowed_styles a on a.id=s.style_term_id where s.content_id=t.id)
    and exists(select 1 from public.teaching_content_roles r where r.content_id=t.id and r.role_term_id=v_role_id)
    and (exists(select 1 from public.teaching_content_levels l where l.content_id=t.id and l.level_term_id=v_level_id) or exists(select 1 from public.teaching_content_styles s join public.dance_style_relations dr on dr.complement_style_term_id=s.style_term_id and dr.active where s.content_id=t.id and dr.parent_style_term_id=v_style_id))
    and (v_query='' or strpos(lower(t.title),v_query)>0 or strpos(lower(coalesce(t.description,'')),v_query)>0 or strpos(lower(coalesce(t.correction_guidance,'')),v_query)>0 or exists(select 1 from public.teaching_content_tags tag where tag.content_id=t.id and strpos(lower(tag.tag),v_query)>0))
  order by case when exists(select 1 from public.student_content_assignments a where a.person_id=p_person_id and a.content_id=t.id) then 0 else 1 end,case when v_query<>'' and lower(t.title)=v_query then 0 when v_query<>'' and left(lower(t.title),length(v_query))=v_query then 1 else 2 end,case when t.completion_status='complete' and t.publication_status='published' then 0 else 1 end,t.updated_at desc,t.id desc limit v_limit;
end $$;

-- 15. Cierre pedagógico exige las revisiones/diagnósticos correspondientes.
create or replace function public.close_class_pedagogy_v2(p_class_id bigint,p_student_message text default null,p_internal_note text default null)
returns public.classes language plpgsql set search_path='' as $$
declare v_class public.classes; missing_count integer;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para cerrar clases.' using errcode='42501'; end if;
  select * into v_class from public.classes where id=p_class_id for update;
  if not found then raise exception 'La clase no existe.' using errcode='P0002'; end if;
  if v_class.status<>'finished' or v_class.administrative_finished_at is null then raise exception 'Termina primero la parte administrativa.' using errcode='22023'; end if;
  select count(*) into missing_count from public.class_evaluation_requirements(p_class_id) r where not r.confirmed;
  if missing_count>0 then raise exception 'Revisa la evaluación de cada alumno antes de cerrar la clase.' using errcode='22023'; end if;
  insert into public.class_pedagogy_summaries(class_id,student_message,internal_note,closed_by,closed_at,updated_at) values(p_class_id,nullif(btrim(p_student_message),''),nullif(btrim(p_internal_note),''),(select auth.uid()),now(),now()) on conflict(class_id) do update set student_message=excluded.student_message,internal_note=excluded.internal_note,closed_by=excluded.closed_by,closed_at=now(),updated_at=now();
  update public.student_content_assignments a set student_visible_at=now() from public.teaching_contents t where t.id=a.content_id and a.person_id in(select person_id from public.class_participants where class_id=p_class_id) and exists(select 1 from public.class_content_events e where e.class_id=p_class_id and e.person_id=a.person_id and e.content_id=a.content_id) and t.active and t.completion_status='complete' and t.publication_status='published' and t.visibility='student' and ((t.content_type='correction' and a.assignment_status='corrected') or (t.content_type in('explanation','sequence') and a.assignment_status='explained'));
  update public.class_content_events e set visible_to_student=true where e.class_id=p_class_id and (e.event_type='reviewed' or e.event_type in('exercise_active','exercise_completed') or (e.event_type='status_changed' and e.new_status in('corrected','explained') and exists(select 1 from public.teaching_contents t where t.id=e.content_id and t.active and t.completion_status='complete' and t.publication_status='published' and t.visibility='student')));
  update public.classes set pedagogy_closed_at=coalesce(pedagogy_closed_at,now()),workflow_stage='closed' where id=p_class_id returning * into v_class;
  return v_class;
end $$;

