-- 9. Sesión de evaluación v3.
create or replace function public.start_evaluation_v3(
  p_person_id bigint,p_style_term_id bigint,p_role_term_id bigint,p_level_term_id bigint,
  p_kind text,p_class_id bigint default null
) returns public.evaluation_sessions
language plpgsql set search_path='' as $$
declare v public.evaluation_sessions;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para evaluar.' using errcode='42501'; end if;
  if p_kind not in ('diagnostic','review','manual','promotion') then raise exception 'Tipo de evaluación no válido.' using errcode='22023'; end if;
  if not exists(select 1 from public.evaluation_level_contexts where style_term_id=p_style_term_id and level_term_id=p_level_term_id and active) then raise exception 'Ese nivel no está disponible para este estilo.' using errcode='22023'; end if;
  if p_class_id is not null and not exists(select 1 from public.class_participants cp where cp.class_id=p_class_id and cp.person_id=p_person_id) then raise exception 'El alumno no pertenece a esta clase.' using errcode='22023'; end if;
  select * into v from public.evaluation_sessions where person_id=p_person_id and class_id is not distinct from p_class_id and style_term_id=p_style_term_id and role_term_id=p_role_term_id and level_term_id=p_level_term_id and evaluation_kind=p_kind and status='draft' order by id desc limit 1;
  if found then return v; end if;
  insert into public.evaluation_sessions(person_id,class_id,style_term_id,role_term_id,level_term_id,evaluation_kind,status,evaluated_by)
  values(p_person_id,p_class_id,p_style_term_id,p_role_term_id,p_level_term_id,p_kind,'draft',(select auth.uid())) returning * into v;
  return v;
end $$;

create or replace function public.save_evaluation_answer(p_session_id bigint,p_question_id bigint,p_option_id bigint)
returns public.evaluation_answers language plpgsql set search_path='' as $$
declare s public.evaluation_sessions; q public.evaluation_questions; o public.evaluation_question_options; m public.evaluation_milestones; a public.evaluation_answers; e public.student_evaluations;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para evaluar.' using errcode='42501'; end if;
  select * into s from public.evaluation_sessions where id=p_session_id for update;
  if not found or s.status<>'draft' then raise exception 'La evaluación no está abierta.' using errcode='22023'; end if;
  select * into q from public.evaluation_questions where id=p_question_id and active;
  select * into o from public.evaluation_question_options where id=p_option_id and question_id=p_question_id and active;
  if q.id is null or o.id is null then raise exception 'Pregunta o respuesta no válida.' using errcode='22023'; end if;
  if q.style_term_id<>s.style_term_id or q.role_term_id<>s.role_term_id or q.level_term_id<>s.level_term_id then raise exception 'La pregunta no corresponde a esta evaluación.' using errcode='22023'; end if;
  select * into m from public.evaluation_milestones where id=o.milestone_id and active;
  if m.id is null or m.aptitude_term_id<>q.aptitude_term_id then raise exception 'El hito no corresponde a la pregunta.' using errcode='22023'; end if;
  insert into public.evaluation_answers(session_id,question_id,option_id,aptitude_term_id,milestone_id,question_snapshot,answer_snapshot,milestone_snapshot,score_snapshot,answered_by)
  values(s.id,q.id,o.id,q.aptitude_term_id,m.id,q.prompt,o.label,m.label,m.score,(select auth.uid()))
  on conflict(session_id,question_id) do update set option_id=excluded.option_id,milestone_id=excluded.milestone_id,answer_snapshot=excluded.answer_snapshot,milestone_snapshot=excluded.milestone_snapshot,score_snapshot=excluded.score_snapshot,answered_by=excluded.answered_by,answered_at=now()
  returning * into a;
  insert into public.student_evaluations(session_id,person_id,class_id,style_term_id,role_term_id,level_term_id,aptitude_term_id,evaluation_kind,score,note,evaluated_by)
  values(s.id,s.person_id,s.class_id,s.style_term_id,s.role_term_id,s.level_term_id,q.aptitude_term_id,s.evaluation_kind,m.score,m.label,(select auth.uid()))
  on conflict(session_id,aptitude_term_id) where session_id is not null do update set score=excluded.score,note=excluded.note,evaluated_by=excluded.evaluated_by,updated_at=now()
  returning * into e;
  insert into public.student_evaluation_state(person_id,style_term_id,role_term_id,level_term_id,aptitude_term_id,milestone_id,score,milestone_label,source_session_id,updated_by)
  values(s.person_id,s.style_term_id,s.role_term_id,s.level_term_id,q.aptitude_term_id,m.id,m.score,m.label,s.id,(select auth.uid()))
  on conflict(person_id,style_term_id,role_term_id,level_term_id,aptitude_term_id) do update set milestone_id=excluded.milestone_id,score=excluded.score,milestone_label=excluded.milestone_label,source_session_id=excluded.source_session_id,updated_by=excluded.updated_by,updated_at=now();
  update public.evaluation_sessions set updated_at=now() where id=s.id;
  return a;
end $$;

