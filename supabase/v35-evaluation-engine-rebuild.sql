  on conflict(person_id,content_id) do nothing;
  get diagnostics n=row_count;
  return n;
end $$;

-- 12. Requisitos de promoción y decisión humana.
create or replace function public.evaluation_promotion_status(p_person_id bigint,p_style_term_id bigint,p_role_term_id bigint,p_level_term_id bigint)
returns jsonb language sql stable set search_path='' as $$
with scores as (
  select coalesce(sum(s.score),0)::numeric earned,
         coalesce(sum(mx.max_score),0)::numeric possible
  from public.student_evaluation_state s
  join lateral (select max(m.score)::numeric max_score from public.evaluation_milestones m where m.style_term_id=s.style_term_id and m.role_term_id=s.role_term_id and m.level_term_id=s.level_term_id and m.aptitude_term_id=s.aptitude_term_id and m.active) mx on true
  where s.person_id=p_person_id and s.style_term_id=p_style_term_id and s.role_term_id=p_role_term_id and s.level_term_id=p_level_term_id
), req as (
  select count(*) total,count(*) filter(where exists(select 1 from public.student_explanation_attainments a where a.person_id=p_person_id and a.content_id=r.content_id)) done
  from public.required_level_explanations r where r.style_term_id=p_style_term_id and r.role_term_id=p_role_term_id and r.level_term_id=p_level_term_id and r.active
)
select jsonb_build_object('earned',scores.earned,'possible',scores.possible,'percentage',case when scores.possible>0 then round(scores.earned*100/scores.possible,1) else 0 end,'score_ready',scores.possible>0 and scores.earned*2>=scores.possible,'required_total',req.total,'required_done',req.done,'content_ready',req.total=req.done,'ready',scores.possible>0 and scores.earned*2>=scores.possible and req.total=req.done) from scores,req;
$$;

create or replace function public.promote_student_level(p_person_id bigint,p_style_term_id bigint,p_role_term_id bigint,p_keep boolean default false,p_reason text default null)
returns public.level_promotion_decisions language plpgsql set search_path='' as $$
declare dp public.student_dance_profiles; next_level bigint; st jsonb; d public.level_promotion_decisions;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para decidir promociones.' using errcode='42501'; end if;
  select * into dp from public.student_dance_profiles where person_id=p_person_id and style_term_id=p_style_term_id and role_term_id=p_role_term_id and active order by is_primary desc,id limit 1 for update;
  if dp.id is null or dp.level_term_id is null then raise exception 'No existe un nivel actual.' using errcode='22023'; end if;
  st:=public.evaluation_promotion_status(p_person_id,p_style_term_id,p_role_term_id,dp.level_term_id);
  if not coalesce((st->>'ready')::boolean,false) and not p_keep then raise exception 'Todavía no cumple puntuación y contenido obligatorio.' using errcode='22023'; end if;
  select c2.level_term_id into next_level from public.evaluation_level_contexts c1 join public.evaluation_level_contexts c2 on c2.style_term_id=c1.style_term_id and c2.active and c2.sort_order>c1.sort_order where c1.style_term_id=p_style_term_id and c1.level_term_id=dp.level_term_id and c1.active order by c2.sort_order limit 1;
  insert into public.level_promotion_decisions(person_id,style_term_id,role_term_id,from_level_term_id,to_level_term_id,decision,reason,decided_by)
  values(p_person_id,p_style_term_id,p_role_term_id,dp.level_term_id,next_level,case when p_keep then 'kept' else 'promoted' end,nullif(btrim(coalesce(p_reason,'')),''),(select auth.uid())) returning * into d;
  if not p_keep then
    if next_level is null then raise exception 'Ya está en el último nivel disponible.' using errcode='22023'; end if;
    update public.student_dance_profiles set level_term_id=next_level,updated_at=now() where id=dp.id;
  end if;
  return d;
end $$;

-- 13. Activación Bachazouk según respuesta del profesor.
create or replace function public.resolve_complement_track(
  p_person_id bigint,p_parent_style_term_id bigint,p_role_term_id bigint,p_answer text,p_class_id bigint default null
) returns jsonb language plpgsql set search_path='' as $$
declare r public.dance_style_relations; lvl bigint; dp_id bigint;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para modificar recorridos.' using errcode='42501'; end if;
  select * into r from public.dance_style_relations where parent_style_term_id=p_parent_style_term_id and active order by id limit 1;
  if r.id is null then return jsonb_build_object('active',false,'reason','no_complement'); end if;
  if p_answer='knows' then return jsonb_build_object('active',false,'needs_diagnostic',true,'style_term_id',r.complement_style_term_id); end if;
  if p_answer='wants_to_learn' then
    select c.level_term_id into lvl from public.evaluation_level_contexts c where c.style_term_id=r.complement_style_term_id and c.active order by c.sort_order,c.id limit 1;
    insert into public.student_dance_profiles(person_id,style_term_id,role_term_id,level_term_id,is_primary,active)
    values(p_person_id,r.complement_style_term_id,p_role_term_id,lvl,false,true)
    on conflict do nothing returning id into dp_id;
    return jsonb_build_object('active',true,'needs_diagnostic',false,'style_term_id',r.complement_style_term_id,'level_term_id',lvl);
  end if;
  return jsonb_build_object('active',false,'needs_diagnostic',false,'style_term_id',r.complement_style_term_id);
end $$;

-- Primera explicación del complemento activa el recorrido en su primer nivel si aún no existe.
create or replace function private.activate_complement_on_first_explanation()
returns trigger language plpgsql set search_path='' as $$
declare comp_style bigint; parent_style bigint; lvl bigint; role_id bigint;
begin
  if new.attainment_kind<>'explained' then return new; end if;
  select s.style_term_id into comp_style from public.teaching_content_styles s join public.dance_style_relations r on r.complement_style_term_id=s.style_term_id and r.active where s.content_id=new.content_id limit 1;
  if comp_style is null then return new; end if;
  select cp.role_term_id into role_id from public.class_participants cp where cp.class_id=new.source_class_id and cp.person_id=new.person_id;
  if role_id is null then return new; end if;
  if not exists(select 1 from public.student_dance_profiles where person_id=new.person_id and style_term_id=comp_style and role_term_id=role_id and active) then
    select level_term_id into lvl from public.evaluation_level_contexts where style_term_id=comp_style and active order by sort_order,id limit 1;
    insert into public.student_dance_profiles(person_id,style_term_id,role_term_id,level_term_id,is_primary,active) values(new.person_id,comp_style,role_id,lvl,false,true);
  end if;
  return new;
end $$;
