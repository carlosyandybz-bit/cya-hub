create or replace function public.mark_explanation_learned_by_derivation(p_person_id bigint,p_content_id bigint,p_session_id bigint default null)
returns integer language plpgsql set search_path='' as $$
declare n integer;
begin
  if not (select private.is_staff()) then raise exception 'No tienes permiso para acreditar contenido.' using errcode='42501'; end if;
  with recursive path(content_id) as (
    select p_content_id
    union
    select r.source_content_id from public.teaching_content_relations r join path p on p.content_id=r.target_content_id where r.relation_type in ('prerequisite','required_before')
  ), eligible as (
    select distinct p.content_id from path p join public.teaching_contents t on t.id=p.content_id and t.content_type='explanation'
    where p.content_id=p_content_id or exists(select 1 from public.required_level_explanations re where re.content_id=p.content_id and re.active)
  )
